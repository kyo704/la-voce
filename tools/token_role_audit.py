def こめんとを外す(t):
  """★戒めの 文を 数えない ため、★コメントを 外します。

    ★★行を 先に、★ブロックを あとに（★`components/tests/_source.js` と 同じ 順）。
  """
  # ★★★行の 数を 変えません（★2026-09-18・ここで 行番号が ずれました）。
  #   ★★はじめ、★ブロックの コメントを 丸ごと 消して いました。
  #   ★★その ぶん 行が 詰まり、★出した 行番号が 別の 行を 指しました。
  #   ★★★指す 先の ちがう 行番号は、★無い より 悪い です。
  #   ★★だから、★中身だけ 消して 改行は 残します。
  def 改行だけ残す(m):
    return "\n" * m.group(0).count("\n")

  # ★★★`^\s*` は 使いません（★2026-09-18・ここで 1行 消えました）。
  #   ★★`\s` は 改行も 含みます。★行の 頭から 前の 改行まで 呑み込み、
  #     ★★空文字に 置き換えた とき、★行が 1本 減ります。
  #   ★★空白と タブ だけ に します。
  t = re.sub(r"^[ \t]*//.*$", "", t, flags=re.M)
  t = re.sub(r"\{/\*[\s\S]*?\*/\}", 改行だけ残す, t)
  return re.sub(r"/\*[\s\S]*?\*/", 改行だけ残す, t)


