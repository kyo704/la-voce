#     ★★`color: allowed ? C.ink : C.inkFaint` を 拾えません でした。
#     ★★★`inkFaint` が「字に 0回」と 出ました。★実際は 3か所 で 字 です。
#     ★★★見つからない 道具は、★「無い」と 言っては いけません。
#   ★★いまは、★`C.x` が 出て くる **その ところ** の 手前を 見て、
#     ★★`color:` か `background`／`border` かで 分けます。
役 = {}
for k in 色:
  役[k] = {"字": 0, "地": 0, "線": 0}


def 役を見る(一行, k):
  """★1行の 中の `C.k` を、★字・地・線に 分けて 数えます。"""
  出 = {"字": 0, "地": 0, "線": 0}
  for m in re.finditer(r"C\.%s\b" % k, 一行):
    直前 = 一行[:m.start()].rsplit(",", 1)[-1]
    if re.search(r"background(?:Color)?\s*:", 直前):
      出["地"] += 1
    elif re.search(r"border[A-Za-z]*\s*:", 直前):
      出["線"] += 1
    elif re.search(r"\bcolor\s*:", 直前):
      出["字"] += 1
  return 出


# ★★★較正 ── ★わざと「分けにくい 1件」を 作って、★字として 数えられる こと。
#   ★★きょう、★この 形（三項）を 見落として、★`inkFaint` を「字に 0回」と 出しました。
