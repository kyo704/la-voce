def 明るさ(hexv):
  h = str(hexv).lstrip("#")
  if len(h) == 3:
    h = "".join(c * 2 for c in h)
  v = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
  v = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in v]
  return 0.2126 * v[0] + 0.7152 * v[1] + 0.0722 * v[2]


def 比(a, b):
  x, y = 明るさ(a), 明るさ(b)
  return (max(x, y) + 0.05) / (min(x, y) + 0.05)


