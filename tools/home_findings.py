# -*- coding: utf-8 -*-
"""★ホームの 調べ ── ★書いた もの が、★描かれて いるか（★N-1 の 決まり）

  ★★★「書き込んで いる 値は、★必ず どこかで 読まれて いるか」
    ★★「作った 関数は、★必ず どこかから 呼ばれて いるか」

  ★★★この 1本が 数え、★この 1本が 覚え書きを 書きます。
    ★★手で 書いた 文を 混ぜません。

  ★★較正 ── ★必ず 描かれて いる 節（`nagare`）で、★見つかる ことを 確かめます。
"""

import io, os, re, sys, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def 読む(みち):
  p = os.path.join(ROOT, みち)
  if not os.path.exists(p):
    print("★止まりました ── ありません: " + みち)
    sys.exit(2)
  return io.open(p, encoding="utf-8").read()


def 註を外す(s):
  s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
  return "\n".join(l for l in s.split("\n") if not re.match(r"^\s*//", l))


節もと = 読む("lib/opsHomeSections.js")
画面 = 註を外す(読む("components/OpsHome.jsx"))
殻 = 註を外す(読む("components/VocalTracker.jsx"))

# ---------------------------------------------------------------------------
# 【一】★節 ── ★出すと 決めて いる のに、★描いて いない もの
# ---------------------------------------------------------------------------
節 = re.findall(r'\{\s*key:\s*"(\w+)",\s*label:\s*"([^"]+)"', 節もと)
if not 節:
  print("★止まりました ── 節を 1つも 読めません")
  sys.exit(2)
描く = set(re.findall(r'出す\("(\w+)"\)', 画面))
if "nagare" not in 描く:
  print("★止まりました ── 較正が 合いません（`nagare` は 必ず 描かれます）")
  sys.exit(2)
描かれない = [(k, l) for k, l in 節 if k not in 描く]

# ---------------------------------------------------------------------------
# 【二】★関数 ── ★作った のに、★どこからも 呼ばれて いない もの
# ---------------------------------------------------------------------------
出した = re.findall(r"export function (\w+)", 節もと)
呼び先 = 画面 + 殻
使わない = [f for f in 出した if not re.search(r"\b%s\(" % f, 呼び先)]

# ---------------------------------------------------------------------------
# 【二の二】★数の 札 ── ★できことを 見て いるか
# ---------------------------------------------------------------------------
#   ★★★見本の 数の 札は、★役職で 枚数が 変わります（4／3／2）。
#     ★★実装は いつも 同じ 枚数 です。
札 = re.findall(r"<Stat label=\"([^\"]+)\"", 画面)
札の数 = len(札)
if 札の数 == 0:
  print("★止まりました ── 数の 札を 1つも 読めません")
  sys.exit(2)
札の門 = len(re.findall(r'出す\("\w+"\)\s*&&\s*<Stat', 画面))

# ---------------------------------------------------------------------------
# 【三】★役職の 名で 数えて いる ところ
# ---------------------------------------------------------------------------
役名 = re.findall(r"const (SCHEDULE_ROLES) = (\[[^\]]*\])", 殻)
役名使い = len(re.findall(r"SCHEDULE_ROLES", 殻))

今日 = datetime.date.today().isoformat()
出 = os.path.join(ROOT, "docs", "reports", "%s-ホームの調べ.md" % 今日)

行 = []
行.append("# ★ホームの 調べ ── ★書いた ものが 描かれて いるか")
行.append("")
行.append("★%s ／ ★`tools/home_findings.py` が 書きました。" % 今日)
行.append("★（★丈は 下に あります）")
行.append("")
行.append("## ★① 節 ── ★出すと 決めて いる %d のうち、★描いて いるのは %d"
          % (len(節), len(描く)))
行.append("")
行.append("| 節 | 名 | 描いて いるか |")
行.append("|---|---|---|")
for k, l in 節:
  行.append("| `%s` | %s | %s |" % (k, l, "○" if k in 描く else "★ない"))
行.append("")
if 描かれない:
  行.append("★★★描かれない 節 …… **%d**" % len(描かれない))
  for k, l in 描かれない:
    行.append("- `%s`（%s）" % (k, l))
  行.append("")
  行.append("★★`homeSections(perms)` は これらを 返します。★画面が 使いません。")
  行.append("")
  行.append("★★★たとえば、★`bill` だけ を 持つ 役職 ──")
  行.append("★★`節の数` は 1 なので、★訳の 1行（`EMPTY_LINE`）は 出ません。")
  行.append("★★けれど `bill` を 描く ところが ないので、★節も 出ません。")
  行.append("★★★出るのは 数の 札 %d枚 だけ です。" % 札の数)
  行.append("")
  行.append("★★その 数の 札は、★できことを 見て いません（★下の ④）。")
else:
  行.append("★★すべて 描かれて います。")
行.append("")
行.append("## ★② 関数 ── ★作った %d のうち、★呼ばれて いないのは %d"
          % (len(出した), len(使わない)))
行.append("")
for f in 出した:
  行.append("- `%s` …… %s" % (f, "★呼ばれて いません" if f in 使わない else "○"))
行.append("")
if 使わない:
  行.append("★★★裁定 その79 は「出欠を 持つ のに、★どこからも 行けない 方」の")
  行.append("★★逃げ道を 決めて います。★その 判じは 書いて ありますが、★呼ばれて いません。")
行.append("")
行.append("## ★④ 数の 札 ── ★%d枚。★できことの 門 …… %d" % (札の数, 札の門))
行.append("")
for x in 札:
  行.append("- %s" % x)
行.append("")
行.append("★★見本は 役職で 枚数が 変わります ── ★学長 4枚 ／ 先生 3枚 ／ 職員 2枚。")
行.append("★★★実装は いつも %d枚 です。" % 札の数)
行.append("★★「名簿の 人数」は、★名簿の できこと（`meibo`）を 見ずに 出して います。")
行.append("")
行.append("## ★③ 役職の 名で 数えて いる ところ")
行.append("")
for 名, 中 in 役名:
  行.append("- `%s` = `%s` …… %d か所で 使って います" % (名, 中, 役名使い))
行.append("")
行.append("★★ホームの「先生」の 数 です。★できことでは なく、★役職の 名で 数えて います。")
行.append("★★★台帳 08-1（A2）と 同じ 形 です。★新しい 預けを 作りません。")
行.append("")
行.append("## ★見た目")
行.append("")
行.append("★この 道具は **字** を 見ます。★描かれた 姿を 見て いません。")
行.append("★★`VISUAL: UNVERIFIED` です。")

本文 = "\n".join(行) + "\n"
丈 = len(本文.splitlines())
本文 = 本文.replace("★（★丈は 下に あります）",
                   "★全%d行 ／ 末尾は「%s」" % (丈, 行[-1]), 1)
io.open(出, "w", encoding="utf-8").write(本文)
print(出)
print("節 %d（描く %d ／ 描かない %d）／ 関数 %d（呼ばれない %d）"
      % (len(節), len(描く), len(描かれない), len(出した), len(使わない)))
