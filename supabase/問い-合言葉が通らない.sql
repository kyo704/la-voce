-- ---------------------------------------------------------------------------
-- 【〇】★★いちばん 疑わしい こと ── ★合言葉が **2種類** あります
--
--   ★★`teacher_invitations` … ★先生が **生徒**を 招く
--     ★★出る ところ … ★レッスン → 教える → 「生徒を招待する（テスト機能）」
