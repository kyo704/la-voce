-- ---------------------------------------------------------------------------
-- 【一】★★塩（pepper）が 入って いるか ── ★いちばん 疑わしい ところ
--
--   ★★`get_invitation_teacher` は、★塩が 無い か 20文字 未満の とき、
--     ★★**何も せずに null を 返します**。★画面には「入れませんでした」と 出ます。
--     ★★合言葉が 正しくても、★同じ 字が 出ます。
--
--   ★★★Vercel の `CODE_ATTEMPT_PEPPER` は、★この 関数と 関わりが ありません。
--     ★★関数が 読むのは `public.app_secrets` の 行 だけ です。
--     ★★（★アプリ側の `lib/codeAttempts.js` は、★いま どこからも 呼ばれて いません。）
--
--   ★★★中身は 出しません。★長さ と 形 だけ を 見ます。
-- ---------------------------------------------------------------------------
select name as 名,
       length(value) as 文字数,
       (length(value) >= 20) as 関数が受けつける長さか,
       (value ~ '^[◯○oO\s]+$') as まだ置き字のままか
from public.app_secrets
where name = 'code_pepper';

-- ★行が 1つも 返らなければ、★塩が **入って いません**。★それが 原因 です。

-- ---------------------------------------------------------------------------
-- 【二】★発行した 合言葉が、★使える 形で 入って いるか
--
--   ★★合言葉そのものは 出しません。★頭の 2文字と 長さ だけ。
-- ---------------------------------------------------------------------------
select left(code, 2) || repeat('・', greatest(length(code) - 2, 0)) as 合言葉の形,
       length(code) as 文字数,
       (code = upper(trim(code))) as 大文字で入っているか,
       org_id is not null as 教室が入っているか,
       used_at is null as まだ使われていないか,
       expires_at > now() as 期限内か,
       created_at
from public.teacher_invitations
order by created_at desc
limit 5;

-- ---------------------------------------------------------------------------
-- 【三】★★同じ 合言葉が、★別の 表に 入って いないか
--
--   ★★入り口が 2つ あります ──
--     ★`teacher_invitations` … ★先生が **生徒**を 招く（★合言葉の 道）
--     ★`org_invitations`     … ★学校が **先生**を 招く（★別の 道）
--   ★★「もっと → 教室 → 招待コード」で 出るのが どちらかで、
--     ★★正しい 8文字でも 通らない ことが あります。
-- ---------------------------------------------------------------------------
select 'teacher_invitations' as 表, count(*) as 行数,
       count(*) filter (where used_at is null and expires_at > now()) as いま使えるもの
from public.teacher_invitations
union all
select 'org_invitations', count(*),
       count(*) filter (where used_at is null and expires_at > now())
from public.org_invitations;

-- ---------------------------------------------------------------------------
-- 【四】★★止められて いないか（★10回／24時間）
--
--   ★★合言葉そのものは 残して いません。★ハッシュ だけ です。
--   ★★ここでは 全体の 数を 見ます。★10に 近ければ、★止まって いる 見込みが あります。
-- ---------------------------------------------------------------------------
select count(*) as この24時間の試し,
       count(distinct code_hash) as 別々の合言葉の数,
       max(at) as いちばん新しい試し
from public.code_attempts
where at > now() - interval '24 hours';

-- ★合言葉ごとの 数（★多い 順に 5つ）。★ハッシュは 頭だけ 出します。
select left(code_hash, 8) || '…' as ハッシュの頭,
       count(*) as 試した回数,
       (count(*) >= 10) as 止まっているか
from public.code_attempts
where at > now() - interval '24 hours'
group by code_hash
order by count(*) desc
limit 5;

