-- ============================================================================
-- 名簿に「学年」の 欄を 足します（★G07 の 絞り込み）
--
--   ★出どころ 新しい 動く見本 `SH['shiboru']`（★2026-09-11）
--     「状態 ／ 学年 ／ 先生」の 3つで 絞ります。
--            docs/opus/引き継ぎ-最終稿として作るときの注意（9月10日）.md §3
--
--   ★★なぜ 要るか。
--     いまの memberships に、学年の 欄が ありません。
--     画面は 作りましたが、★1人も 学年を 持っていないので、
--     ★札が 1枚も 出ません（★押せない 札を 出さない ように してあります）。
--
--   ★★なぜ 1年〜4年の 決め打ちに しないか。
--     見本の「学校の 形」に、こう あります。
--       「学部・学科・★学年・事務の分野を 足す・消す（修士・博士・研究生・本科…）」
--     ★学年は 学校が 決める ものです。★4つとは 限りません。
--     ★★だから 文字の 欄です。★選択肢を こちらで 決めません。
--
--   ★★埋め戻しません。
--     いま 名簿に いる 方は、★ぜんぶ null の ままです。
--     ★分からない ものを、こちらで 決めません。
--     ★★「学年を 入れていない」と「1年です」は、別の ことです。
--
--   ★★何度 流しても 安全です。
-- ============================================================================


-- ----------------------------------------------------------------------------
-- §0 いまの ようす（★読むだけ）
-- ----------------------------------------------------------------------------
select
  '実行前' as いつ,
  (select count(*) from information_schema.columns
     where table_schema = 'public' and table_name = 'memberships'
       and column_name = 'grade_label') as 学年の欄,
  (select count(*) from public.memberships) as 名簿の行;


-- ----------------------------------------------------------------------------
-- §1 欄を 足す
-- ----------------------------------------------------------------------------
alter table public.memberships
  add column if not exists grade_label text;

comment on column public.memberships.grade_label is
  '学年・コース（例：声楽3年／修士2年／研究生）。学校が決める文字。既定は null。';

-- ★★長さの 上限だけ 掛けます。★中身は 決めません。
--   ★★書き間違いで 長い 文が 入るのを 止めるだけです。
do $$
begin
  if not exists (
    select 1 from pg_constraint
     where conname = 'memberships_grade_label_len'
  ) then
    alter table public.memberships
      add constraint memberships_grade_label_len
      check (grade_label is null or char_length(grade_label) <= 40);
  end if;
end $$;


-- ----------------------------------------------------------------------------
-- §2 引きやすく する
--    ★学年で 絞るのは、★その 学校の 中だけです。
-- ----------------------------------------------------------------------------
create index if not exists memberships_org_grade_idx
  on public.memberships (org_id, grade_label)
  where grade_label is not null;


-- ----------------------------------------------------------------------------
-- §3 権限について
--
--   ★★新しい 面（ポリシー）を 作りません。
--     memberships には もう 面が あります。★欄が 1つ 増えるだけです。
--   ★★学年は、★健康の ことでは ありません。
--     ★先生に 見せない 11列（lib/shareScope.js）には 入れません。
-- ----------------------------------------------------------------------------
-- （ここには 何も 書きません。それが 決めです。）


-- ----------------------------------------------------------------------------
-- §4 確かめ（★読むだけ）
-- ----------------------------------------------------------------------------
select
  '実行後' as いつ,
  (select count(*) from information_schema.columns
     where table_schema = 'public' and table_name = 'memberships'
       and column_name = 'grade_label') as 学年の欄,
  (select count(*) from public.memberships where grade_label is not null) as 学年が入っている行;

