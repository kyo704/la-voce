select column_name as "列", data_type as "型", is_nullable as "null を許すか"
  from information_schema.columns
 where table_schema = 'public' and table_name = 'profiles'
   and column_name in ('is_under_18', 'age_question_shown_at', 'age_band', 'age_band_answered_at')
 order by 1;

-- ---------------------------------------------------------------------------
-- ① 列を足します
--
--   ★null が「まだ答えていない」です。
--   ★★埋め戻しません。★1行も UPDATE しません。
--     ★いまいる方は、全員 null から始まります。
--     ★必要になったとき（連携・有料）に、そのとき聞きます。
-- ---------------------------------------------------------------------------
alter table public.profiles
  add column if not exists age_band text,
  add column if not exists age_band_answered_at timestamptz;

comment on column public.profiles.age_band is
  '年齢の帯。under15 / teen / adult。★null は「まだ答えていない」。'
  '★is_under_18 とは別の答え。★移し替えないこと。'
  '★生年月日は取らない。';

-- ---------------------------------------------------------------------------
-- ② 値の形
--
--   ★unknownMinor は★保存しません。★答えではなく、「分からない」だからです。
--     ★分からないことは、★列に書かず、★読むときに決めます。
-- ---------------------------------------------------------------------------
do $$
begin
  if not exists (select 1 from pg_constraint
                  where conname = 'age_band_values'
                    and conrelid = 'public.profiles'::regclass) then
    alter table public.profiles
      add constraint age_band_values check (
        age_band is null or age_band in ('under15', 'teen', 'adult')
      );
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- ③ 書ける人
--
--   ★profiles の UPDATE は、本人の行だけです（既存のポリシー）。
--   ★★年齢の変更を、止めません（追補 §2.2）。
--     ★止めると、★正しく直そうとした人まで止まります。
--     ★嘘は見抜けません。★見抜けないことを、設計に織り込みます。
--   ★★変更は、age_answer_changes に残ります（既存の仕組み）。
--     ★止めるのではなく、★記録します。
--
--   ★ここでは、権限もポリシーも★1つも変えません。
--     ★profiles は列ごとの権限にしていません（2026-09-04 時点）。
--     ★★もし列ごとに絞る日が来たら、
--       ★★先に revoke、それから grant の順で書くこと。
--       ★「与えない」は「剥がした」ではありません（2026-09-03 の穴）。
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- ④ 確かめ
-- ---------------------------------------------------------------------------

-- ④-1 列ができていること（2行）
select column_name as "列", data_type as "型", is_nullable as "null を許すか"
  from information_schema.columns
 where table_schema = 'public' and table_name = 'profiles'
   and column_name in ('age_band', 'age_band_answered_at')
 order by 1;

-- ④-2 ★埋め戻していないこと
--     ★答えた人の数だけが出ます。★いま当てた直後なら、0 のはずです。
--     ★★人数を書き残さないこと（2026-09-02 の凍結）。見るだけです。
select age_band as "帯", count(*) as "行数"
  from public.profiles
 group by age_band
 order by 1 nulls first;

