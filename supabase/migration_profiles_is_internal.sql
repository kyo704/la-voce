-- ============================================================================
-- profiles.is_internal ― 「これは試験用の器です」という印（2026-09-03）
--
--   ★なぜ要るか
--     36件のうち、いくつかは動作を試すために作った器です。
--     お知らせの通知先を数えるときに混ざると、★実際より多く見えます。
--     いま人数の根拠になっているのは display_name（ごく一部にしか入っていない）と
--     name（「テスター」の文字は★1件も入っていない）で、どちらも使えません。
--     ★空の列で対象を決めると、黙って誰にも届きません。
--
--   ★どうやって決めるか
--     ここでは1件も true にしません。default false で列を足すだけです。
--     ★1件ずつ、メールアドレスを運営者が目で確かめてから true にします。
--     ★姓の一致では決めません（同姓の別人がいます。2026-09-02 に撤回済み）。
--     ★メールの形（+t1、test を含む等）でも自動では決めません。
--       形が似ているだけの実在の方を、黙って通知先から外すおそれがあります。
--
--   ★この印がしないこと
--     ・削除の対象から外す      … 外しません。本人の記録です。
--     ・控え（バックアップ）から外す … 外しません。
--     ・書き出しから外す        … 外しません（lib/exportData.js に載せました）。
--     ★外すのは「お知らせを何人に出すか」の数だけです。
--
--   ★読む側（共通ゲート E：書いた値は、どこかで読まれているか）
--     lib/noticeAudience.js の noticeGroupOf / shouldNotify / notifiableProfiles
--     が、この列を読みます。★列と同じ日に書きました。
--
--   ★何度実行しても同じ結果になります。既存の値は書き換えません。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- ① 列を足す
--
--   ★not null default false にします。null を作りません。
--     「まだ決めていない」と「試験用ではない」を分ける必要がないからです。
--     ★通知の判定では、迷ったら「送る」ほうに倒れます（false 側）。
--     送りすぎは謝れますが、届かなかったことには誰も気づけません。
-- ---------------------------------------------------------------------------
alter table public.profiles
  add column if not exists is_internal boolean not null default false;

comment on column public.profiles.is_internal is
  '運営が動作確認のために作った器なら true。お知らせの人数から外すためだけに使う。削除・控え・書き出しからは外さない。1件ずつメールアドレスを確かめて手で立てる。';

-- ---------------------------------------------------------------------------
-- ② 足りたことを確かめる
-- ---------------------------------------------------------------------------
select column_name as "列", data_type as "型",
       is_nullable as "null可", column_default as "既定値"
  from information_schema.columns
 where table_schema = 'public' and table_name = 'profiles'
   and column_name = 'is_internal';

-- ★この時点では、全員 false のはずです。
select is_internal as "試験用か", count(*) as "人数"
  from public.profiles group by 1 order by 1;

-- ---------------------------------------------------------------------------
-- ③ ★印をつける候補を、目で見るための一覧
--
--   ★この照会は、何も書き換えません。見るだけです。
--   ★ここに出たからといって、試験用とは限りません。
--     必ず1件ずつ、心当たりのあるものだけを④で立ててください。
-- ---------------------------------------------------------------------------
select p.id, u.email as "メール", p.name as "名前", p.display_name as "表示名",
       p.cohort as "群", p.consent_health_data_at as "同意した日時",
       p.onboarding_completed as "登録を終えたか", p.created_at as "作った日時"
  from public.profiles p
  join auth.users u on u.id = p.id
 order by p.created_at;

-- ---------------------------------------------------------------------------
-- ④ 印をつける（★確かめたメールアドレスだけを、ここに書いてください）
--
--   ★下は、そのままでは何もしません。'' の行は誰にも当たりません。
--     確かめたぶんだけ、アドレスを1行ずつ足してから実行してください。
--   ★実行のたびに、更新した件数が出ます。
--     ★0件だったら、アドレスが1つも当たっていません。
--       「エラーが出なかった＝できた」ではありません。
--       PostgREST でも SQL でも、0件の更新はエラーになりません。
-- ---------------------------------------------------------------------------
with 確かめたもの as (
  select unnest(array[
    ''                       -- ← ここにメールアドレスを1つずつ足す
  ]) as email
),
更新 as (
  update public.profiles p
     set is_internal = true
    from auth.users u
   where u.id = p.id
     and u.email in (select email from 確かめたもの where email <> '')
  returning p.id
)
select count(*) as "★印をつけた件数（0なら1件も当たっていません）" from 更新;

-- ---------------------------------------------------------------------------
-- ⑤ 結果
--
--   ★内訳で確かめます。合計が合うことは、内訳が合っている証拠になりません
--     （2026-09-02 の裁定）。
-- ---------------------------------------------------------------------------
select p.is_internal as "試験用か", p.cohort as "群", count(*) as "人数"
  from public.profiles p group by 1, 2 order by 1, 2;

-- ★お知らせを出す相手（試験用を除く）を、1件ずつ並べます。
select u.email as "メール", p.cohort as "群",
       case
         when p.is_internal then '★出しません（試験用）'
         when p.cohort = 'founder' then '① 運営者'
         when p.cohort = 'tester'  then '② テスター'
         else '③ そのほかの方'
       end as "配信の段"
  from public.profiles p
  join auth.users u on u.id = p.id
 order by 3, 1;
