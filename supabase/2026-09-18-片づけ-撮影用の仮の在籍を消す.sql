-- ---------------------------------------------------------------------------
-- 【一】★消す 前に 数える ── ★これだけ 先に 走らせて ください
--
--   ★★出る 数が **6** なら、★【二】へ 進んで ください。
--   ★★6 で ない なら、★止まって、★この 紙を お戻し ください。
-- ---------------------------------------------------------------------------
select count(*) as 消える数
from public.enrollments e
join public.organizations o on o.id = e.org_id
where o.name like '%はじめの1人テスト%'
  and e.status = 'active'
  and e.enrolled_at >= date '2026-09-18'
  and e.enrolled_at <  date '2026-09-19';

-- ---------------------------------------------------------------------------
-- 【二】★消す
--
--   ★★★教室を 名で 絞って います。★`org_id` を 書き写しません。
--     ★書き写すと、★写し違いが そのまま 別の 教室に 当たります。
--   ★★日で 絞って います。★きょう 入れた ものだけ です。
--     ★★もとから あった 行（★status = 'left' の 1件）は 残ります。
-- ---------------------------------------------------------------------------
delete from public.enrollments e
using public.organizations o
where o.id = e.org_id
  and o.name like '%はじめの1人テスト%'
  and e.status = 'active'
  and e.enrolled_at >= date '2026-09-18'
  and e.enrolled_at <  date '2026-09-19';

-- ---------------------------------------------------------------------------
-- 【三】★消えたか 見る
--
--   ★★`在籍` が 0 なら 片づきました。
-- ---------------------------------------------------------------------------
select o.name as 教室,
       count(*) filter (where e.status = 'active') as 在籍,
       count(*)                                    as 行の数
from public.organizations o
left join public.enrollments e on e.org_id = o.id
where o.name like '%はじめの1人テスト%'
group by o.name;

-- ---------------------------------------------------------------------------
-- 【四】★受け持ちが 残って いないか
--
--   ★★在籍を 消しても、★`assignments` は 残ります。
--     ★★仮の 在籍に 受け持ちを 付けて いなければ、★0 です。
--   ★★0 で なければ、★その 行も 一緒に 片づけます（★お知らせ ください）。
-- ---------------------------------------------------------------------------
select count(*) as 残った受け持ち
from public.assignments a
join public.organizations o on o.id = a.org_id
where o.name like '%はじめの1人テスト%'
  and a.ended_at is null;
