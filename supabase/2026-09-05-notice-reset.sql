-- ---------------------------------------------------------------------------
-- ① ★まず、どれだけ在るかを見ます（★消す前に、数を見ること）
-- ---------------------------------------------------------------------------
select count(*) as "お知らせを閉じた行の数"
  from public.user_notices
 where notice_key = 'consentApology2026';

-- ---------------------------------------------------------------------------
-- ② ★消します
--
--   ★★「同意し直した方」も、この行を持っています。
--     ★その方に、もう一度出してよいか ── ★出してよいです。
--     ★同意し直した方は、★もう一度出ても、★同意の画面で「済んでいる」と分かります。
--     ★★出しすぎるほうが、★届かないより、まだよいのです。
--
--   ★どうしても、同意し直した方には出したくない場合は、
--     ★下の where に and 条件を足してください（★consent_policy_version で絞る）。
--     ★★ただし、★版が上がっていない方も混ざります。★お勧めしません。
-- ---------------------------------------------------------------------------
delete from public.user_notices
 where notice_key = 'consentApology2026';

-- ---------------------------------------------------------------------------
-- ③ ★確かめ（★0 になっていること）
-- ---------------------------------------------------------------------------
select count(*) as "★0 のはず"
  from public.user_notices
 where notice_key = 'consentApology2026';

-- ★ほかのお知らせが、残っていること
select notice_key as "鍵", count(*) as "数"
  from public.user_notices
 group by notice_key
 order by notice_key;
