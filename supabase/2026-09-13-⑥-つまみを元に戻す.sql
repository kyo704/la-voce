-- ────────────────────────────────────────────────────────────────
-- ① ★いまの 姿（★読むだけ）
-- ────────────────────────────────────────────────────────────────
select q.name                                          as "役職",
       coalesce((q.perms ->> 'shukketsu')::boolean, false) as "出席を つける",
       coalesce((q.perms ->> 'meibo')::boolean, false)     as "名簿",
       q.perms                                         as "できこと（全部）"
from public.org_posts q
join public.organizations o on o.id = q.org_id
where o.name = '★実機テスト（消してよい）'
order by q.sort_order;

-- ★★期待 ── 2行（★学部長・課長）。
--   ★★学部長の「出席を つける」が false なら、★②で 戻します。
--   ★★true の ままなら、★②は 要りません。★そのまま ⑨へ。


-- ────────────────────────────────────────────────────────────────
-- ② ★学部長の「出席を つける」を 元に 戻す（★true に する）
--    ★★ほかの できことには 触れません。★1つの 鍵だけを 入れ直します。
-- ────────────────────────────────────────────────────────────────
update public.org_posts q
   set perms = jsonb_set(coalesce(q.perms, '{}'::jsonb),
                         '{shukketsu}', 'true'::jsonb, true)
  from public.organizations o
 where o.id = q.org_id
   and o.name = '★実機テスト（消してよい）'
   and q.name = '学部長';

