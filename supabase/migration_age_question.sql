-- ============================================================================
-- 18歳未満かどうかの確認（作業指示-公開前の実装.md A-7 の1行目）
--
--   A-7 は「生年月日、または『18歳未満か』を登録時に聞く」から始まります。
--   ★坂本さんの判断で、生年月日ではなく はい/いいえ にしました。
--     必要なのは「18歳未満か」だけで、生年月日はそれ以上を集めてしまいます。
--
--   ★答えていない人は、未成年として扱います（フェイルクローズ）。
--     そのため null を「まだ答えていない」の意味で使い、既定値を入れません。
--     0/false を既定で入れると、「成人だと答えた」と区別がつかなくなります。
--
--   ★profiles.age には触れません。あれは体組成の推定に使う任意の数値で、
--     目的が違います。年齢の確認は is_under_18 だけを見ます。
--     正は lib/ageGate.js です。
--
--   ★何度実行しても同じ結果になります。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- ① 実行の前に数える（★記録として残してください）
-- ---------------------------------------------------------------------------
select count(*) as "いまの登録者数" from public.profiles;

-- ---------------------------------------------------------------------------
-- ② 列を足す
-- ---------------------------------------------------------------------------

-- 18歳未満か。★null は「まだ答えていない」。既定値を入れないこと。
alter table public.profiles
  add column if not exists is_under_18 boolean;

-- この質問を一度出した時刻。★飛ばした人にも入ります。
-- 答えたかどうかではなく、「もう出したか」を覚えるための列です。
-- 二度と催促しないために使います。
alter table public.profiles
  add column if not exists age_question_shown_at timestamptz;

-- ---------------------------------------------------------------------------
-- ③ 列の説明
-- ---------------------------------------------------------------------------
comment on column public.profiles.is_under_18 is
  '18歳未満か。★null は「まだ答えていない」。既定値を入れないこと。null と true はどちらも未成年として扱う（lib/ageGate.js）。';
comment on column public.profiles.age_question_shown_at is
  'この質問を一度出した時刻。★飛ばした人にも入る。二度と催促しないための目印で、答えの有無ではない。';

-- ---------------------------------------------------------------------------
-- ④ 確かめる（★2行とも出ること。is_under_18 の既定値が空であること）
-- ---------------------------------------------------------------------------
select column_name as "列", data_type as "型", is_nullable as "null可",
       coalesce(column_default, '(既定値なし)') as "既定値"
  from information_schema.columns
 where table_schema = 'public' and table_name = 'profiles'
   and column_name in ('is_under_18', 'age_question_shown_at')
 order by column_name;

-- ★全員が「まだ答えていない」であること（＝現時点では全員が未成年として扱われる）
select count(*) as "まだ答えていない人（いまは全員のはず）"
  from public.profiles
 where is_under_18 is null;
