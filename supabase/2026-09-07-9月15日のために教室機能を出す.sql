-- ===========================================================================
-- ① いまの状態を見ます（★読むだけ）
-- ===========================================================================
select
  p.id                                      as 利用者,
  coalesce(p.is_admin, false)               as 管理者か,
  coalesce(p.teacher_beta_access, false)    as 教室機能が出ているか
from public.profiles p
where p.id = '99b695d8-ae90-43a5-9767-a8d073a4003d';

-- ★「教室機能が出ているか」が false なら、②を流してください。
--   ★true なら、すでに出ています。②は要りません。

-- ===========================================================================
-- ② 立てます
-- ===========================================================================
update public.profiles
   set teacher_beta_access = true
 where id = '99b695d8-ae90-43a5-9767-a8d073a4003d';

-- ===========================================================================
-- ③ 確かめます（★読むだけ）
-- ===========================================================================
select
  p.id                                      as 利用者,
  coalesce(p.teacher_beta_access, false)    as 教室機能が出ているか
from public.profiles p
where p.id = '99b695d8-ae90-43a5-9767-a8d073a4003d';

-- ★「教室機能が出ているか」が true になっていれば、成功です。
-- ★★アプリを開き直してください。読み込みのときに、1回だけ読んでいます。

