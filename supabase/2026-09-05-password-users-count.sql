-- ============================================================================
-- ★パスワードをお使いの方が、何人いらっしゃるか（2026-09-05）
--
--   ★これは、★読むだけの SQL です。★1文字も書き換えません。
--     ★安心して、そのまま実行できます。
--
--   ★なぜ必要か
--     ★6桁の数字で入る道（④）を、★いまお使いの方にも出すかどうか。
--     ★その判断に、★「いま何人がパスワードで入っているか」が要ります。
--
--   ★★auth.audit_log_entries は、0件でした（2026-09-05 確認）。
--     ★このプロジェクトでは、★監査ログが残っていません。
--     ★★だから、★別の場所から数えます。
--
--   ★★数える場所は、★auth.users と auth.identities です。
--     ★これは、監査ログではありません。★アカウントそのものです。
--     ★消えません。★保存期間もありません。
-- ============================================================================


-- ---------------------------------------------------------------------------
-- ① ★パスワードを持っている方の数
--
--   ★★encrypted_password は、★パスワードを決めた方にだけ入ります。
--     ★6桁の数字だけで作られたアカウントには、★空です。
--
--   ★★ただし、★「持っている」と「使っている」は、★別のことです。
--     ★昔パスワードで作って、★いまは数字で入っている方も、★ここに入ります。
--     ★★①だけで結論を出さないこと。★③と合わせて読みます。
-- ---------------------------------------------------------------------------
select
  count(*) filter (
    where encrypted_password is not null and encrypted_password <> ''
  ) as "パスワードを持っている",
  count(*) filter (
    where encrypted_password is null or encrypted_password = ''
  ) as "パスワードを持っていない",
  count(*) as "ぜんぶ"
from auth.users
where deleted_at is null;


-- ---------------------------------------------------------------------------
-- ② ★入り口の種類ごとの数
--
--   ★auth.identities は、★1人につき、★入り口の数だけ行があります。
--     ★provider = 'email' … メール（★パスワードでも、6桁でも、これです）
--     ★provider = 'google' など … 外部のもの
--
--   ★★provider だけでは、★パスワードと6桁を見分けられません。
--     ★どちらも 'email' です。★見分けは①でします。
--   ★ここで見たいのは、★「メール以外の入り口の方がいるか」です。
-- ---------------------------------------------------------------------------
select provider as "入り口", count(*) as "人数"
from auth.identities
group by provider
order by count(*) desc;


-- ---------------------------------------------------------------------------
-- ③ ★★いま実際に、★どちらで入っているか
--
--   ★★これが、★いちばん知りたい数です。
--
--   ★raw_app_meta_data には、★Supabase が、★最後に使った入り口を書きます。
--     ★ただし、★'email' としか書かれません（★①と同じ弱点）。
--
--   ★★そこで、★最後に入った日と、★パスワードの有無を、★組み合わせます。
--     ★「パスワードを持っていて、★最近入っている」＝★いま使っている方。
--     ★★これは推定です。★断定ではありません。
--       ★6桁の道は 2026-09-04 に作ったばかりで、★まだ誰にも出していません。
--       ★★だから今は、★パスワードを持つ方＝パスワードで入っている方、
--         と読んで、★まず間違いありません。
-- ---------------------------------------------------------------------------
select
  case
    when u.encrypted_password is null or u.encrypted_password = ''
      then '6桁だけ（パスワードなし）'
    else 'パスワードあり'
  end as "種類",
  count(*) as "人数",
  count(*) filter (where u.last_sign_in_at >= now() - interval '30 days')
    as "30日以内に入った",
  count(*) filter (where u.last_sign_in_at >= now() - interval '90 days')
    as "90日以内に入った",
  count(*) filter (where u.last_sign_in_at is null)
    as "一度も入っていない"
from auth.users u
where u.deleted_at is null
group by 1
order by 2 desc;


-- ---------------------------------------------------------------------------
-- ④ ★最後に入った日の、月ごとの散らばり
--
--   ★★「いま使っている方が何人か」を、★人数ではなく★形で見ます。
--     ★★30日以内の方だけが、★移行の案内を出す相手です。
--     ★2年前に一度きりの方に、★案内は届きません。
-- ---------------------------------------------------------------------------
select
  to_char(date_trunc('month', u.last_sign_in_at), 'YYYY-MM') as "最後に入った月",
  count(*) as "人数"
from auth.users u
where u.deleted_at is null and u.last_sign_in_at is not null
group by 1
order by 1 desc;


-- ---------------------------------------------------------------------------
-- ⑤ ★もし、これから記録を残したいなら（★いまは、しなくて結構です）
--
--   ★★Supabase の監査ログが空なのは、★プランの都合です。
--     ★こちらで元に戻すことはできません。
--
--   ★★どうしても「どちらで入ったか」を数えたいときは、
--     ★すでにある onboarding_counts に、★段を足す形になります。
--     ★★user_id を持たない、★日ごとの回数だけの表です。
--     ★個人を特定しません。
--
--   ★ただし、★足すには bump_onboarding_count の白名簿に
--     ★新しい段の名前を書き足す必要があります（★SQL の書き換えです）。
--   ★★いま急いで決めることではありません。★①〜④で足ります。
-- ---------------------------------------------------------------------------


