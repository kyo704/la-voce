-- ============================================================================
-- 招待に「どの教室か」を持たせる（2026-09-01）
--
--   ★何が起きていたか
--     招待を受けた生徒は、在籍（enrollments）を作るために
--     ★先生の memberships を読もうとしていました。
--     ですが memberships_select は「本人か、教室のオーナー・管理者」だけです。
--     生徒はどちらでもないので、0行が返ります（★エラーではありません）。
--     その結果 enrollments の upsert は★一度も実行されませんでした。
--     enrollments は、この日まで全体で0行でした。
--
--   ★形そのものが間違っていました
--     招待には「どの教室への招待か」が入っていませんでした（code と
--     teacher_id と期限だけ）。だから生徒が、先生の非公開の行を読んで
--     ★教室を推測するしかありませんでした。
--     RLS はまさにそれを防ぐためのものです。
--
--   → 招待そのものに org_id を持たせます。
--     発行するのは先生なので、自分の教室のIDは当然に分かります。
--
--   ★既存の行は埋めません（null のままにします）。
--     「発行時に教室が決まっていた」ことと「あとから推測して埋めた」ことは
--     別の事実です。古い招待は、受け取る側で解決します
--     （app/api/enrollment/accept が、先生のオーナー教室を見にいきます）。
--
--   ★何度実行しても同じ結果になります。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- ① 実行前の状態（★記録として残してください）
-- ---------------------------------------------------------------------------
select count(*) as "招待の総数",
       count(*) filter (where used_at is null) as "まだ使われていない"
  from public.teacher_invitations;

select count(*) as "★在籍の総数（この時点では0のはずです）"
  from public.enrollments;

-- ---------------------------------------------------------------------------
-- ② 列を足す
--
--   ★null を許します。既存の招待には入れません（後から推測しないため）。
--   ★教室が消えたら、招待も一緒に消えるのが自然なので cascade にします。
-- ---------------------------------------------------------------------------
alter table public.teacher_invitations
  add column if not exists org_id uuid references public.organizations(id) on delete cascade;

comment on column public.teacher_invitations.org_id is
  'この招待が、どの教室への招待か。★発行時に入れる。'
  '★null は「発行時には記録していなかった古い招待」。受け取る側で解決する。'
  '★生徒に先生の memberships を読ませないために存在する列（2026-09-01）。';

-- ---------------------------------------------------------------------------
-- ③ 確かめる
-- ---------------------------------------------------------------------------
select column_name as "列", data_type as "型", is_nullable as "null可"
  from information_schema.columns
 where table_schema = 'public' and table_name = 'teacher_invitations'
   and column_name = 'org_id';

-- ★既存の行が書き換わっていないこと（org_id が入っている行は0であるべき）
select count(*) as "org_id が入っている招待（この時点では0）"
  from public.teacher_invitations
 where org_id is not null;
