/** ★曲線の 指図（★これが 入って いたら、★描き直しです）。 */
export const CURVE_COMMANDS = Object.freeze(["C", "c", "S", "s", "Q", "q", "T", "t", "A", "a"]);

/**
 * ★その しるしの 中身（★svg の 内側）。
 *
 *   ★★知らない 名は null。★空の 四角を 出しません。
 *     ★★「何も 出ない」より、★「呼び方が 違う」と 分かる ほうが 直せます。
 */
export function iconBody(key) {
  if (Object.prototype.hasOwnProperty.call(ICO, key)) return ICO[key];
  if (Object.prototype.hasOwnProperty.call(ICO_P, key)) return ICO_P[key];
  return null;
}

/** ★しるしの 名の 一覧（★見張りが 数えます）。 */
export function iconKeys() {
  return Object.keys(ICO).concat(Object.keys(ICO_P));
}

/**
 * ★曲線が 混ざって いない か。
 *
 *   ★★`d="…"` の 中 だけ を 見ます。★`rx`・`cx` の x を 拾いません。
 */
export function hasCurve(body) {
  const ds = [...String(body || "").matchAll(/d="([^"]*)"/g)].map((m) => m[1]);
  return ds.some((d) => CURVE_COMMANDS.some((c) => d.includes(c)));
}
