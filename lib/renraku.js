/** ★宛先の 空（★しぼって いない 姿）。 */
export const EMPTY_TARGET = Object.freeze({
  divisionIds: [], gradeYears: [], userIds: []
});

/** ★しぼって いるか（★3つ とも 空なら しぼって いません）。 */
export function isWholeSchool(t) {
  const x = t || EMPTY_TARGET;
  return (x.divisionIds || []).length === 0
    && (x.gradeYears || []).length === 0
    && (x.userIds || []).length === 0;
}

/**
 * ★届く 方（★名簿の 行から 数えます）。
 *
 *   ★★`rows` は `{ user_id, division_id, grade_year, counted }`。
 *   ★★★いま 在る 方 だけ を 数えます（★`counted`）。
 *     ★★休会・退会の 方に、★お知らせは 届きません。
 *   ★★しぼって いなければ、★その 学校の 在る 方 みなさん です。
 *   ★★しぼって いれば ── ★どれか 1つでも 当てはまる 方 です（or）。
 *     ★★★「学科 かつ 学年」では ありません。★狭めすぎると 0人に なります。
 *     ★★見本も、★段ごとに 候補が 減る 形 です（★and では ありません）。
 */
export function reachOf(rows, t) {
  const x = t || EMPTY_TARGET;
  const 居る = (rows || []).filter((r) => r && r.counted !== false);
  if (isWholeSchool(x)) return 居る.map((r) => r.user_id);
  const out = new Set();
  居る.forEach((r) => {
    if ((x.userIds || []).includes(r.user_id)) { out.add(r.user_id); return; }
    if (r.division_id && (x.divisionIds || []).includes(r.division_id)) {
      out.add(r.user_id); return;
    }
    if (r.grade_year != null && (x.gradeYears || []).includes(Number(r.grade_year))) {
      out.add(r.user_id);
    }
  });
  return [...out];
}

/** ★何人に 届くか の 字。★0人なら はっきり 言います。 */
export function reachWord(n) {
  return Number(n) > 0 ? `${Number(n)}人に 届きます` : "このままでは 誰にも 届きません";
}

/** ★出せるか（★0人では 出せません。★本文が 空でも 出せません）。 */
export function mayPostAnnouncement(n, body) {
  return Number(n) > 0 && !!String(body || "").trim();
}

