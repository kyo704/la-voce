/**
 * ★何日 経ったか。★時計を 見ません。★今日を 渡してもらいます。
 *
 *   ★★★【後まわし・2026-09-18】★`createdAt` は 台帳の UTC の 字 です。
 *     ★★`slice(0,10)` は、★その 字を そのまま 切って います。
 *     ★★日本では 9時間 先 です ── ★夜の 書き込みは、★1日 古く 数えます。
 *     ★★★いま 直して いない わけ ── ★ここが 決める のは
 *       ★★「90日 経ったか」だけ です。★90日の 端が 1日 動きます。
 *       ★★お相手に 出る のは 「消えます」の 断り だけ で、★日づけは 出ません。
 *       ★★★画面に 間違った 日づけが 出る ところ（`lib/monkaReadNotice.js`）は、
 *         ★★同じ 日に 直しました。★あちらは 見える ので 先 です。
 *     ★★★引き金 ── ★この 関数が 日づけを **出す** ように なった 日。
 *       ★★または `HIDE_AFTER_DAYS` を 90 より 短く する 日（★端が 効いて きます）。
 *       ★★そのときは `dayOf`（`lib/todayBand.js`）に 通して ください。
 *       ★★★`lib/monkaReadNotice.js` が この 1本を 読んで います。
 *         ★★取り込みを 増やすと、★見張りの 読み込みが 2段に なって 落ちます
 *         （★`components/tests/_source.js` の `loadLib`）。★そこも ご一緒に。
 *     ★★台帳 docs/ledgers/08-保留している決め.md 08-5
 */
export function ageInDays(createdAt, todayISO) {
  const c = String(createdAt || "").slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(c) || !/^\d{4}-\d{2}-\d{2}$/.test(String(todayISO || ""))) return null;
  const a = Date.UTC(Number(c.slice(0, 4)), Number(c.slice(5, 7)) - 1, Number(c.slice(8, 10)));
  const b = Date.UTC(Number(todayISO.slice(0, 4)), Number(todayISO.slice(5, 7)) - 1, Number(todayISO.slice(8, 10)));
  return Math.round((b - a) / 86400000);
}

/** ★もうすぐ 画面から 消えるか（★見本③）。 */
export function isVanishingSoon(createdAt, todayISO) {
  const d = ageInDays(createdAt, todayISO);
  return d != null && d >= HIDE_AFTER_DAYS - SOON_DAYS && d < HIDE_AFTER_DAYS;
}

/** ★もう 画面から 消える ぶんか（★90日を 過ぎた）。★台帳には 残ります。 */
export function isExpired(createdAt, todayISO) {
  const d = ageInDays(createdAt, todayISO);
  return d != null && d >= HIDE_AFTER_DAYS;
}

/**
 * ★出す 書き込み。
 *
 *   ★★取り消した ものも 残します（★見本②「静かに 1行だけ 残ります」）。
 *     ★★中身は 出しません。★取り消した、という 1行だけです。
 *   ★90日を 過ぎた ものは 出しません。★★台帳からは 消しません（★裁定 その77）。
 *   ★古い順に 並べます（★会話だからです）。
 */
export function visibleMessages(messages, todayISO) {
  return (messages || [])
    .filter((m) => m && !isExpired(m.created_at, todayISO))
    .sort((a, b) => (String(a.created_at) < String(b.created_at) ? -1 : 1))
    .map((m) => ({
      ...m,
      withdrawn: !!m.withdrawn_at,
      // ★★取り消したら、★中身を 出しません。
      body: m.withdrawn_at ? null : m.body,
      soon: isVanishingSoon(m.created_at, todayISO)
    }));
}

