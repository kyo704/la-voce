/**
 * ★運営モードで 名簿と 役職を 読みに 行って よい 方か。
 *
 *   @param email ★その方の お名前（メール）
 *   @param env   ★process.env（★試せる ように 渡します）
 */
export function mayLoadOpsDetail(email, env) {
  const raw = (env && env.NEXT_PUBLIC_OPS_FIX_ALLOWLIST) || "";
  const list = String(raw).split(",").map((s) => s.trim().toLowerCase()).filter(Boolean);
  if (list.length === 0) return false;
  return list.includes(String(email || "").trim().toLowerCase());
}

/** ★環境変数の 名前。★2か所で 書かないため、ここに 置きます。 */
export const OPS_FIX_ENV = "NEXT_PUBLIC_OPS_FIX_ALLOWLIST";
