/**
 * ★伝える ボタンを 出して よいか。
 *
 *   ★★先生が いない 回には 出しません ── ★届く 先が ありません。
 *   ★★すでに 伝えて ある ときも 出しません ── ★2度 送りません（★見本「1回だけ」）。
 */
export function mayTell(lesson) {
  const l = lesson || {};
  return !!l.teacher_id && !l.student_notice;
}

/** ★伝えた あとの 1行。★「ありがとう」と 書きません ── ★ただ 届いたと 言います。 */
