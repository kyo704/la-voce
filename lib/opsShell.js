function isPerms(x) {
  return Array.isArray(x) || x instanceof Set
    || (x && typeof x === "object" && !Array.isArray(x));
}

export function tabsFor(roleOrPerms) {
  // ★★できことを 渡されたら、★そちらで 決めます（★裁定 §7-3）。
  //   ★役職の 名前で 分けません。
  if (isPerms(roleOrPerms)) return tabsForPerms(roleOrPerms);
  // ★★A13 で ここは 消えます。★役職を 誰もが 持つように なれば 要りません。
  //
  // ★★★この 行を さわる 方へ（★2026-09-14・坂本さんの お決め）
  //   ★★ここを 外す 仕事に、★名前が ついて います ── **A2**。
  //     ★引き金は ①教室の 機能に 着手する とき
  //     　　　　　 ②次に この ファイルを さわる 必要が 生じた とき
  //     ★★いま、★②に 当たって います。★先に 読んで ください ──
  //       `docs/records/やること-9月15日のあと.md` の **㉑**
  //
  //   ★★実測（★2026-09-14・`node tools/perm-matrix.js`）
  //     ★この 経路（役職の 名前）… ★食い違い **33 通り**／120
  //     ★下の `tabsForPerms`（できこと）… ★食い違い **0 通り**
  //     ★★直し方は もう あります。★使って いないだけ です。
  //
  //   ★★実害は ありません。★画面に よけいに 出るだけ で、
  //     ★書き込みは `app/api/org/posts/route.js:246` の
  //     `mayChangePerson` が 止めます（★2026-09-14・本物の JWT で 確認）。
  //   ★★★ただし ── ★ここを 読み違えないで ください。
  //     ★33件は「画面に 出るが 通らない」＝ ★**押せない 札**（★§8⑤）。
  //     ★★実害は ないが、★**原則には 触れて います**。
  //     ★★先送りの わけは「通らない から」で あって、
  //       ★「よい こと だから」では ありません。
  //   ★★仕掛けは もう あります ── ★下の `tabsForPerms()`。
  //     ★作る 仕事では なく、★**呼ぶ 側を 切り替える** 仕事 です。
  //   ★★けれど 範囲が 大きい です ── ★門の 外の 38人 ぜんぶの 運営画面。
  const keys = BY_ROLE[roleOrPerms] || [];
  return OPS_TABS.filter((t) => keys.includes(t.key));
}

