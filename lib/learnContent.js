export function getArticlesForProfession(professionKey) {
  return ARTICLES.filter((a) => a.professions === "all" || (Array.isArray(a.professions) && a.professions.includes(professionKey)))
    .sort((a, b) => a.chapter - b.chapter || a.order - b.order);
}
export function getArticleById(id) {
  return ARTICLES.find((a) => a.id === id) || null;
}
