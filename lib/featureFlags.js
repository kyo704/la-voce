// ============================================================================
// 機能フラグ（統合実行ルートv4 G2-14「指導者・教室機能を機能フラグでオフ」）
//
// ★判定はこのファイルだけが持つこと。画面ごとに is_admin を書くと、
//   隠し忘れが必ず出る（表示ゲート・ロック判定・共有範囲と同じ原則）。
//
// なぜ隠すのか（v4 §4-2）:
//   指導者機能は最大の増幅装置だが、いま権限の層とデータの層が固まっていない。
//   壊れたものの上で増幅すると、事故も増幅される。10人に配る段階では、
//   検証できていない機能を一般ユーザーの視界から外しておく。
//   ★「捨てる」ではなく「順番の問題」。G3.5 で戻す。
// ============================================================================

/**
 * 検証途中の機能を見せてよい相手か。
 * 管理者（is_admin）と、指導者ベータに招いた人（teacher_beta_access）だけ。
 */
export function canSeeBetaFeatures(profile) {
  if (!profile) return false;
  return !!profile.is_admin || !!profile.teacher_beta_access;
}

/**
 * 指導者・教室の機能（生徒の招待、生徒一覧、教室の管理）。
 * ★既につながっている人からは取り上げない。
 *   共有を解除する手段まで消えてしまい、かえって不利益になるため。
 */
export function canSeeTeacherFeatures(profile, { hasTeacherLinks = false, hasStudentLinks = false } = {}) {
  return canSeeBetaFeatures(profile) || hasTeacherLinks || hasStudentLinks;
}

/**
 * ★生徒の側から「先生とつながる」入口。
 *
 * これは指導者機能ではありません。生徒が招待コードを入れ、共有する項目を選び、
 * つながりを解除する — どれも生徒自身の操作です。canSeeTeacherFeatures で
 * 一緒に隠していたため、次の2つが起きていました。
 *
 *  1. 新規ユーザーは「先生とつながる」に永久に到達できない。
 *     以前これは「レッスンタブの中にあるのに、そのタブはつながって初めて出る」
 *     という形で見つかり、全員が見る「もっと」へ移して直したはずでした。
 *     ところが G2-14 の機能フラグで、移した先ごと隠れていました。
 *     場所を移しただけで、鶏と卵は解けていなかった。
 *
 *  2. ベータの先生が一般の生徒を招待しても、生徒はコードを入れる欄に
 *     たどり着けない。招待の仕組み自体が試せない。
 *
 * ★だから、ここは常に true。隠すのは先生の側の道具（生徒一覧・招待の発行・
 *   教室の管理）だけで、生徒が誰かとつながる権利は、機能フラグの対象外です。
 */
export function canSeeStudentTeacherLink() {
  return true;
}

/**
 * LINE通知の連携。
 * 公式アカウントの運用（友だち追加の導線・Webhookの設定）が固まるまでは、
 * 一般ユーザーに出さない。設定が済んでいない環境では入口だけあっても連携できない。
 */
export function canSeeLineLink(profile) {
  return canSeeBetaFeatures(profile);
}

/**
 * 音楽家の商い（第1章・第2章、shobai-01〜14）を見せてよい相手か。
 *
 * ★これは有料の記事です。根拠は
 *   docs/lavoce-作業指示-問いの形を記事ごとに分ける.md §6「無料と有料」:
 *     無料   基本編の記事すべて／読む前の問い／recall の3問
 *     有料   音楽家の商い（第1章・第2章）／reflect の記述と、その履歴
 *   ★私の推測ではなく、指示に書いてあります。
 *   ただし課金の線はまだ引かれていません（REQUIRE_SUBSCRIPTION は off で、
 *   アプリ全体が無料で動いています）。この状態で本文を全員に出すと、
 *   あとから「前は読めたのに」という形でしか有料化できなくなります。
 *   ★先に配ってから引っ込めるのは、いちばん嫌われるやり方です。
 *
 *   だから当面は、検証中の機能と同じ扱いにします。管理者には見えるので、
 *   坂本さんは中身を確認できます。15〜20人に配る段階では出ません。
 *
 * ★記事の一覧からも本文からも、まとめてここで判定すること。
 *   一覧には出して本文で止める、という形にしないこと。
 *   読めない記事が並んでいるのは、鍵をかけられているのと同じ体験です。
 *
 * ★§6 の「無料の人にも記述欄は見せる」は、記事が読める人に対する話です。
 *   記事そのものが見えない段階では、記述欄も出しません。
 *   課金の線を引くときに、ここを外して §6 の形へ移します。
 */
/**
 * ★★2026-09-16、★お支払いを 見る ように しました（★坂本さんの お指図）。
 *
 *   ★★これまでは `canSeeBetaFeatures` の まま でした ──
 *     ★管理者（`is_admin`）と 指導者ベータ（`teacher_beta_access`）だけ。
 *   ★★つまり **一般の 方には、もともと 出て いません** でした。
 *     ★漏れて いた わけでは ありません。★閉じ方が「お支払い」では
 *       なかった、★という ことです。
 *   ★★上の 覚え書きに、★そう する と 書いて あります ──
 *     「課金の 線を 引く ときに、★ここを 外して §6 の 形へ 移します」。
 *     ★★きょう、★その 線を 引きました。
 *
 *   ★★★ここで、★**やっては いけない** ことが 1つ あります。
 *
 *     ★★プランの 画面で 使った `mayViewSummary` / `paidGateApplies` を、
 *       ★そのまま 持って こないで ください。
 *     ★★あれは「★誰に 壁を 見せるか」の 判定 です。
 *       ★「★誰に 中身を 見せるか」の 判定では ありません。
 *     ★★`NEXT_PUBLIC_GATE_TEST_USER_IDS` に **入って いない** 方には、
 *       ★`mayViewSummary` は **true**（=見せてよい）を 返します。
 *       ★★試しの あいだ、★一般の 方に 壁を 出さない ため です。
 *     ★★だから それで 囲うと ── ★**全員に 開きます。**
 *       ★★閉じる つもりで 書いた 1行が、★逆を します。
 *   ★★だから、★**開いて いる 側**を 数えます ── お支払いが 続いて いるか。
 *     ★読めない ときは 閉じます（★`subscribed` が null なら false）。
 *     ★★迷ったら 閉じる。★お金の 話は そちらへ 倒します。
 *
 *   ★★管理者・指導者ベータは、★これまでどおり 見られます。
 *     ★坂本さんが 中身を 確かめられなく なると 困る から です。
 *
 *   @param profile    ★その方の profiles の 行
 *   @param opts.subscribed ★お支払いが 続いて いるか（true のときだけ 開きます）
 */
export function canSeeShobaiArticles(profile, opts) {
  // ★★`true` だけ を 通します。★"active" などの 字や 1 を 通しません。
  //   ★★呼ぶ 側が 何を 渡しても、★ここで 1つの 形に します。
  if ((opts || {}).subscribed === true) return true;
  return canSeeBetaFeatures(profile);
}

/** 音楽家の商いの記事かどうか。★判定の文字列を画面側に書かないこと。 */
export function isShobaiArticle(article) {
  return !!article && typeof article.id === "string" && article.id.startsWith("shobai-");
}
