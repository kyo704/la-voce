/**
 * ★値段の 札を、★鍵から 引きます（★2026-09-15）。
 *
 *   ★★`components/CountV2.jsx` が、★値段を **直に 書いて** いました。
 *     ★★年額を 5,800 → 4,800 に 下げた とき、★そこだけ 古いまま でした。
 *     ★★`app/billing/page.js:95` に、★同じ 失敗の 記録が あります ──
 *       「★年額を 5,800 → 4,800 に下げたとき、★ここだけ古いまま残りました。」
 *     ★★**2度目** です。★同じ 決めが 2か所に ある かぎり、★また 起きます。
 *
 *   ★★だから、★引く 道を 作ります。★書き写す 先を 増やしません。
 */
export function priceLabelOf(key) {
  const p = PLANS.find((x) => x.key === key);
  return p ? p.priceLabel : "";
}

/** ★税込である ことを 添えた 札（★かぞえるの 画面が 使います）。 */
export function priceWithTaxOf(key) {
  const p = PLANS.find((x) => x.key === key);
  if (!p) return "";
  return p.priceYen.toLocaleString("ja-JP") + "円（税込）";
}


/** 名前から引きます。★知らない名前には null を返します。 */
export function planByKey(key) {
  return PLANS.find((p) => p.key === key) || null;
}

/**
 * ★1回払いの 買い切りか（★2026-09-09）。
 *
 *   ★★Checkout の mode が 変わります。
 *     ★買い切り　mode: "payment"　　　★1度きり。★自動更新 なし
 *     ★月ごと　  mode: "subscription" ★毎月 更新
 *   ★★2か所で 判じないこと。★ここ1つを 見ます。
 */
export function isBuyOnce(key) {
  const p = PLANS.find((x) => x.key === key);
  return !!(p && p.buyOnce);
}

