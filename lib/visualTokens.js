//       ★★裁定 §5-3 が いちばん 嫌って いる 形 です。
export const TABLE_ROW_BASE_PX = 40;
export const SCALE_VAR = "--scale";

/** ★表の 入れ物の 名（★裁定の まま）。 */
export const TABLE_CLASS = "tblwrap";

/** ★左の 列（錨）に 付ける 名（★裁定の まま。★2つ とも 効きます）。 */
export const ANCHOR_CLASSES = Object.freeze(["stick", "anc"]);

// ----------------------------------------------------------------------------
// 【五】★CSS に 直す
// ----------------------------------------------------------------------------
//   ★★★文字で 組み立てます。★画面ごとに 書き写しません。
//     ★★写しが できた 日に、★片方だけ 直る 日が 来ます。

function 宣言(tokens) {
  return Object.keys(tokens).map((k) => `--${k}:${tokens[k]}`).join(";");
}

/**
 * ★土台の CSS。★`.wsv` の 中 だけ に かかります。
 *
 *   ★★`:root` に 置きません。★門の 外の 画面を 変えない ため です。
 */
export function tokensCss() {
  const 明 = 宣言(TOKENS_LIGHT);
  const 暗 = 宣言(TOKENS_DARK);
  const 行 = `calc(${TABLE_ROW_BASE_PX}px * var(${SCALE_VAR},1))`;
  return [
    `.${SCOPE_CLASS}{${明}}`,
    `html[data-th="dark"] .${SCOPE_CLASS}{${暗}}`,

    // ★★表の 入れ物。★中で すべります。★外の 画面は すべりません。
    `.${SCOPE_CLASS} .${TABLE_CLASS}{overflow:auto;position:relative;max-height:560px;`
      + `background:var(--card);border:1px solid var(--line);border-radius:12px}`,

    // ★★見出しの 行を 貼り付けます（★NN/g「ヘッダー行・ヘッダー列を 固定せよ」）。
    `.${SCOPE_CLASS} .${TABLE_CLASS} thead th,`
      + `.${SCOPE_CLASS} .${TABLE_CLASS} tr:first-child th{`
      + `position:sticky;top:0;z-index:3;background:var(--paper);`
      + `box-shadow:inset 0 -1px 0 var(--line)}`,

    // ★★左の 列 ── ★これが「錨」です。
    //   ★★横に すべった とき、★どの 行を 見て いるかの 確かめ に なります。
    `.${SCOPE_CLASS} .${TABLE_CLASS} .stick,`
      + `.${SCOPE_CLASS} .${TABLE_CLASS} .anc{`
      + `position:sticky;left:0;z-index:2;background:var(--card);`
      + `box-shadow:1px 0 0 var(--line2)}`,
    `.${SCOPE_CLASS} .${TABLE_CLASS} thead .stick,`
      + `.${SCOPE_CLASS} .${TABLE_CLASS} thead .anc,`
      + `.${SCOPE_CLASS} .${TABLE_CLASS} tr:first-child .stick{`
      + `z-index:4;background:var(--paper)}`,

    // ★★行の 高さ ── ★文字の つまみに 連動（★別の つまみを 作りません）。
    `.${SCOPE_CLASS} .${TABLE_CLASS} td,`
      + `.${SCOPE_CLASS} .${TABLE_CLASS} th{height:${行}}`
  ].join("\n");
}

/** ★色の 名を `var(--…)` に。★直に 書かない ため の 入口 です（★§1-3）。 */
export function v(name) {
  if (!Object.prototype.hasOwnProperty.call(TOKENS_LIGHT, name)) return null;
  return `var(--${name})`;
}
