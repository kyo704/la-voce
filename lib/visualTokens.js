/** ★px を rem に。★`lib/uiKit.js` と 同じ 式 です。 */
export function rem(px) {
  return (Number(px) / 16) + "rem";
}

/** ★段の 名から 大きさ（rem）。★知らない 名は null。★黙って 既定に しません。 */
export function stepRem(key) {
  const s = TYPE_STEPS.find((x) => x.key === key);
  return s ? rem(s.px) : null;
}

