/** ★入口の 縞の 色か（★見張りが 外す ため）。 */
export function isEntranceStripe(hex) {
  const h = String(hex || "").toUpperCase();
  return ENTRANCE_STRIPE_COLORS.some((x) =>
    x.colors.some((c) => c.toUpperCase() === h));
}

/** ★よその 会社の 色か（★見張りが 外す ため）。 */
export function isExternalBrand(hex) {
  const h = String(hex || "").toUpperCase();
  return EXTERNAL_BRAND_COLORS.some((x) =>
    x.bg.toUpperCase() === h || x.text.toUpperCase() === h);
}

/** ★その 名が、★裁定から 動かして ある か。 */
