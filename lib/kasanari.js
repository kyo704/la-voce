/**
 * ★重なりを 見つけます。
 *
 *   ★★同じ 日・同じ 時間の 帯に、★2つ以上の 予定が ある とき です。
 *   ★★★どちらが 正しいかを 決めません。★並べて 返すだけ です。
 *   ★★返す 順は、★渡された 順の まま です ── ★教室で 並べ替えません。
 *     ★★★並べ替えると、★どちらかが 上に なります。★上は「先」に 見えます。
 *
 * @param {Array} items ★[{ id, on, from, to, org, teacher, room }]
 */
export function findOverlaps(items) {
  const 列 = (Array.isArray(items) ? items : []).filter(
    (x) => x && x.on && x.from && x.to);
  const 出 = [];
  for (let i = 0; i < 列.length; i += 1) {
    for (let k = i + 1; k < 列.length; k += 1) {
      const a = 列[i], b = 列[k];
      if (a.on !== b.on) continue;
      if (String(a.from) >= String(b.to) || String(b.from) >= String(a.to)) continue;
      出.push({ on: a.on, from: a.from, to: a.to, items: [a, b] });
    }
  }
  return 出;
}

/** ★日と 時間の 字（★見本「9月12日（金）　14:40 〜 15:25」）。 */
export const WEEK = Object.freeze(["日", "月", "火", "水", "木", "金", "土"]);
export function whenWord(on, from, to) {
  const d = new Date(String(on) + "T00:00:00");
  if (Number.isNaN(d.getTime())) return "";
  const 日 = (d.getMonth() + 1) + "月" + d.getDate() + "日（" + WEEK[d.getDay()] + "）";
  return 日 + "　" + String(from || "") + " 〜 " + String(to || "");
}

