//
//   ★★★位置を 保ちます。★消した ぶんを 空白に します。
//     ★★行番号が ずれると、★報せが 使えなく なります。
//     ★★改行は 残します。★行の 数が 変わりません。
//
//   ★★★黙って 落としません（★裁定 その124）。
//     ★★`stripJs` / `stripSql` は、★消した 数を 一緒に 返します。
//     ★★呼ぶ 側は、★その 数を 1行 出します。
//
//   ★★★落とすのは **註 だけ** です（★裁定 その137・2026-09-21）。
//     ★★はじめ 字（文字列）も 落として いました（★裁定 その135）。
//     ★★★それだと `target="_blank"` の ような **属性の 値** も 消えます。
//       ★★探して いる ものが、★在っても 見えなく なります。
//     ★★字は すべて 残します。★画面の 文も、★属性の 値も。
//
//   ★★★ただし SQL の `comment on … is '…'` は **註 です**。
//     ★★字の 形を して いますが、★台帳に 残す 覚え書き です。
