/** ★消した ぶんを 空白に します。★改行は 残します。 */
function 空白に(s) {
  return s.replace(/[^\n]/g, " ");
}

/**
 * ★共通の 読み取り。★頭から 1文字ずつ 見ます。
 *
 *   ★★★正規表現で 書いて 1度 焼けました（★2026-09-11）。
 *     ★★行コメントの 中の `/*` が、★ブロックの 開きとして 読まれ、
 *       ★★2700字が 本文ごと 消えました。
 *     ★★頭から 読めば、★その 取り違えは 起きません。
 */
function 読む(src, opts, sql) {
  const s = String(src == null ? "" : src);
  // ★★★字を 1つずつ 足すと、★大きい 紙で 止まります（★2026-09-21）。
  //   ★★`VocalTracker.jsx` は 140万字 あります。★10分 待っても 終わりません。
  //   ★★★かけらを 並べて、★最後に 1度 つなぎます。
  const 出 = [];
  let 註 = 0, 文 = 0;
  let i = 0;
  let 前 = 0;   // ★まだ 出に 入れて いない ところの 始め
  // ★★`comment on … is` の 直後の 字は 註 です（★SQL のみ）。
  const 覚え書き = sql ? /comment\s+on\s+[\s\S]{0,120}?\bis\s*$/i : null;
  const 出す = (端) => { if (端 > 前) 出.push(s.slice(前, 端)); };

  /**
   * ★この `/` は 正規表現の 始まりか、★割り算か（★2026-09-21 に 足しました）。
   *
   *   ★★★足すまで、★正規表現を 読み飛ばす 形が ありません でした。
   *     ★★`components/VocalTracker.jsx:3805` の
   *       `.replace(/[「」『』"\u2019"\u2019]/g, "")` で 崩れました。
   *     ★★文字の 組の 中の `"` を、★**字の 始まり** と 読みます。
   *       ★★そこから ずれ、★同じ 紙の 註 **700行** が 外れません でした。
   *     ★★★「註を 外した」つもりの 数えが、★註を 数えて いました。
   *
   *   ★★見分け方 ── ★直前の、★空白でない 1字 を 見ます。
   *     ★値が 来た あと（`)` `]` 名前 数）なら **割り算**。
   *     ★それ以外（`(` `,` `=` `:` `[` `!` `&` `|` `?` `{` `}` `;` 演算子）や、
   *       ★`return` `typeof` などの 語の あとなら **正規表現**。
   *   ★★★完全では ありません。★JavaScript は そこまで 素直では ありません。
   *     ★★けれど「文字の 組の 中の 引用符で 崩れる」は これで 止まります。
   */
  const 正規表現か = (at) => {
    let j = at - 1;
    while (j >= 0 && /\s/.test(s[j])) j -= 1;
    if (j < 0) return true;
    const c2 = s[j];
    if (/[)\]]/.test(c2)) return false;
    if (/[A-Za-z0-9_$]/.test(c2)) {
      // ★語の あと。★`return /…/` なら 正規表現、★`x / y` なら 割り算。
      let k = j;
      while (k >= 0 && /[A-Za-z0-9_$]/.test(s[k])) k -= 1;
      const 語 = s.slice(k + 1, j + 1);
      return ["return", "typeof", "instanceof", "in", "of", "new", "delete",
        "void", "throw", "do", "else", "yield", "await", "case"].includes(語);
    }
    return true;
  };
  while (i < s.length) {
    const c = s[i];
    const 次 = s[i + 1];
    // ── ★行の 註 ──
    if ((c === "/" && 次 === "/") || (sql && c === "-" && 次 === "-")) {
      出す(i);
      const j2 = s.indexOf("\n", i);
      const 端 = j2 < 0 ? s.length : j2;
      出.push(空白に(s.slice(i, 端)));
      註 += 1;
      i = 端; 前 = 端;
      continue;
    }
    // ── ★かたまりの 註 ──
    if (c === "/" && 次 === "*") {
      出す(i);
      const j2 = s.indexOf("*/", i + 2);
      const 端 = j2 < 0 ? s.length : j2 + 2;
      出.push(空白に(s.slice(i, 端)));
      註 += 1;
      i = 端; 前 = 端;
      continue;
    }
    // ── ★正規表現 ── ★読み飛ばします（★2026-09-21）。
    //   ★★中身は 残します。★落とすのは 註 だけ です（★裁定 その137）。
    //   ★★けれど **読み飛ばさないと**、★中の 引用符で 位置が ずれます。
    if (!sql && c === "/" && 次 !== "/" && 次 !== "*" && 正規表現か(i)) {
      let j2 = i + 1;
      let 組 = false;
      while (j2 < s.length) {
        const d = s[j2];
        if (d === "\\") { j2 += 2; continue; }
        if (d === "\n") break;            // ★行を またぐ 正規表現は ありません
        if (組) { if (d === "]") 組 = false; j2 += 1; continue; }
        if (d === "[") { 組 = true; j2 += 1; continue; }
        if (d === "/") { j2 += 1; break; }
        j2 += 1;
      }
      i = j2;
      continue;
    }
    // ── ★字（文字列）── ★残します（★裁定 その137）。
    //   ★★ただし SQL の `comment on … is '…'` は 註 なので 落とします。
    if (c === '"' || c === "'" || c === "`") {
      let j2 = i + 1;
      while (j2 < s.length) {
        if (s[j2] === "\\") { j2 += 2; continue; }
        if (s[j2] === c) { j2 += 1; break; }
        j2 += 1;
      }
      if (覚え書き) {
        // ★★直前の 120字 だけ 見ます。★全部 見ると 遅く なります。
        const 手前 = s.slice(Math.max(0, i - 140), i).replace(/\s+$/, "");
        if (覚え書き.test(手前)) {
          出す(i);
          出.push(空白に(s.slice(i, j2)));
          文 += 1;
          i = j2; 前 = j2;
          continue;
        }
      }
      i = j2;
      continue;
    }
    i += 1;
  }
  出す(s.length);
  return { code: 出.join(""), comments: 註, strings: 文 };
}

/** ★JavaScript / JSX。★落とすのは 註 だけ です（★裁定 その137）。 */
export function stripJs(src, opts) {
  return 読む(src, opts, false);
}

/** ★SQL。★`--` も 註 として 落とします。 */
export function stripSql(src, opts) {
  return 読む(src, opts, true);
}

/** ★検査の 頭に 出す 1行（★黙って 落とさない・裁定 その124）。 */
export function strippedLine(r) {
  return `★註 ${r.comments}件`
    + (r.strings ? `・覚え書き ${r.strings}件` : "")
    + "を 除いて 検べました（字は 残して います）";
}
