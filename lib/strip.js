/** ★消した ぶんを 空白に します。★改行は 残します。 */
function 空白に(s) {
  return s.replace(/[^\n]/g, " ");
}

/**
 * ★共通の 読み取り。★頭から 1文字ずつ 見ます。
 *
 *   ★★★正規表現で 書いて 1度 焼けました（★2026-09-11）。
 *     ★★行コメントの 中の `/*` が、★ブロックの 開きとして 読まれ、
 *       ★★2700字が 本文ごと 消えました。
 *     ★★頭から 読めば、★その 取り違えは 起きません。
 */
function 読む(src, opts, sql) {
  const s = String(src == null ? "" : src);
  const 字を消す = !opts || opts.strings !== false;
  let 出 = "";
  let 註 = 0, 文 = 0;
  let i = 0;
  while (i < s.length) {
    const c = s[i];
    const 次 = s[i + 1];
    // ── ★行の 註 ──
    if ((c === "/" && 次 === "/") || (sql && c === "-" && 次 === "-")) {
      const j = s.indexOf("\n", i);
      const 端 = j < 0 ? s.length : j;
      出 += 空白に(s.slice(i, 端));
      註 += 1;
      i = 端;
      continue;
    }
    // ── ★かたまりの 註 ──
    if (c === "/" && 次 === "*") {
      const j = s.indexOf("*/", i + 2);
      const 端 = j < 0 ? s.length : j + 2;
      出 += 空白に(s.slice(i, 端));
      註 += 1;
      i = 端;
      continue;
    }
    // ── ★字（文字列）──
    if (c === '"' || c === "'" || c === "`") {
      let j = i + 1;
      while (j < s.length) {
        if (s[j] === "\\") { j += 2; continue; }
        if (s[j] === c) { j += 1; break; }
        j += 1;
      }
      const なか = s.slice(i, j);
      出 += 字を消す ? 空白に(なか) : なか;
      if (字を消す) 文 += 1;
      i = j;
      continue;
    }
    出 += c;
    i += 1;
  }
  return { code: 出, comments: 註, strings: 文 };
}

/** ★JavaScript / JSX。★`{ strings:false }` で 字を 残せます。 */
export function stripJs(src, opts) {
  return 読む(src, opts, false);
}

/** ★SQL。★`--` も 註 として 落とします。 */
export function stripSql(src, opts) {
  return 読む(src, opts, true);
}

/** ★検査の 頭に 出す 1行（★黙って 落とさない・裁定 その124）。 */
export function strippedLine(r) {
  return `★註 ${r.comments}件・字 ${r.strings}件を 除いて 検べました`;
}
