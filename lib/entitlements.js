/** 見る人の区分。★支払いは見ていません。 */
export const VIEWERS = ["tester", "general"];

/** その人が tester か。★null / undefined は general に倒します（フェイルクローズ）。 */
export function viewerOf(profile) {
  return profile && profile.is_tester === true ? "tester" : "general";
}

/**
 * その機能を、いま見せてよいか。
 *
 * ★呼ぶ側で profile.is_tester を直に見ないでください。
 *   フェイルクローズの向きが、そこだけ逆になります（年齢の確認と同じ形）。
 */
export function can(viewer, feature) {
  if (!FEATURES.includes(feature)) return true;      // 知らない鍵は止めない
  if (NEVER_GATED.includes(feature)) return true;    // ★念のため。二重の歯止め
  if (!PREVIEW_FEATURES.includes(feature)) return true;  // 出し分けの対象外
  return viewer === "tester";
}

/** 「開発中」と出すか。can() の裏返しですが、画面が読みやすくなるので置きます。 */
export function isInDevelopmentFor(viewer, feature) {
  return !can(viewer, feature);
}

