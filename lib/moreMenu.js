/** ★小見出しの 順（★見本の とおり）。 */
export const MORE_GROUPS = Object.freeze([null, "じぶんの記録", "教室"]);

/**
 * ★その 行を 出してよいか。
 *
 *   ★★「教室」は、★役職の ある方だけです。
 *   ★★「プラン」は、★見本には いつも あります。★押した先で 案内します。
 *     ★お決め「有料のものは 隠しません。見せて、押せなくします」。
 */
export function mayShowMoreRow(key, o) {
  const opt = o || {};
  if (key === "運営") return !!opt.hasOrgRole;
  return true;
}

/** ★いま 出す 行（★小見出しごとに まとめて 返します）。 */
export function moreSections(o) {
  return MORE_GROUPS
    .map((g) => ({
      group: g,
      rows: MORE_ROWS.filter((r) => (r.group || null) === g && mayShowMoreRow(r.key, o))
    }))
    .filter((s) => s.rows.length > 0);
}
