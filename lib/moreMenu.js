/**
 * ★行の 右に 出す 字（★2026-09-15）。
 *
 *   ★★見本は `<s>5つまで ›</s>` ── ★**数と 矢印の 両方**を 1つに 入れて います。
 *   ★★前は `right={r.right || "›"}` でした。★`right` が あると 矢印が
 *     ★**置きかわり**、★「5つまで」だけに なって いました。
 *     ★★ほかの 行は すべて `›` が 出るのに、★この 行 だけ 出ません。
 *     ★★「押すと 何か 開く」印が、★1行だけ 落ちて いました。
 *
 *   ★★決めは ここに 置きます。★画面で `+ "›"` と 書きません。
 *     ★書くと、★行の 決めが 2か所に なります。
 */
export function rightOf(row) {
  const r = row && row.right;
  return r ? r + " ›" : "›";
}

