/**
 * ★札は 無い けれど パンくずも 出さない 画面。
 *
 *   ★「合言葉で入る」── ★まだ 入って いない 人が 見る 画面 です。
 *     ★★もっとへ 戻る 道を ここに 出しません。
 *     ★★これは 札の 有無 では 決まらない ので、★別に 並べます。
 */
export const NO_CRUMB = Object.freeze(["合言葉で入る"]);

/**
 * ★パンくずを 出すか。
 *
 *   ★★節を 開いて いない ときは 出しません（★もっと 自身の 戻る 道が 出ます）。
 *   ★★自分の 札を 持つ 画面の あいだは 出しません（★2つ 並べない）。
 *   ★★`NO_CRUMB` の 画面も 出しません。
 *
 *   ★★★画面の 紙（`VocalTracker.jsx`）に 名を 書かない ため、
 *     ★ここが 唯一の 決め どころ です。
 */
export function showCrumb(section) {
  const s = String(section || "");
  if (!s) return false;
  if (SELF_BACK.includes(s)) return false;
  if (NO_CRUMB.includes(s)) return false;
  return true;
}
