export function nextSort(key) {
  const i = SORTS.findIndex((s) => s.key === key);
  return SORTS[(i < 0 ? 0 : (i + 1) % SORTS.length)].key;
}

export function sortLabel(key) {
  const s = SORTS.find((x) => x.key === key);
  return s ? s.label : SORTS[0].label;
}

