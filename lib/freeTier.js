//   ★★is_tester が true の方は、★ずっと無料です。★門は、かかりません。
//     ★先に使ってくださった方への、★お礼です。
//     ★すでに在る列で、★本人には書けません（引き金で止めてあります）。
//
//   ★★正直に、1つ書き残します。
//     ★この形だと、★きょうより前から使っておられる方でも、
//     ★is_tester でなければ、★門がかかります。
//     ★9月4日の決まり「一度あげたものを、取り上げない」に、★触れます。
//     ★運営者がご承知のうえで決められたので、★そのとおりにします。
//     ★あとで「聞いていない」が起きないように、★ここに書いておきます。
