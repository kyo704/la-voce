/**
 * ★★ふりかえり（週・月・年の集計）を、見てよいか。
 *
 *   ★売るのは、★これです。★記録そのものではありません。
 *   ★名前を mayViewDate にしていました。★危ない名前でした（2026-09-05 夜）。
 *     ★「その日を見てよいか」と読めます。★記録に壁を置く形に、読めてしまいます。
 */
export function mayReviewDate({
  dateISO, todayISO, subscribed = false, createdAt = null,
  gateEnabled = PAID_GATE_ENABLED, gateStartsAt = GATE_STARTS_AT
}) {
  if (!gateEnabled) return true;
  if (subscribed) return true;
  if (isGrandfathered(createdAt, gateStartsAt)) return true;
  return isWithinFreeWindow(dateISO, todayISO);
}

