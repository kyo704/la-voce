export const PAID_GATE_ENABLED = false;

// ---------------------------------------------------------------------------
// ② ★無料で見られる日数
//
//   ★今日と、★きのうまでの7日間。★合わせて8日ぶんが見えます。
//   ★8日前より前が、★有料の側に入ります。
// ---------------------------------------------------------------------------
export const FREE_DAYS = 7;

/**
 * ★その日付が、無料で見られる範囲か。
 *
 *   ★引数は "YYYY-MM-DD" です。★時刻を持ち込まないこと。
 *   ★★時差で、1日ずれます。
 */
export function isWithinFreeWindow(dateISO, todayISO) {
  if (!dateISO || !todayISO) return false;
  const d = Date.parse(dateISO + "T00:00:00Z");
  const t = Date.parse(todayISO + "T00:00:00Z");
  if (Number.isNaN(d) || Number.isNaN(t)) return false;
  // ★未来の日付は、★無料の側にします。★予定を隠さないためです。
  if (d > t) return true;
  const days = Math.round((t - d) / 86400000);
  return days <= FREE_DAYS;
}

// ---------------------------------------------------------------------------
// ③ ★いまお使いの方を、取り上げないこと
//
//   ★★9月4日の決まり ── ★一度あげたものを、取り上げない。
//   ★線を引く前から使っておられる方は、★これまでどおり全部見られます。
//
//   ★引数は profiles.created_at です。★線を引いた日より前なら、そのままです。
//   ★★この日付は、★運営者が決めます。★私が決めません。
//     ★決まるまで null です。★null のあいだは、★誰も取り上げません。
// ---------------------------------------------------------------------------
export const GATE_STARTS_AT = null; // 例）"2026-10-19"

export function isGrandfathered(createdAt, gateStartsAt = GATE_STARTS_AT) {
  if (!gateStartsAt) return true;   // ★日が決まっていないうちは、全員そのまま
  if (!createdAt) return true;      // ★分からないときは、★取り上げない側に倒す
  const c = Date.parse(createdAt);
  const g = Date.parse(gateStartsAt + "T00:00:00Z");
  if (Number.isNaN(c) || Number.isNaN(g)) return true;
  return c < g;
}

