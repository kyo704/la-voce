/** ★まとめの単位。★"day" と "last7" は、無料の側です。 */
export const SUMMARY_SCOPES = Object.freeze(["day", "last7", "week", "month", "year", "compare"]);

// ★無料で見られるまとめ。★直近7日の数字とグラフまでです（裁定 §3）。
export const FREE_SCOPES = Object.freeze(["day", "last7"]);

/**
 * ★分析タブで選んだ期間を、★まとめの単位に translate します。
 *
 *   ★★画面の言葉（analysisPeriod）と、★決めの言葉（scope）を、
 *     ★ここでだけ、つなぎます。★画面で並べ直さないこと。
 *
 *   ★"last7" だけが、★無料です。
 *   ★★"all" も "custom" も "aroundPerformance" も、★まとめです。
 *     ★期間が長いほど、★計算した数の色が濃くなります。
 */
export function scopeForPeriod(period) {
  if (period === "last7") return "last7";
  if (period === "week") return "week";
  if (period === "month") return "month";
  if (period === "year") return "year";
  // ★all／custom／aroundPerformance／知らない値は、まとめ扱いにします。
  //   ★★知らない値を無料側に倒さないこと。★増やした人が、門を素通りします。
  return "compare";
}

/**
 * ★こちらが計算した数を、見てよいか。
 *
 *   ★★本人が書いた数を、そのまま見せる画面には、★使わないこと。
 *     ★そちらは mayViewRecord() です。★いつでも true です。
 *
 *   ★subscribed は、★サーバから来たものを渡すこと。
 *     ★★localStorage に持たないこと（権利と課金の線引き §2-2）。
 */
export function mayViewSummary({
  scope, profile = null, subscribed = false,
  gateEnabled = PAID_GATE_ENABLED, gateStartsAt = GATE_STARTS_AT
}) {
  if (FREE_SCOPES.includes(scope)) return true;
  // ★門が開いていなければ、★全部見られます。
  if (!gateEnabled || !gateStartsAt) return true;
  if (subscribed) return true;
  if (isAlwaysFree(profile)) return true;
  return false;
}

