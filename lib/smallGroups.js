// 5人未満の かたまりを 出さない（2026-09-10）
//
//   ★出どころ 坂本さん経由・Opus（2026-09-10）
//     「★5人未満の かたまりを 出さない、という 安全策も、
//       ★統計表示の 実装に 反映してください」
//
//   ★★なぜ 要るのか
//     ★「3年生（3人）のうち 2人が 出ます」と 出したとします。
//     ★★誰が 出ないかは、★3人の 中では すぐ 分かります。
//     ★★数だけを 出したつもりが、★1人を 名指ししたのと 同じに なります。
//     ★人数が 小さいほど、★数は 名前に 近づきます。
//
//   ★★だから、★かたまりが 5人に 満たなければ、★数を 出しません。
//     ★★「0人です」とも 言いません。★0 も 中身の 1つです。
//     ★出すのは「まだ 出せません」という 断りだけです。
//
//   ★★合計は 出せます。★分けたときにだけ 効きます。
//     ★54人 のうち 41人、は 出せます。
//     ★★3年生（3人）のうち 2人、は 出せません。
//
//   ★★この決めは、★ここ1か所です。★画面ごとに 書きません。
//
//   ★見張り components/tests/small-groups.test.js
// ============================================================================

/** ★これに 満たない かたまりは、★数を 出しません。 */
export const MIN_GROUP = 5;

/** ★出せないときの 断り。★責める言葉に しません。 */
export const TOO_SMALL_NOTE = "人数が少ないため、内訳は出していません。";

/**
 * ★その かたまりの 数を、★出してよいか。
 *
 *   @param size ★その かたまりの 人数（★分母）
 *
 *   ★★分子では なく、★分母で 決めます。
 *     ★★分子が 0 でも、★分母が 小さければ 危ういからです。
 *     ★「3人のうち 0人」は、★3人 全員を 名指しします。
 */
export function mayShowGroup(size) {
  const n = Number(size);
  return Number.isFinite(n) && n >= MIN_GROUP;
}

/**
 * ★かたまりの 数を、★言葉に します。
 *
 *   @returns 文字列 ／ ★出せないときは null
 *
 *   ★★null を 返します。★0 や "—" を 返しません。
 *     ★呼ぶ側が「出さない」を 選べるように します。
 */
export function groupCountWord(part, size) {
  if (!mayShowGroup(size)) return null;
  return `${Number(part) || 0}/${Number(size)}`;
}

/**
 * ★内訳の 並びから、★出せない ものを 落とします。
 *
 *   @param rows [{ label, part, size }]
 *
 *   ★★落とした ことを、★呼ぶ側に 伝えます（hidden）。
 *     ★★黙って 減らしません。★「一部を 出していません」と 言えるように します。
 */
export function filterGroups(rows) {
  const all = rows || [];
  const shown = all.filter((r) => r && mayShowGroup(r.size));
  return { shown, hidden: all.length - shown.length };
}

/**
 * ★ようす ごとの 数を、★出してよいか（★名簿の 下の 帯）。
 *
 *   ★★ここは、★分けた かたまりです。★休会中 2人、と 出すと、
 *     ★★54人の 中の 2人が 誰かを、★近い人は 見当が つきます。
 *   ★★ですが、★運営の方には 要る 数でも あります（★お支払いの 人数）。
 *   ★★だから「数える人数」は 出し、★内訳（休会・返事まち）だけを 隠します。
 *     ★合計は かたまりでは ありません。★内訳が かたまりです。
 */
export function safeBreakdown(counts) {
  const c = counts || {};
  const out = {};
  ["paused", "invited"].forEach((k) => {
    const n = Number(c[k]) || 0;
    // ★★0 は 出します。★0 は「誰も いない」であって、★誰かを 指しません。
    //   ★★1〜4 が いちばん 危ういので、★そこだけ 隠します。
    out[k] = (n === 0 || n >= MIN_GROUP) ? n : null;
  });
  return out;
}
