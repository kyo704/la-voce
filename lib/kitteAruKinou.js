/**
 * ★並べ替え。★台帳が `order by f.key` で 返しますが、★こちらでも 決めます。
 *
 *   ★★理由 ── ★出発の 朝に 見る 一覧 です。★並びが 変わると 見落とします。
 *     ★台帳の 並びに 頼ると、★関数を 直した 日に 黙って 変わります。
 */
export function sortRows(rows) {
  const list = Array.isArray(rows) ? rows.filter((r) => r && r.key) : [];
  return [...list].sort((a, b) => String(a.key).localeCompare(String(b.key)));
}

