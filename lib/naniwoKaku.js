/**
 * ★出す 行（★種と、★いま 何件 ある か）。
 *
 *   ★★`entries` は `portfolio_entries` の 行 です。
 *   ★★0件の ときは 数を 出しません（★見本 `(c?c+'件':'')`）。
 *     ★★★0を 出すと、★「まだ 何も して いない」と 責める 形に なります。
 */
export function rowsOf(field, entries) {
  const 行 = Array.isArray(entries) ? entries.filter(Boolean) : [];
  return enabledKinds(field).map((k) => {
    const n = 行.filter((e) => e.kind === k.key).length;
    return { key: k.key, label: k.label, count: n, right: n > 0 ? String(n) + "件" : "" };
  });
}

