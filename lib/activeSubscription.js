/**
 * ★止める べき 状態か。
 *
 *   ★★`status` は Stripe の ことば です。★こちらで 言い換えません。
 *   ★★止めるのは「★お金が これから 動く」状態だけ です。
 *     ★`canceled` や `incomplete_expired` は 動きません。★止めません。
 *   ★★`trialing` は 止めます ── ★そのままだと 課金が 始まります。
 *   ★★`past_due` / `unpaid` も 止めます ── ★取り立てが 続きます。
 */
export const BLOCKING_STATUSES = Object.freeze([
  "active", "trialing", "past_due", "unpaid", "incomplete"
]);

/**
 * ★その 行が、★退会を 止める ものか。
 *
 *   @param sub ★`subscriptions` の 1行（★無ければ null）
 */
export function blocksDeletion(sub) {
  if (!sub) return false;
  return BLOCKING_STATUSES.includes(String(sub.status || ""));
}

