// ★読めなかった、と 言う ための 1か所（★2026-09-20）
//
//   ★★★「無い」と「読めなかった」は 別 です。
//     ★★2026-09-20、★日程の 表が 丸1日 空の ままでした。
//       ★★台帳は 断って いました。★画面は「この 日に コマは ありません」と
//         ★★言い切って いました。★どちらか 分かりません でした。
//   ★★★検査4（★`tools/insp_same_shape.py`）が、★同じ 形を 13か所 数えました。
//     ★★`setX(res.error ? [] : res.data)` ── ★断りを 空の 一覧に 変えて います。
//
//   ★★ここが 持つ 決め ── ★字 と、★「読めた か」の 見分け。
//     ★★字を 画面ごとに 書きません。★1つに します。
//
//   ★見張り components/tests/read-fail.test.js
// ============================================================================

export const READ_FAILED_SUB = "しばらく してから、もう一度 お試し ください。";

/**
 * ★読めなかった ときの 1行。
 *
 *   ★★`名` …… ★何を 読もうと したか（★れい「空きコマ」）。
 *   ★★符号（`code`）が あれば 添えます。★次に 調べる 方の 手がかり です。
 */
export function readFailedLine(名, err) {
  const c = (err && (err.code || err.status)) || "";
  const n = String(名 || "").trim();
  return `${n ? n + "を " : ""}読めませんでした。${c ? `（${c}）` : ""}`;
}

/**
 * ★引いた 返りを、★行と「読めたか」に 分けます。
 *
 *   ★★★空の 一覧を 返しても、★`failed` を 見れば 見分けられます。
 *     ★★画面は `failed` の ときだけ、★「読めませんでした」と 出します。
 *   ★★`res` が 無い ときも、★読めなかった と します（★安全な 側へ）。
 */
export function rowsOf(res, 名) {
  if (!res || res.error) {
    return { rows: [], failed: true, line: readFailedLine(名, res && res.error) };
  }
  return { rows: res.data || [], failed: false, line: "" };
}
