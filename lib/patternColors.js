/**
 * ★柄の2色目を、決めます。
 *
 *   ★★お客さまには、選ばせません（★坂本さんのお決め）。
 *     ★1色目から、★表を引いて 決めます。
 *
 *   ★★1色目を選んでいないとき（★もとの色）は、
 *     ★焼かれたときの2色目を、そのまま返します。
 *     ★★見える絵と、同じになります。
 *
 *   @param itemKey   品の鍵
 *   @param firstKey  1色目の鍵（★24色のどれか。★選んでいなければ null）
 */
export function secondColorKey(firstKey) {
  return firstKey ? (SECOND_BY_FIRST[firstKey] || null) : null;
}

export function secondColor(itemKey, firstKey, hexToRgb, paintHex) {
  const k = secondColorKey(firstKey);
  if (k && typeof paintHex === "function" && typeof hexToRgb === "function") {
    const hex = paintHex(k);
    if (hex) return hexToRgb(hex);
  }
  // ★★1色目を選んでいないとき（★もとの色）は、焼かれた色のまま。
  const c = BURNED_SECOND[itemKey];
  return c ? [c[0], c[1], c[2]] : null;
}

/** ★柄ものか（★2色目を持っているか）。 */
export function hasPattern(itemKey) {
  return Object.prototype.hasOwnProperty.call(BURNED_SECOND, itemKey);
}

/** ★柄の型の、絵の在りか。 */
export function maskSrc(itemKey) {
  return "/sheep/mask/" + itemKey + ".png";
}
