/** 撤回した時刻。撤回していなければ null。 */
export function withdrawnAt(profile) {
  const v = profile && profile.consent_health_data_withdrawn_at;
  return v ? String(v) : null;
}

/**
 * 健康の記録を、新しく書いてよいか。
 *
 * ★entries と cycle_periods の★書き込み口が、ここだけを見ます。
 * ★削除は、この門を通しません。★いつでもできます。
 */
export function mayWriteRecords(profile) {
  return withdrawnAt(profile) == null;
}

/**
 * その人のデータを、分析に使ってよいか。
 *
 * ★分析は、その人の端末で、その人のデータから作られます。
 *   ★どこかに送って集計しているわけではありません。
 *   ★だから「使わない」は「作らない・出さない」と同じことです。
 * ★これまでの記録そのものは、★見られます。止めるのは分析だけです。
 */
export function mayUseForAnalysis(profile) {
  return withdrawnAt(profile) == null;
}
