/**
 * 止めている機能。
 *
 *   key        コードから参照する鍵
 *   label      画面に出ていた名前
 *   since      止めた日
 *   why        なぜ止めたか（★事実だけ。言い訳を書かない）
 *   evidence   そう判断した根拠
 *   resumeWhen 何ができたら戻すか
 *   dataPolicy 既存のデータをどうするか
 */
export const PAUSED_FEATURES = [
  {
    key: "measure.cpps",
    label: "客観測定（CPPS）",
    since: "2026-09-01",
    why: "計算が仕様どおりではなく、値が実際より低く出ます。数字が信用できません。",
    evidence: [
      "雑音ゼロの合成母音でも 1.56〜7.11 にしかならない（Praat は 15〜20 dB）",
      "同じ周期性でも F0 で値が変わる（110Hz:1.56 / 220Hz:4.72 / 330Hz:7.11）。",
      "FFT の大きさを 2048→16384 に増やしても、この依存は消えない",
      "平滑化をしていない（CPPS の S）。中央値ではなく平均を取っている",
      "憲章 §1-7 の品質ゲート（暗騒音・クリッピング・オクターブ跳び・有効フレーム率70%）が1つも実装されていない"
    ],
    resumeWhen: [
      "平滑化と中央値を仕様どおりに実装する",
      "§1-7 の品質ゲートを入れる",
      "★Praat で測った既知の音声と突き合わせて、値が一致することを確かめる"
    ],
    dataPolicy:
      "★既存の cpps_value は消しません。埋めもしません。新しく増やさないだけです。" +
      "列も残します。過去に測った値は、当時そう表示されていた事実の記録です。"
  }
];

export function isPaused(key) {
  return PAUSED_FEATURES.some((f) => f.key === key);
}

export function pausedFeature(key) {
  return PAUSED_FEATURES.find((f) => f.key === key) || null;
}

/** CPPS を画面に出してよいか。★止めているあいだは false。 */
export const CPPS_ENABLED = !isPaused("measure.cpps");
