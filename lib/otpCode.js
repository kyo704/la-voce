// ★Supabase が出せる範囲です（6〜10）。
//   ★★これは「決め打ち」ではなく、★受け入れる幅です。
//   ★下限より短いものは、★打ち間違いとして扱います。
export const OTP_MIN_LENGTH = 6;
export const OTP_MAX_LENGTH = 10;

// ★数字だけにして、★長すぎる分を落とします。
//   ★★貼り付けで、前後に空白や改行が付いてくることがあります。
export function normalizeOtp(input) {
  if (typeof input !== "string") return "";
  return input.normalize("NFKC").replace(/[^0-9]/g, "").slice(0, OTP_MAX_LENGTH);
}

// ★送ってよい形かどうか。
//   ★★長さを決め打ちで比べないこと。
export function isSendableOtp(input) {
  return normalizeOtp(input).length >= OTP_MIN_LENGTH;
}

