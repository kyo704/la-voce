// ============================================================================
// 月経周期の「文言」を、誰にどう見せるか
//
//   ★機能そのものは、誰に対しても止めません（未成年を含む）。
//     初潮は多くの場合18歳よりずっと前です。記録を止めることは、
//     いちばん必要な人から自己管理の道具を取り上げることになります。
//     lib/ageGate.js が守っているのは「外へ出ていくこと」——
//     研究利用への同意（法的な有効性）と、先生とつながること（保護者の確認）——
//     であって、自分のための記録ではありません。
//
//   ★ここで扱うのは、そのどちらでもない3つ目の話です。
//     「使っていない人にも、話題だけが目に入る」状態を減らします。
//
//     ① 書き出しの説明と、退会の確認の一覧
//        → これまで、周期を記録していない人にも「月経周期」と出ていました。
//          ★関係のある人にだけ出します。年齢に関係なく、全員に対してです。
//          （記録していない人に見せる理由が、そもそもありません）
//
//     ② 設定のオプトインの説明文
//        → ★消しません。消すと、切り替えだけがあって説明が無い状態になり、
//          「何が起きるのか分からないまま選ぶ」ことになります。
//          未成年には★短い言い方にします（消すのではなく、整えます）。
// ============================================================================

import { isTreatedAsMinor } from "./ageGate.js";

/**
 * 書き出し・退会の一覧に「月経周期」を並べてよいか。
 *
 * ★年齢では決めません。使っているかどうかで決めます。
 *   使っていない人に見せる理由が無いためです。
 */
export function mentionsCycleInDataLists(profile) {
  return !!(profile && profile.track_cycle);
}

/** 設定の切り替えに添える説明。★未成年にも必ず何かを返します（空にしない）。 */
export function cycleOptInDescription(profile) {
  if (isTreatedAsMinor(profile)) {
    // ★短くします。何が起きるかは伝わり、話題の広がりは持たせない。
    return "周期開始日を1タップで記録できます。任意です。";
  }
  return "周期開始日を1タップで記録し、分析タブで声・メンタルとの関連を見られるようにします。任意（オプトイン）です。";
}
