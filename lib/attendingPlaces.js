/**
 * ★1つの 教室の 添え字（★見本 `.rep .s`）。
 *
 *   ★★見本 …「音楽教室　／　鈴木 かおる 先生　／　2026年6月10日から」
 *   ★★読めない ところは **飛ばします**。★「不明」と 書きません。
 *     ★★埋めると、★読めなかった ことが 隠れます。
 */
export function placeSubtitle({ teacher, since } = {}) {
  // ★★★教室の 種類（`kind`）は **出しません**（★Opus の 裁定・2026-09-16）。
  //   ★★台帳は solo 19件／studio 0件。★19件とも 同じ 値 です。
  //     ★★出しても、★全員に 同じ 字が 並ぶ だけ で、★何も 伝えて いません。
  //   ★★見本の「大学」も、★絵として 書かれた もので、★根拠が ありません。
  //   ★★決め打ちで「個人レッスン」と 書くと、★こちらが 名乗り方を 決めます。
  //     ★★声優養成所・合唱団・ミュージカルスクールが 入って きた とき 誤りに なります。
  //     ★★一度 出した 字は、★消すのが 難しい です。
  //   ★★先生が ご自分で 名乗れる ように する のは、★あと の 仕事 です（★台帳に 登録）。
  const parts = [];
  if (teacher) parts.push(teacher + " 先生");
  if (since) parts.push(since + "から");
  return parts.join("　／　");
}

/**
 * ★日付を、★見本の 形に します（★「2026年6月10日」）。
 *
 *   ★★読めない ときは `null` を 返します。★きょうの 日付で 埋めません。
 */
export function joinedLabel(iso) {
  if (!iso) return null;
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return null;
  return d.getFullYear() + "年" + (d.getMonth() + 1) + "月" + d.getDate() + "日";
}

