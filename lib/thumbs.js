/** ★小さい絵の 置き場所。 */
export const THUMB_BASE = "/sheep/thumbs/";

/** ★小さい絵の 一辺（★1マス72px の 2倍）。 */
export const THUMB_PX = 144;

/**
 * ★一覧に出す、小さい絵の みちすじ。
 *
 *   ★★持ちものだけ、★置き場所（左・右・両手）で 絵が 変わります。
 *     ★そのときは、★鍵の うしろに 付けます（★作るときと 同じ形）。
 *
 *   @param key  品の鍵
 *   @param side 持ちものの 置き場所（★ほかの品では null）
 */
export function thumbSrc(key, side) {
  if (!key) return null;
  return THUMB_BASE + key + (side ? "__" + side : "") + ".png";
}
