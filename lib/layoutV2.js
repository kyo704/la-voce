/**
 * ★新しい画面を、出してよい方か。
 *
 *   ★★名簿が 空なら false。★読めなければ false。
 *     ★★falseの側に 倒します。★迷ったら 変えない、が 安全です。
 */
export function mayUseLayoutV2(userId, env) {
  const raw = (env && env.NEXT_PUBLIC_LAYOUT_V2_USER_IDS) || "";
  const ids = String(raw).split(",").map((s) => s.trim()).filter(Boolean);
  if (ids.length === 0) return false;
  return ids.includes(String(userId || ""));
}

