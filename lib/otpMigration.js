// ---------------------------------------------------------------------------
// ④ ★移る前に、必ず済ませること
//
//   ★★復旧コードを、★先にお渡しします。
//     ★パスワードを外してから渡すと、★その間、★逃げ道がありません。
//     ★★順番を入れ替えないこと。
// ---------------------------------------------------------------------------
export const MIGRATION_STEPS = Object.freeze([
  "explain",        // ★何が変わるかを、先に書く
  "recovery_code",  // ★★復旧コードをお渡しする（★ここが先）
  "verify_otp",     // ★6桁で、いちど入っていただく（★届くことを確かめる）
  "drop_password"   // ★そのあとで、パスワードを外す
]);

export function nextMigrationStep(done) {
  const list = Array.isArray(done) ? done : [];
  for (const step of MIGRATION_STEPS) {
    if (!list.includes(step)) return step;
  }
  return null; // ★ぜんぶ済みました
}

// ★★途中で閉じられたら、★そこから続けられること。
//   ★「パスワードを外した」だけが残る形に、★絶対にしないこと。
export function migrationLeftUnsafe(done) {
  const list = Array.isArray(done) ? done : [];
  return list.includes("drop_password") && !list.includes("recovery_code");
}
