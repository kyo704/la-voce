export const OTP_MIGRATION_ROLLOUT_ENABLED = false;

// ---------------------------------------------------------------------------
// ② ★お誘いを出してよいか
//
//   ★★1回だけです。★断られたら、二度と出しません。
//     ★9月4日の決まり ── 催促しない。
//
//   ★引数は、★サーバが調べたものだけを受け取ります。
//     ★hasPassword は、★auth.users を見ないと分かりません。
//     ★★だから、★ブラウザの側で組み立てないこと。
// ---------------------------------------------------------------------------
export function mayShowMigrationPrompt({
  rolloutEnabled = OTP_MIGRATION_ROLLOUT_ENABLED,
  hasPassword,
  declinedAt,
  completedAt
} = {}) {
  // ★★出すと決めていないうちは、★何があっても出しません。
  if (!rolloutEnabled) return false;
  // ★パスワードをお持ちでない方には、★移る先がありません。
  if (!hasPassword) return false;
  // ★もう移られた方に、★もう一度は出しません。
  if (completedAt) return false;
  // ★★一度断られたら、二度と出しません。★催促しないこと。
  if (declinedAt) return false;
  return true;
}

// ---------------------------------------------------------------------------
