// ★★★毎日の 見張り ── ★決まりの 控えの 道具が、★ちゃんと 見つけるか
//
//   ★出どころ  Opus（2026-09-23）──
//     「★policy_diff を 毎日の 見張りに 入れて ください。
//       『先生は 生徒の 記録を 見られない』を 壊す 変更は、
//       ★必ず ポリシーの 変更として 現れます」
//
//   ★★ここで 走らせるのは `--selftest` だけ です。
//     ★★本物の 控えを 取るのは 人の 仕事（★1日 1回）。★網に つなぎません。
//     ★★★けれど「道具が 壊れて いない こと」は 毎日 見ます。
//       ★★道具が 黙って 壊れたら、★見張りが 無いのと 同じ です（★2026-09-23 の contrast）。
//
//   ★★`--selftest` は、★くらべる ところ だけ では なく
//     ★**本番を 1回 読む ところ**も 試します。★そこが 空なら 落ちます。
// ============================================================================
const { spawnSync } = require("child_process");
const path = require("path");

const 道 = path.join(__dirname, "..", "..", "tools", "policy_diff.py");
const r = spawnSync("python3", [道, "--selftest"], { encoding: "utf8" });
const 出 = (r.stdout || "") + (r.stderr || "");
console.log(出.trim());

let 落ち = 0;
function t(cond, label) {
  if (cond) console.log("  ok   " + label);
  else { console.log("  NG   " + label); 落ち++; }
}
t(r.status === 0, "★当たり合わせが 通った");
t(/★決まりの 中身が 変わる[\s\S]{0,40}★見つけました/.test(出), "★中身の 変わりを 見つける");
t(/★決まりが 消える[\s\S]{0,40}★見つけました/.test(出), "★決まりが 消えたのを 見つける");
t(/★RLS が 切られる[\s\S]{0,40}★見つけました/.test(出), "★RLS が 切られたのを 見つける");
t(/控える ところ[\s\S]{0,60}★読めました/.test(出), "★本番を 読む ところも 生きて いる");

console.log(落ち === 0 ? "\n★すべて 通りました" : "\n★" + 落ち + "件 落ちました");
process.exit(落ち === 0 ? 0 : 1);
