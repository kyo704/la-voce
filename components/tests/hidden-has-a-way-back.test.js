const { readRaw, stripComments } = require("./_source");

let 落ちた = 0;
function たしかめる(名, 条件, 言い分) {
  if (条件) { console.log("  ○ " + 名); return; }
  落ちた += 1;
  console.log("  × " + 名 + "  …… " + 言い分);
}

const 生 = readRaw("components", "VocalTracker.jsx");
const 行 = 生.split("\n");
const 本 = stripComments(生);

// ★★★門の 外だけ の 枝の 中に ある もの は 隠して いません。
//   ★★`!layoutV2 ?` の 枝の 中 では `inMore` は `undefined` を 返します。
const 隠した = new Set();
行.forEach((l, i) => {
  const m = /inMore\("([^"]+)"\)/.exec(l);
  if (!m) return;
  const 上 = 行.slice(Math.max(0, i - 40), i).join("\n");
  if (/!layoutV2 \?/.test(上)) return;
  隠した.add(m[1]);
});
const 開ける = new Set(
  (本.match(/setMoreSection\("([^"]+)"\)/g) || [])
    .map((s) => s.replace(/^setMoreSection\("/, "").replace(/"\)$/, ""))
);

たしかめる("★隠して いる 節を 数えられた", 隠した.size > 0,
  "★1つも 見つかりません ── ★数え方が 壊れて います");

const 道無し = [...隠した].filter((n) => !開ける.has(n));
たしかめる("★隠した 節には すべて 開ける 道が ある", 道無し.length === 0,
  "★戻る 道が ありません …… " + 道無し.join("・")
  + "  ★★消すか、★たどり着ける 場所へ 移してください（★隠した まま に しません）");

// ★★★`inMore` を 通さない 直書きが 増えて いない こと。
//   ★★数を 覚えません ── ★`inMore` を 通した ものと くらべます。
const 直 = (本.match(/display:\s*"none"/g) || []).length;
const 通 = (本.match(/inMore\(/g) || []).length;
たしかめる("★隠すのは `inMore` を 通す ほうが 多い", 直 < 通,
  `★直書き ${直} ／ ★\`inMore\` ${通} ── ★直書きは 戻る 道を 数えられません`);

console.log(落ちた === 0 ? "RESULT: OK" : "RESULT: NG (" + 落ちた + ")");
process.exit(落ちた === 0 ? 0 : 1);
