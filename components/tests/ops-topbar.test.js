// ============================================================================
// ★見張り ── ★運営の 上の 帯（★裁定 2026-09-18・⑧）
//
//   ★出どころ 見本 00-動く見本-PC・iPad（運営）.html の `class="top"`
//
//   ★★見本の 右がわ に ある もの ── ★6つ
//     ★1 未送信 N件　★2 役職の名　★3 お名前
//     ★4 あ ふつう（文字の 大きさ）　★5 ◐ 端末に合わせる（明るさ）　★6 ↻
//
//   ★★★きょう 置いた のは 2つ（★2 と 3）です。
//     ★★あと の 4つは 置いて いません。★理由は 下に 書きます。
//     ★★この 見張りは、★置いた 2つ が ある ことを 見ます。
//       ★★置いて いない 4つを「無い」と 責めません。
//       ★★お決めを いただく まで、★押せない 札を 置きません（★§8⑤）。
// ============================================================================

const assert = require("assert");
const fs = require("fs");
const path = require("path");
const { readCode, readRaw } = require("./_source");

const ROOT = path.join(__dirname, "..", "..");
const 見本の道 = path.join(ROOT, "docs/design/pack-final/00-動く見本-PC・iPad（運営）.html");

let 数 = 0;
function ok(cond, 名) {
  数 += 1;
  assert.ok(cond, "★落ちました ── " + 名);
  console.log("  ok  " + 名);
}

// ★★較正 ── ★見本に 上の 帯が 無ければ 止まります。
if (!fs.existsSync(見本の道)) {
  console.error("★止まりました ── 見本が ありません: " + 見本の道);
  process.exit(1);
}
const 見本 = fs.readFileSync(見本の道, "utf8");
assert.ok(/<div class="top"><div class="l">/.test(見本),
  "★止まりました ── 見本に 上の 帯が ありません。★測りの ほうを 疑って ください。");

const 殻 = readRaw("components", "OpsShell.jsx");
const 本体 = readRaw("components", "VocalTracker.jsx");

// ------------------------------------------------------------------------
// ★一 ★役職の 名が 出て いるか
// ------------------------------------------------------------------------
ok(/postName/.test(殻), "殻が 役職の 名を 受け取る");
ok(/postName \? \(/.test(殻), "役職の 名が あれば、★それを 出す");
ok(/typeof role === "string" \? role : "役職"/.test(殻),
  "名が 無い ときは、★これまでどおり「役職」");
ok(/postName=\{opsMembership/.test(本体), "名を 渡して いる");
ok(/opsPostsById\[opsMembership\.post_id\]/.test(本体),
  "名は できことと **同じ ところ** から 取る");

// ------------------------------------------------------------------------
// ★二 ★お名前が 出て いるか
// ------------------------------------------------------------------------
ok(/myName/.test(殻), "殻が お名前を 受け取る");
ok(/myName=\{profile/.test(本体), "お名前を 渡して いる");
ok(/display_name/.test(本体.slice(本体.indexOf("myName=\{profile"),
  本体.indexOf("myName=\{profile") + 120)),
  "お名前は ご本人の display_name");

// ------------------------------------------------------------------------
// ★三 ★置いて いない もの を、★押せない 札に して いないか
// ------------------------------------------------------------------------
//   ★★見本の ↻ は「最初から やり直す」── ★見本を 試す ため の もの です。
//     ★★品では ありません。★だから 置きません。
const コード = readCode("components", "OpsShell.jsx");
ok(!/location\.reload/.test(コード), "↻（やり直す）を 置いて いない");
ok(!/disabled/.test(コード), "押せない 札が 1つも ない（★§8⑤）");

// ★★文字の 大きさ と 明るさ は、★すでに 別の ところに あります。
//   ★★ここに 2つめを 置くと、★同じ 決めが 2か所に なります。
ok(!/zCycle|thCycle|文字を 大きく/.test(コード),
  "文字の 大きさ・明るさ の 2つめを 置いて いない");

console.log("\n★" + 数 + "件 通りました ── 運営の 上の 帯");
