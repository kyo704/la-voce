// ★名簿の 二段組・数えないもの・但し書き（★裁定 その84 NEW_ORDER 2・2026-09-18）
//
//   ★出どころ 見本 `P_meibo`（★`00-動く見本-PC・iPad（運営）.html`）
//            ★坂本さんの お決め 1・2・3（2026-09-18）
//
//   ★★見る の は 5つ。
//     ★【一】★二段組の 境目を、★新しく 作って いない か
//     ★【二】★ご請求の 中身が 1つ か（★上と 下で 写して いない か）
//     ★【三】★「数えないもの」が 出て いる か
//     ★【四】★但し書きの 3行（★1行目は 太字）
//     ★【五】★`.ff-display` を 外した か
// ============================================================================

const { readCode, readRaw, loadLib } = require("./_source");

let ok = 0, ng = 0;
function t(cond, label) {
  if (cond) { ok++; console.log("  ○ " + label); }
  else { ng++; console.log("  ✗ " + label); }
}

(async () => {
  const R = await loadLib("lib", "orgRoster.js");
  const T = await loadLib("lib", "opsRosterTable.js");
  const 画面 = readRaw("components", "OpsRoster.jsx");
  const 本文 = readCode("components", "OpsRoster.jsx");

  // -------------------------------------------------------------------------
  // 【一】★境目
  // -------------------------------------------------------------------------
  console.log("【一】二段組の 境目を 新しく 作って いない");
  t(/const 二段 = showRosterTable\(winW\);/.test(画面),
    "★表を 出す 境目と 同じ もの を 使って いる");
  // ★★★数を 直に 書いて いない こと。
  //   ★★2つ 目の 境目を 作ると、★表は 出て いるのに 右の 欄が 無い 幅が できます。
  t(!/winW\s*>=?\s*\d{3}/.test(本文), "★幅の 数を 直に 書いて いない");
  t(typeof T.ROSTER_TABLE_AT === "number", "境目は lib が 持つ（" + T.ROSTER_TABLE_AT + "）");
  // ★★道具の 較正。
  t(/winW\s*>=?\s*\d{3}/.test("if (winW >= 885) {}"), "★わざとの 1件（直の 数）を 見つけられる");
  t(/alignItems: "flex-start"/.test(画面), "★見本の `align-items:flex-start` が ある");
  t(/flex: 3/.test(画面) && /minWidth: 230/.test(画面), "★左 3 ／ 右 min 230（★見本の まま）");
  t(/position: "sticky"/.test(画面), "★右の 欄を 貼りつけて いる（★見本の 但し書き）");

  // -------------------------------------------------------------------------
  // 【二】★ご請求の 中身は 1つ
  // -------------------------------------------------------------------------
  console.log("【二】ご請求の 中身は 1つ");
  t((画面.match(/function 請求の中身\(\)/g) || []).length === 1, "中身の 関数は 1つ");
  t((画面.match(/請求の中身\(\)/g) || []).length >= 3, "上でも 下でも 同じ ものを 呼ぶ");
  // ★★★同じ 字を 2回 書いて いない こと。
  t((本文.match(/今月のご請求/g) || []).length === 1, "「今月のご請求」は 1か所");
  t((本文.match(/数える人数/g) || []).length === 1, "「数える人数」は 1か所");
  // ★★狭い ときだけ 下に 貼りつく こと（★同じ 数を 2か所に 出さない）。
  t(/\{二段 \? null : \(/.test(画面), "★二段組の ときは 下の 帯を 出さない");

  // -------------------------------------------------------------------------
  // 【三】★数えないもの
  // -------------------------------------------------------------------------
  console.log("【三】数えないもの（★見本の 2枚目）");
  t(R.NOT_COUNTED_HEAD === "数えないもの", "題が 見本の まま");
  const 行 = R.notCountedRows();
  t(行.length === 4, "4行 ある");
  t(行.map((x) => x.name).join("／") === "休会／招待中／先生・事務／5人まで",
    "並びが 見本の まま（" + 行.map((x) => x.name).join("／") + "）");
  t(行[3].value === "0円", "5人までは 0円");
  // ★★★「5人」は `FREE_UP_TO` から 引く こと。★書き写さない こと。
  t(R.FREE_UP_TO === 5, "0円の 上限が 名前に なって いる");
  t(!/5人まで/.test(readCode("components", "OpsRoster.jsx")), "★画面が 5 を 書き写して いない");
  // ★★式と 画面が 同じ 数を 見て いる こと。
  t(R.monthlyFee(R.FREE_UP_TO) === 0, "5人は 0円");
  t(R.monthlyFee(R.FREE_UP_TO + 1) > 0, "6人から 0円で ない");
  t(本文.includes("notCountedRows"), "画面が lib から もらって いる");
  // ★★狭い ときも 出す こと（★見本の 2枚目は 消えません）。
  t(/\{二段 \? null : 数えないものの箱\(\)\}/.test(画面), "★狭い ときも 出す");

  // -------------------------------------------------------------------------
  // 【四】★但し書き
  // -------------------------------------------------------------------------
  console.log("【四】但し書き（★3行・1行目は 太字）");
  const 注 = R.rosterNotes();
  t(注.length === 3, "3行 ある");
  t(注[0] === R.ROSTER_NOTE_BOLD, "1行目が 太字の 行");
  t(注[0].includes("健康"), "1行目は 健康の 断り");
  // ★★★「税別」を 書き写して いない こと。
  t(注[2].includes(R.PRICE_TAX_LABEL), "3行目が 税の 書き方を 名前で 引いて いる");
  t(!/税別/.test(本文), "★画面が「税別」を 書き写して いない");
  t(本文.includes("rosterNotes"), "画面が lib から もらって いる");
  t(/<b style=\{\{ color: C\.ink \}\}>/.test(画面), "1行目を 太く して いる");

  // -------------------------------------------------------------------------
  // 【五】★書体
  // -------------------------------------------------------------------------
  console.log("【五】門の中では .ff-display を 使わない");
  t(!/ff-display/.test(本文), "★名簿に `.ff-display` が ない");
  // ★★道具の 較正。
  t(/ff-display/.test('className="ff-display italic"'), "★わざとの 1件を 見つけられる");
  // ★★決めの 出どころが 残って いる こと。
  t(readRaw("lib", "uiKit.js").includes(".ff-display を 使いません"),
    "★決めは uiKit に ある");

  // -------------------------------------------------------------------------
  // 【六】★人数の 1行
  // -------------------------------------------------------------------------
  console.log("【六】人数の 1行（★見本の .sub）");
  const 行文 = R.rosterSubLine(54, 48);
  t(行文.includes("54人") && 行文.includes("在籍 48人"), "数が 入る");
  t(行文.includes("＝ご請求の 人数"), "★お金の 話だ と 分かる 印が ある");
  t(行文.includes("休会・退会・招待中は 数えません"), "数えない ものを 書いて いる");
  t(本文.includes("rosterSubLine"), "画面が lib から もらって いる");

  console.log(`\n○ ${ok}　✗ ${ng}`);
  process.exit(ng === 0 ? 0 : 1);
})();
