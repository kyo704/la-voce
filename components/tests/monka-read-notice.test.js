// ============================================================================
// ★見張り ── ★門下の やりとりを 確かめる こと を、★先に お伝えして いるか
//             （★裁定 その76 訂正版 ② ／ 追補・2026-09-18）
//
//   ★★★`monka_read` を 作る **前** に、★学生に お伝えする ため の 見張り です。
//     ★★黙って 読める 仕組みを、★作らない ため です。
//
//   ★★測る のは 4つ です。
//     ★一 ★入る ときの 承知に、★確かめる ことが ある、と 書いて あるか
//     ★二 ★同じ ところに、★健康の 記録は 誰も 見られない、と 書いて あるか
//     ★三 ★やめた あとも 残る、と 書いて あるか
//     ★四 ★★字を 持つ ところが 1つ か（★画面に 書き写して いないか）
// ============================================================================

const assert = require("assert");
const fs = require("fs");
const path = require("path");
const { readCode, loadLib, stripComments } = require("./_source");

let 数 = 0;
function ok(cond, 名) {
  数 += 1;
  assert.ok(cond, "★落ちました ── " + 名);
  console.log("  ok  " + 名);
}

(async () => {
  const A = await loadLib("lib", "attendingPlaces.js");
  const 承知 = A.JOIN_WL.join("\n");

  // ------------------------------------------------------------------------
  // ★一・二 ★入る ときの 承知
  // ------------------------------------------------------------------------
  // ★★★2026-09-18・坂本さんの 最終の お決めで、★5行の 文体が 変わりました。
  //   ★★字を 丸ごと 書き写して 比べません。★変わる たび 見張りが 落ちます。
  //   ★★見るのは **言って いる こと** です ── ★語の 組み合わせ で 見ます。
  ok(/やりとり[\s\S]{0,40}確かめる/.test(承知),
    "確かめる ことが ある、と 書いて ある");
  ok(/学校が定めた監査員|学校の 定めた 方/.test(承知),
    "誰が 確かめるかを 言って いる");
  ok(/健康の記録は、誰も見られません|健康の 記録は、誰も 見られません/.test(承知),
    "健康の 記録は 誰も 見られない、と 書いて ある");

  // ★★★2つは 離れて いては いけません。
  //   ★★「確かめる ことが あります」だけ 読むと、★健康の ことも 読まれる、と
  //     ★★読まれ かねません。★すぐ 次に 置きます。
  const i = A.JOIN_WL.findIndex((x) => /確かめる/.test(x));
  const j = A.JOIN_WL.findIndex((x) => /健康の記録は、誰も|健康の 記録は、誰も/.test(x));
  ok(i >= 0 && j === i + 1, "2つが 続いて いる（間に 何も 挟まって いない）");

  // ★★いちばん 効く 1行を 太く。
  ok(A.JOIN_WL_BOLD.some((x) => /健康の記録は、誰も|健康の 記録は、誰も/.test(x)),
    "健康の 1行を 太く して いる");

  // ------------------------------------------------------------------------
  // ★三 ★やめた あとも 残る
  // ------------------------------------------------------------------------
  const やめる = A.LEAVE_LINES.join("\n");
  ok(/連絡に 書いたこと[\s\S]{0,30}残ります/.test(やめる),
    "やめた あとも 連絡が 残る、と 書いて ある");

  // ------------------------------------------------------------------------
  // ★四 ★字を 持つ ところは 1つ
  // ------------------------------------------------------------------------
  const 本体 = readCode("components", "VocalTracker.jsx");
  ok(!/健康の記録は、誰も見られません|健康の 記録は、誰も 見られません/.test(本体),
    "画面が 字を 書き写して いない（lib が 持つ）");
  ok(!/学校が定めた監査員|学校の 定めた 方/.test(本体),
    "画面が 字を 書き写して いない（2つめ）");

  // ★★★太い ところが、★本文の 字と そろって いるか。
  //   ★★字を 変えた とき、★太い ほうを 直し忘れると **太く なりません**。
  //   ★★落ちても 誰も 気づきません。★だから ここで 見ます。
  A.JOIN_WL_BOLD.forEach((b) => {
    数 += 1;
    assert.ok(A.JOIN_WL.some((x) => x.includes(b)),
      "★落ちました ── 太い 字が 本文に ありません: " + b);
  });
  console.log("  ok  太い 字が、★ぜんぶ 本文の 中に ある（" + A.JOIN_WL_BOLD.length + "）");

  // ------------------------------------------------------------------------
  // ★五 ★見られた ことを、★ご本人に お伝えする（★裁定 その76 ③）
  // ------------------------------------------------------------------------
  const N = await loadLib("lib", "monkaReadNotice.js");

  ok(N.noticeLine("2026-09-18T04:00:00Z", "てすと")
    === "9月18日、あなたと てすと 先生の やりとりが 確かめられました。",
    "1行の 形が 裁定の とおり");
  ok(N.noticeLine("2026-09-18T04:00:00Z", null)
    === "9月18日、あなたと 先生の やりとりが 確かめられました。",
    "お名前が 読めない ときは「先生」と だけ");
  // ★★★「名前を表示できませんでした」を ここに 混ぜない。
  //   ★★2026-09-18、★招かれて いる 1枚で 同じ ことが 起きて いました。
  ok(!/表示できません/.test(N.noticeLine("2026-09-18T04:00:00Z", null)),
    "読めなかった 断りを 混ぜて いない");

  // ★★誰が 見たかを 出さない ── ★台帳の 関数が そもそも 返しません。
  // ★★★注を 落として から 見ます（★また 同じ 罠に 当たりました）。
  //   ★★紙の 注に「`ended_at` で 絞りません」と 書いて あります。
  //   ★★落とさずに 探すと、★自分の 注に 当たって 落ちます。
  const 紙 = stripComments(fs.readFileSync(
    path.join(__dirname, "..", "..", "supabase/migration_monka_read_notices.sql"), "utf8"), ".sql");
  const 返す = /returns table \(([^)]*)\)/i.exec(紙);
  assert.ok(返す, "★止まりました ── 関数の 返す ものを 読めません。");
  ok(!/viewer/i.test(返す[1]), "台帳の 関数が、★誰が 見たかを 返さない");
  ok(/viewed_at/.test(返す[1]) && /teacher_name/.test(返す[1]),
    "返すのは 日づけと 先生の お名前 だけ");

  // ★★やめた あとも 知らせる（★裁定 その76 追補）。
  ok(!/ended_at/.test(紙), "やめた あとも 出す（ended_at で 絞って いない）");

  // ★★日数を 書き写して いない。★連絡と 同じ ところから 取る。
  const 束 = readCode("lib", "monkaReadNotice.js");
  ok(/HIDE_AFTER_DAYS/.test(束), "日数は lib/renraku.js から 取る");
  ok(!/\b90\b/.test(束), "90 を 書き写して いない");

  // ★★画面が 字を 書き写して いない。
  ok(!/確かめられました/.test(本体), "画面が 1行を 書き写して いない");
  // ★★片づける もの では ない ── ★既読の 仕掛けを つけて いない。
  const 描く = 本体.slice(本体.indexOf("monkaReadNotices("), 本体.indexOf("monkaReadNotices(") + 900);
  ok(!/markNoticeShown/.test(描く), "「わかりました」を 置いて いない（片づける ものでは ありません）");

  console.log("\n★" + 数 + "件 通りました ── 先に お伝えする 1行");
})().catch((e) => { console.error(e.message || e); process.exit(1); });
