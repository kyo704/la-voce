// ============================================================================
// ★役職の 画面の 断り（★見本 `stPost` ／ ★2026-09-18・坂本さんの ご承認）
//
//   ★★足した の は 5つ。★どれも「なぜ できないか」「なぜ この 置き方か」です。
//     ★① 決まりの 1行（warn ①）
//     ★② 見るだけの 方への 断り（warn ②）
//     ★③④⑤ 表の 置き方の 説明（note）
//
//   ★★★見る の は 3つ。
//     ★【一】★字が lib に あり、★画面に 書き写されて いない か
//     ★【二】★決まりの 行が、★触った ときの 断りと 1文字も ずれて いない か
//     ★【三】★表が 無い ときに、★表の 説明を 出して いない か
// ============================================================================

const { readCode, readRaw, loadLib, readPack } = require("./_source");

let ok = 0, ng = 0;
function t(cond, label) {
  if (cond) { ok++; console.log("  ○ " + label); }
  else { ng++; console.log("  ✗ " + label); }
}

(async () => {
  const P = await loadLib("lib", "opsPerms.js");
  const M = await loadLib("lib", "opsPostMatrix.js");
  const 本文 = readCode("components", "OpsPosts.jsx");
  const 生 = readRaw("components", "OpsPosts.jsx");

  // -------------------------------------------------------------------------
  // 【一】★決まりの 1行
  // -------------------------------------------------------------------------
  console.log("【一】決まりの 1行（★warn ①）");
  const 行 = P.ruleLine();
  t(行.startsWith("決まりは 1つ ──"), "見本の 頭で 始まる");
  // ★★★中の 1文は `CANNOT_GRANT_REASON` そのもの。★書き写して いない こと。
  t(行.includes(P.CANNOT_GRANT_REASON.replace(/。$/, "")),
    "★触った ときの 断りと 同じ 1文");
  t(!/決まりは 1つ/.test(本文), "★画面が 字を 書き写して いない");
  t(本文.includes("ruleLine()"), "画面は lib を 呼んで いる");
  // ★★道具の 較正 ── ★わざと 書き写した ことに して、★見つかる こと。
  t(/決まりは 1つ/.test('<b>決まりは 1つ ──「…」</b>'), "★わざとの 1件を 見つけられる");
  // ★★★ずれを 見つけられる こと ── ★断りを 変えたら 行も 変わる。
  t(P.ruleLine().includes("自分が 持っていないと 渡せません"), "中の 1文が 通って いる");

  // -------------------------------------------------------------------------
  // 【二】★見るだけの 方への 断り
  // -------------------------------------------------------------------------
  console.log("【二】見るだけの 方への 断り（★warn ②）");
  t(P.VIEW_ONLY_HEAD === "あなたは 見るだけです。", "見本の 字");
  const 役職 = [{ name: "学長", perms: ["post", "meibo"] },
    { name: "事務長", perms: ["post"] }, { name: "教授", perms: [] }];
  t(P.viewOnlyLine(役職) === "ひとの 役職を 変えられるのは 学長・事務長",
    "持って いる 役職を 並べる（" + P.viewOnlyLine(役職) + "）");
  // ★★★1人も 居ない ときに、★空の 文を 返さない こと。
  t(P.viewOnlyLine([]).includes(P.NOBODY_LABEL), "★1つも 無ければ「（いません）」");
  t(P.viewOnlyLine(null).includes(P.NOBODY_LABEL), "★渡されなくても 落ちない");
  // ★★役割の 名では なく、★できこと で 数えて いる こと。
  t(P.whoCan([{ name: "学長", role: "owner", perms: [] }], "post") === P.NOBODY_LABEL,
    "★役割の 名では 数えない（★できこと だけ）");
  // ★★画面に 出て いる こと。★持って いる 方には 出さない こと。
  t(生.includes('{!can(myPerms, "post") ? ('), "★持って いない ときだけ 出す");
  t(本文.includes("viewOnlyLine(posts)"), "★役職の 一覧から 引いて いる");
  t(!/あなたは 見るだけです/.test(本文), "★画面が 字を 書き写して いない");

  // -------------------------------------------------------------------------
  // 【三】★表の 置き方の 説明
  // -------------------------------------------------------------------------
  console.log("【三】表の 置き方の 説明（★note 3行）");
  t(M.TABLE_NOTES.length === 3, "3行 ある");
  t(M.TABLE_NOTES[0].text.includes("左の 列"), "① 左の 列に 置いた こと");
  t(M.TABLE_NOTES[1].text.includes("貼り付いています"), "② 貼り付いて いる こと");
  t(M.TABLE_NOTES[2].text.includes("役職名を 押すと"), "③ 役職名が 押せる こと");
  // ★★★太い ところは 行の 頭 とは 限りません（★見本 ── ① は 4文字 だけ）。
  //   ★★「頭が 太い」と 決めて 書いて、★見本と ちがって いました。
  M.TABLE_NOTES.forEach((n) => {
    t(!n.bold || n.text.startsWith(n.bold),
      "太い ところが 行の 中に ある ──「" + (n.bold || "なし") + "」");
  });
  t(M.TABLE_NOTES[0].bold === "できること", "① 太いのは「できること」の 4文字 だけ");
  t(M.TABLE_NOTES[2].bold === "", "③ 太い ところは ない");
  // ★★★表が 出て いる ときだけ 出す こと。
  //   ★★狭い 画面には「左の 列」も「見出しの 行」も ありません。
  //   ★★無い ものの 説明を すると、★探して しまいます。
  t(生.includes("{showTable(winW) ? TABLE_NOTES.map"), "★表が 出て いる ときだけ 出す");
  t(!/左の 列に 置きました/.test(本文), "★画面が 字を 書き写して いない");
  t(本文.includes("TABLE_NOTES"), "画面は lib から もらって いる");

  // -------------------------------------------------------------------------
  // 【四】★見本と 1文字も ずれて いない
  //
  //   ★★見本の 紙から 直に 拾って くらべます。★こちらに 写しません。
  // -------------------------------------------------------------------------
  console.log("【四】見本の 字と 1文字も ずれて いない");
  const 見本 = readPack(
    "00-動く見本-PC・iPad（運営）.html");
  const i = 見本.indexOf("function stPost(");
  const 塊 = 見本.slice(i, 見本.indexOf("\nfunction ", i + 1));
  t(塊.length > 1000, "見本の 節を 切り出せた");
  // ★★★見本の 中では、★字の 途中に `<b>` が 入って います。
  //   ★★そのまま 探すと 見つかりません。★2026-09-18、★ここで 2件 落ちました。
  //   ★★本文だけ を くらべます。★太さは 上の 節で 別に 見て います。
  const 素 = 塊.replace(/<\/?b>/g, "");
  t(素.length < 塊.length, "★`<b>` を 外せた（★道具の 較正）");
  M.TABLE_NOTES.forEach((n) => {
    t(素.includes(n.bold ? n.bold : n.text.slice(0, 20)),
      "見本に ある ── 「" + n.text.slice(0, 18) + "…」");
  });
  t(塊.includes(P.VIEW_ONLY_HEAD.replace("。", "")), "見本に ある ──「あなたは 見るだけです」");
  t(塊.includes(P.CANNOT_GRANT_REASON.replace(/。$/, "")), "見本に ある ── 決まりの 1文");

  console.log(`\n○ ${ok}　✗ ${ng}`);
  process.exit(ng === 0 ? 0 : 1);
})();
