const { execFileSync } = require("child_process");
const path = require("path");

const 蔵 = path.join(__dirname, "..", "..");
let 出 = "";
try {
  出 = execFileSync("python3", [path.join(蔵, "tools", "trigger_met.py")],
    { cwd: 蔵, encoding: "utf-8" });
} catch (e) {
  出 = (e.stdout || "") + (e.stderr || "");
}

let 落ちた = 0;
function たしかめる(名, 条件, 言い分) {
  if (条件) { console.log("  ○ " + 名); return; }
  落ちた += 1;
  console.log("  × " + 名 + "  …… " + 言い分);
}

const 数 = (見出し) => {
  const m = new RegExp("■ " + 見出し + "[^（]*（(\\d+)）").exec(出);
  return m ? Number(m[1]) : -1;
};

たしかめる("★道具が 走った", /TRIGGER_MET/.test(出), "★出力が ありません:\n" + 出.slice(0, 400));
