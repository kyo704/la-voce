const { execFileSync } = require("child_process");
const path = require("path");

const 蔵 = path.join(__dirname, "..", "..");
let 出 = "";
let 番 = 0;
try {
  出 = execFileSync("python3", [path.join(蔵, "tools", "screen_count.py"), "--check"],
    { cwd: 蔵, encoding: "utf-8" });
} catch (e) {
  出 = (e.stdout || "") + (e.stderr || "");
  番 = e.status === undefined ? 1 : e.status;
}

let 落ちた = 0;
function たしかめる(名, 条件, 言い分) {
  if (条件) { console.log("  ○ " + 名); return; }
  落ちた += 1;
  console.log("  × " + 名 + "  …… " + 言い分);
}

たしかめる("★道具が 走った", /SCREEN_COUNT/.test(出),
  "★出力が ありません:\n" + 出.slice(0, 500));
たしかめる("★4本 とも 読めた", !/★見本が 足りません|見つかりません/.test(出),
  "★`LIVE` の 見本が 足りません:\n" + 出.slice(0, 400));
たしかめる("★確定値と 合って いる", 番 === 0 && /★確定値と 一致/.test(出),
  "★数が 変わりました。★増減が 正しい なら `tools/screen_count.py` の `FIXED` を 直し、"
  + "★同じ 日に 実行ルートの 数も 直して ください:\n"
  + 出.split("\n").filter((l) => /画面|シート|確定値/.test(l)).join("\n"));
// ★★見本の 中の JavaScript が 壊れて いない こと（★道具が 数えます）。
たしかめる("★見本の 誤りが 0件", !/誤り\s*[1-9]/.test(出),
  "★見本の JavaScript が 落ちて います:\n"
  + 出.split("\n").filter((l) => /誤り/.test(l)).join("\n"));

console.log(落ちた === 0 ? "RESULT: OK" : "RESULT: NG (" + 落ちた + ")");
process.exit(落ちた === 0 ? 0 : 1);
