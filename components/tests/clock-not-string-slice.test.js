// ============================================================================
// ★時刻を「字」で 切らない（★2026-09-18・実機で 見つけました）
//
//   ★★★見つかり方
//     ★★本番の 画面を 撮りました。★きょうの ながれに「06:00」と 出て いました。
//     ★★台帳の その レッスンは `2026-09-18 06:00:00+00` ── ★UTC です。
//     ★★日本の 15:00 でした。★9時間 ずれて いました。
//     ★★★見張りも 組み立ても 通って いました。★画面だけが 間違って いました。
//
//   ★★★なぜ 起きる か
//     ★★`scheduled_at` は 文字で 届きます。★"2026-09-18T06:00:00+00:00"。
//     ★★`slice(11,16)` は、★その 字の 11〜16文字目 を 取ります。
//     ★★字は 合って います。★意味が ちがいます。
//     ★★★日づけも 同じ です ── ★21:00 UTC は、★日本では 翌朝 です。
//       ★★きょうの ながれに、★あすの レッスンが 混ざります。
//
//   ★★★決め ── ★時刻・日づけは `lib/todayBand.js` で 読みます。
//     ★★`timeOf(iso)` … ★端末の 時計の 時刻。
//     ★★`dayOf(iso)` …… ★端末の 時計の 日づけ。
//     ★★どちらも `Intl.DateTimeFormat` です。★イタリアでは その場の 時刻に なります。
//
//   ★★★この 見張りが 見る の は「時刻の 列を 字で 切って いないか」だけ です。
//     ★★`new Date().toISOString().slice(0,10)`（★今日を 作る）は 別 です。
//     ★★あれは 自分で 作った 字 を 切って います。★台帳の 字 では ありません。
// ============================================================================

const { readCode, loadLib } = require("./_source");

let ok = 0, ng = 0;
function t(cond, label) {
  if (cond) { ok++; console.log("  ○ " + label); }
  else { ng++; console.log("  ✗ " + label); }
}

// ---------------------------------------------------------------------------
// 【一】★台帳の 時刻を 字で 切って いる ところが 無い こと
//
//   ★★見る のは、★運営の 画面と その 決めごと だけ です。
//     ★★ほかの 画面には 昔からの 書き方が 残って います（★別の 荷）。
//     ★★ここを 広げる ときは、★一度に 1つずつ 直して ください。
// ---------------------------------------------------------------------------
const 見る = [
  ["lib", "opsSchedule.js"],
  ["lib", "opsAttendance.js"],
  ["lib", "monkaReadNotice.js"],
  ["components", "OpsHome.jsx"],
  ["components", "OpsSchedule.jsx"],
  ["components", "OpsAttendance.jsx"],
  ["components", "TellTeacher.jsx"]
];

console.log("【一】台帳の 時刻を 字で 切って いない");
見る.forEach((p) => {
  const code = readCode(...p);
  t(!/slice\(\s*11\s*,\s*16\s*\)/.test(code), p.join("/") + " ── slice(11,16) が ない");
  // ★★`scheduled_at` ／ `viewed_at` を 字で 切って いない こと。
  t(!/(scheduled_at|viewed_at)[^\n]*\.slice\(\s*0\s*,\s*10\s*\)/.test(code),
    p.join("/") + " ── 時刻の 列を slice(0,10) して いない");
});

// ---------------------------------------------------------------------------
// 【二】★道具の 較正 ── ★わざと 1件 作って、★見つかる こと
//
//   ★★見つからない 道具は、★壊れて いても「通った」と 言います。
// ---------------------------------------------------------------------------
console.log("【二】道具の 較正（わざと 1件 作ります）");
const 悪い例 = 'const t = String(l.scheduled_at).slice(11, 16);';
t(/slice\(\s*11\s*,\s*16\s*\)/.test(悪い例), "わざとの 1件を 見つけられる");
const 悪い例2 = 'const d = String(r.viewed_at || "").slice(0, 10);';
t(/(scheduled_at|viewed_at)[^\n]*\.slice\(\s*0\s*,\s*10\s*\)/.test(悪い例2),
  "わざとの 1件（日づけ）を 見つけられる");

// ---------------------------------------------------------------------------
// 【三】★読み替えが 正しい こと ── ★9時間の ずれを 直して いるか
// ---------------------------------------------------------------------------
(async () => {
  console.log("【三】UTC を 端末の 時計で 読む");
  const band = await loadLib("lib", "todayBand.js");
  t(typeof band.dayOf === "function", "dayOf が ある");

  // ★★この 見張りは 日本の 時計で 走らせます（★TZ=Asia/Tokyo）。
  //   ★★どこで 走らせても 同じ 答えに する ため、★時間帯を 渡します。
  t(band.timeOf("2026-09-18T06:00:00+00:00", "Asia/Tokyo") === "15:00",
    "06:00 UTC は 15:00（東京）");
  t(band.dayOf("2026-09-18T21:00:00+00:00", "Asia/Tokyo") === "2026-09-19",
    "21:00 UTC は 翌日（東京）");
  t(band.dayOf("") === "", "空は 空");

  const sch = await loadLib("lib", "opsSchedule.js");
  const l = { scheduled_at: "2026-09-18T06:00:00+00:00" };
  t(sch.timeOf(l) === band.timeOf(l.scheduled_at), "日程の 時刻は todayBand と 同じ");
  t(sch.dateOf(l) === band.dayOf(l.scheduled_at), "日程の 日づけは todayBand と 同じ");
  t(sch.timeOf({}) === "" && sch.dateOf({}) === "", "空は 空（日程）");

  console.log(`\n○ ${ok}　✗ ${ng}`);
  process.exit(ng === 0 ? 0 : 1);
})();
