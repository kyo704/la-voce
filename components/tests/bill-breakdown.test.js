// ============================================================================
// ★見張り ── ★ご請求の 計算の 内訳（★裁定 2026-09-18・⑥）
//
//   ★出どころ 見本 00-動く見本-PC・iPad（運営）.html の `billPlans` / `billWl`
//   ★裁定    「稟議の 数字です。★無いと 通りません」（★Opus・2026-09-18）
//
//   ★★測る のは 4つ です。
//     ★一 ★段の 数・率が 見本と 同じ か（★見本から 引きます。★書き写しません）
//     ★二 ★★内訳と 答えが ずれない か
//          ★★`monthlyFee` が `billPlans` を 使って いる こと。
//          ★★これが この 見張りの 本体 です。
//     ★三 ★下限が `MONTHLY_FLOOR` から 出て いるか（★12,800 を 書いて いないか）
//     ★四 ★画面が 自分で 掛け算を して いないか
//
//   ★★★見本の 下限は 12,800円 です。★実装は 9,800円 です。
//     ★★裁定 その20（2026-09-13）で 改めました。★実装の ほうが 新しい です。
//     ★★だから ここでは、★見本の 12,800 と **突き合わせません**。
//     ★★代わりに「画面が 数を 書き写して いない」ことを 見ます。
// ============================================================================

const assert = require("assert");
const fs = require("fs");
const path = require("path");
const { readCode, readRaw, loadLib } = require("./_source");

const ROOT = path.join(__dirname, "..", "..");
const 見本の道 = path.join(ROOT, "docs/design/pack-final/00-動く見本-PC・iPad（運営）.html");

let 数 = 0;
function ok(cond, 名) {
  数 += 1;
  assert.ok(cond, "★落ちました ── " + 名);
  console.log("  ok  " + 名);
}

(async () => {
  // ------------------------------------------------------------------------
  // ★★較正 ── ★見本に billPlans が 無ければ 止まります。
  // ------------------------------------------------------------------------
  if (!fs.existsSync(見本の道)) {
    console.error("★止まりました ── 見本が ありません: " + 見本の道);
    process.exit(1);
  }
  const 見本 = fs.readFileSync(見本の道, "utf8");
  // ★★★2026-09-23 ── ★見本の 名が 変わりました。
  //   ★もと `function billPlans(…)`（★段の 一覧を 返す）
  //   ★いま `function gakkoYen(n)`（★答えだけ を 返す）＋ `billPlan()`（★プランの 種）
  //   ★★段の 率は `gakkoYen` の 式の 中に あります ──
  //       Math.max(12800, Math.min(n*400, Math.max(n,100)*350, Math.max(n,300)*250))
  //   ★★★だから 率は そこから 読みます。★書き写しません。
  const i = 見本.indexOf("function gakkoYen(");
  assert.ok(i > 0, "★止まりました ── 見本に gakkoYen が ありません。");
  const 見本の本体 = 見本.slice(i, i + 300);

  // ★★率は 見本から 引きます（★`n*400` ／ `…*350` ／ `…*250`）。
  const 見本の率 = [...見本の本体.matchAll(/\*\s*(\d{3})\b/g)].map((m) => Number(m[1]));
  assert.ok(見本の率.length >= 3, "★止まりました ── 見本の 率を 読めません。");

  // ★★★9月10日の 食いちがいの 確かめ（★Opus の お指図・2026-09-23）──
  //   ★「100人以上 350円」「300人以上 250円」の **条件**が 見本の 式に あるか。
  //   ★★もとは `n*350` と 書いて あり、★20人の 教室でも 350円の 段が 当たって いました。
  assert.ok(/Math\.max\(\s*n\s*,\s*100\s*\)\s*\*\s*350/.test(見本の本体),
    "★止まりました ── 見本の 350円に「100人以上」の 条件が ありません（★2026-09-10 の 食いちがい）");
  assert.ok(/Math\.max\(\s*n\s*,\s*300\s*\)\s*\*\s*250/.test(見本の本体),
    "★止まりました ── 見本の 250円に「300人以上」の 条件が ありません");
  assert.ok(/Math\.max\(\s*12800\s*,/.test(見本の本体),
    "★止まりました ── 見本に 下限 12,800円が ありません");

  const R = await loadLib("lib", "orgRoster.js");

  // ------------------------------------------------------------------------
  // ★一 ★段が 見本と 同じ か
  // ------------------------------------------------------------------------
  const 段 = R.billPlans(194);
  ok(段.length === 見本の率.length,
    "段の 数が 見本と 同じ（" + 見本の率.length + "）");
  ok(段.map((p) => p.rate).join(",") === 見本の率.join(","),
    "率が 見本と 同じ（" + 見本の率.join(" / ") + "）");

  // ★★見本の 数字（194人）を そのまま 当てます。
  ok(段[0].yen === 77600 && 段[1].yen === 67900 && 段[2].yen === 75000,
    "194人の 内訳が 見本と 同じ（77,600 / 67,900 / 75,000）");

  // ------------------------------------------------------------------------
  // ★二 ★内訳と 答えが ずれない か ── ★ここが 本体
  // ------------------------------------------------------------------------
  //   ★★同じ 式の 2つめの 写しが できて いないか。
  //     ★★写しが できると、★率を 1つ 変えた とき 片方だけ 直ります。
  const src = readCode("lib", "orgRoster.js");
  const mf = src.slice(src.indexOf("export function monthlyFee("));
  const mf本体 = mf.slice(0, mf.indexOf("}") + 1);
  ok(/billPlans\(/.test(mf本体), "monthlyFee が billPlans を 使って いる");
  ok(!/TIERS\.map/.test(mf本体), "monthlyFee が 自分で 段を 数えて いない");

  // ★★★2026-09-23（★Opus の お決め）── ★見る 先を 変えました。
  //   ★★もとは `billPlans`（★学校の 段の 表）と `monthlyFee` を くらべて いました。
  //     ★★★6〜30人は **教室の 定額**（2,980円）です。★段の 表とは 合いません。
  //       ★★合わない のが 正しい 姿 です。★くらべる 相手が まちがって いました。
  //   ★★★いまは **学校の 段の 人** だけ で くらべます。
  //     ★教室・無料の 段は、★下の「三」で `billBreakdown` を 見ます。
  [31, 99, 100, 194, 299, 300, 1000].forEach((n) => {
    const 安い = Math.min(...R.billPlans(n).map((p) => p.yen));
    const 答え = R.monthlyFee(n);
    数 += 1;
    assert.ok(答え === Math.max(安い, R.MONTHLY_FLOOR),
      "★落ちました ── " + n + "人で 内訳と 答えが ずれます");
  });
  console.log("  ok  8とおりの 人数で、内訳の いちばん 安いものと 答えが 合う");

  // ★★5人までは 0円（★裁定）。★内訳を 出しません。
  ok(R.monthlyFee(5) === 0, "5人は 0円");

  // ------------------------------------------------------------------------
  // ★三 ★下限は lib から 出て いるか
  // ------------------------------------------------------------------------
  const 画面 = readCode("components", "OpsSettings.jsx");
  ok(/MONTHLY_FLOOR/.test(画面), "画面が MONTHLY_FLOOR を 使って いる");
  ok(!/12,?800/.test(画面), "画面に 12,800 が 書かれて いない（★裁定 その20）");
  ok(!/9,?800/.test(画面), "画面に 9,800 が 書き写されて いない");

  // ------------------------------------------------------------------------
  // ★四 ★画面が 自分で 掛け算を して いないか
  // ------------------------------------------------------------------------
  // ★★★2026-09-23 ── ★画面が 呼ぶ 先が 変わりました（★Opus の お決め FIX_3）。
  //   ★もと `billPlans`（★段の 表を そのまま 出す）
  //   ★いま `billBreakdown`（★その 段の もの だけ を 出す）
  ok(/billBreakdown\(/.test(画面), "画面が billBreakdown を 呼んで いる");
  ok(!/\*\s*400|\*\s*350|\*\s*250/.test(画面), "画面が 自分で 掛けて いない");

  // ------------------------------------------------------------------------
  // ★四の二 ★勝った 行に 印が つくか
  // ------------------------------------------------------------------------
  //   ★★★6人の 教室で 撮って、★分かりました ──
  //     ★★どの 段も 下限に 届かない とき、★どこにも 印が つきません でした。
  //     ★★9,800円 が どこから 来たのか、★読んで 分かりません。
  //   ★★内訳は「追える ように する」ため の もの です。
  //     ★★勝った 行に 印が 無い 内訳は、★その 役目を 果たしません。
  // ★★★2026-09-23 ── ★下限の 判じは `lib/orgRoster.js` に 移りました。
  //   ★もと …… 画面の 中で `下限が勝った` を 数えて いました（★決めが 2か所）。
  //   ★いま …… `billBreakdown` が `floorUsed` を 返し、★下限の 行を 足します。
  //     ★★下限が 効いた ときだけ 出ます。★効いて いない ときに 出すと、
  //       ★「下限が 当たった」と 読めて しまいます。
  ok(!/下限が勝った/.test(画面), "★画面が 自分で 下限を 判じて いない");
  ok(/floorUsed/.test(readCode("lib", "orgRoster.js")), "★下限の 判じが lib に ある");
  {
    const b31 = R.billBreakdown(31), b50 = R.billBreakdown(50);
    ok(b31.floorUsed === true, "★31人は 下限が 効く（12,400 → 12,800）");
    ok(b50.floorUsed === false, "★50人は 下限が 効かない（20,000）");
    ok(b31.lines.some((l) => l.label === R.FLOOR_LINE && l.chosen),
      "★下限が 効いた ときだけ、★下限の 行に 印が つく");
    ok(!b50.lines.some((l) => l.label === R.FLOOR_LINE),
      "★効いて いない ときは 下限の 行を 出さない");
  }
  // ★★★2026-09-23 ── ★印の つけ先は **1つ**に なりました。
  //   ★もと …… 段の 行と 下限の 行の 2か所で 別々に 書いて いました。
  //   ★いま …… `billBreakdown` が 返す 行に `chosen` が 付いて 来ます。
  //     ★★画面は それを そのまま 出すだけ です。★数えません。
  const 印の数 = (画面.match(/いちばん 安いもの/g) || []).length;
  ok(印の数 === 1, "★印の つけ先は 1か所（★lib が 決める）");
  // ★★定額の 段では「いちばん 安いもの」と 書かない こと。
  //   ★★くらべる ものが 1つ しか ありません。★くらべて いないのに そう 書くと 迷わせます。
  ok(/!内訳\.flat/.test(画面), "★定額の 段では「いちばん 安いもの」と 書かない");

  // ★★★2026-09-23 ── ★`billPlans` で 数えるのを やめました。
  //   ★★6〜30人は **教室の 定額** です。★段の 表とは 合いません（★合わないのが 正）。
  //   ★★★いまは `billBreakdown` の 行で 見ます ── ★印は いつでも ちょうど 1つ。
  [0, 5, 6, 20, 30, 31, 99, 100, 194, 300].forEach((c) => {
    const b = R.billBreakdown(c);
    const 印 = b.lines.filter((l) => l.chosen);
    数 += 1;
    assert.ok(b.total === 0 ? 印.length === 0 : (印.length === 1 && 印[0].yen === b.total),
      "★落ちました ── " + c + "人で 勝ち手が 決まりません（印 " + 印.length + "）");
  });
  console.log("  ok  7とおりの 人数で、勝った 行が 1つに 決まる");

  // ------------------------------------------------------------------------
  // ★五 ★「今月の ご請求」の 字（★裁定 ⑦）／★小見出しの 置き場（★裁定 ⑤）
  // ------------------------------------------------------------------------
  //   ★★小見出しは 箱の **外**・上。★見本 `stBill()` と 同じ です。
  const 生画面 = readRaw("components", "OpsSettings.jsx");
  ok(/<H3>今月の ご請求<\/H3>[\s\S]{0,80}<div style=\{card\}>/.test(生画面),
    "「今月の ご請求」の 小見出しが、★箱の 外・上 に ある");
  ok(/<H3>料金の 決まり<\/H3>[\s\S]{0,40}<div style=\{card\}>/.test(生画面),
    "「料金の 決まり」の 小見出しが、★箱の 外・上 に ある");
  ok(!/<p style=\{\{ \.\.\.small, marginBottom: 2 \}\}>料金の 決まり/.test(生画面),
    "箱の 中の 1行目 から 消えて いる");
  ok(/from "@\/components\/UiV2"/.test(生画面),
    "小見出しは UiV2 の H3（★2つめの 決めを 作らない）");

  //   ★★見本の 大きさを 引きます。★書き写しません。
  //   ★★★どの 画面の 数か を、★先に 決めて から 引きます。
  //     ★★同じ 字が 2か所に あります ──
  //       ★見本 719行 … 名簿の 中の「いまの ご請求」（19px）
  //       ★見本1058行 … 設定・ご請求（`P_settei` → `stBill`）（22px）
  //     ★★はじめ 近い ほう（19px）を 拾い、★別の 画面の 数を 使って いました。
  const 設定の本体 = 見本.slice(見本.indexOf("function stBill()"),
    見本.indexOf("function stBill()") + 900);
  const 見本の字 = /今月の' \+ ' ご請求[\s\S]{0,40}?font-size:(\d+)px;font-weight:(\d+)/.exec(設定の本体)
    || /font-size:(\d+)px;font-weight:(\d+)/.exec(設定の本体);
  assert.ok(見本の字, "★止まりました ── 見本の「今月の ご請求」の 字を 読めません。");
  const rem = (Number(見本の字[1]) / 16) + "rem";
  const 行 = 画面.slice(画面.indexOf("今月のご請求"), 画面.indexOf("今月のご請求") + 300);
  ok(行.includes(rem), "字の 大きさが 見本と 同じ（" + 見本の字[1] + "px = " + rem + "）");
  ok(行.includes("fontWeight: " + 見本の字[2]), "太さが 見本と 同じ（" + 見本の字[2] + "）");

  // ★★★2026-09-23（★Opus の お決め）── ★確かめ点を 足しました。
//   ★6・7・29・30・31・99 ── ★段の 境目 と、★その すぐ 前後 です。
//   ★★★見るのは 1つ ── ★「印の ついた 行が ちょうど 1つ で、★それが 答えと 同じ」。
//     ★★定額の 段で 1人あたりを 割ると、★ここが 必ず 落ちます。
console.log("\n★三 ★段ごとに、★内訳と 答えが 合う か");
[0, 5, 6, 7, 29, 30, 31, 50, 99, 100, 216, 300].forEach((n) => {
  const b = R.billBreakdown(n);
  const 印 = b.lines.filter((l) => l.chosen);
  if (b.total === 0) {
    ok(b.lines.length === 0, `${n}人 ── ★0円 の ときは 内訳を 出さない`);
    return;
  }
  ok(印.length === 1 && 印[0].yen === b.total,
    `${n}人（${b.plan}）── ★印は 1つ で、★答え ${b.total} と 同じ`
    + (印.length === 1 ? "" : `（印 ${印.length}つ）`));
  // ★★定額の 段に 1人あたりの 式を 出して いない こと。
  if (b.flat) {
    ok(!b.lines.some((l) => /×/.test(l.label)),
      `${n}人 ── ★定額の 段に 式を 出して いない`);
  }
});
// ★★★画面と 請求が 同じ 関数を 呼ぶ こと（★FIX_3）。
const 設定画面 = readCode("components", "OpsSettings.jsx");
ok(/billBreakdown\(/.test(設定画面), "★画面は billBreakdown を 呼んで いる");
ok(!/billPlans\(/.test(設定画面), "★画面は billPlans を 自分で 数えて いない");

console.log("\n★" + 数 + "件 通りました ── ご請求の 内訳");
})().catch((e) => { console.error(e.message || e); process.exit(1); });
