// ============================================================================
// ★見張り ── ★招かれて いる 1枚で、★嘘の 断りを 出さない
//
//   ★出どころ 実機（★2026-09-18・坂本さん）──
//     ★「名前を表示できませんでした」と「てすと 先生から」が 並んで いました。
//
//   ★★★お名前は 読めて います。★教室の 名 だけ が 空 です。
//     ★★台帳を 数えました ── ★まだ 使われて いない 招待 17 のうち 8つ が 空。
//     ★★お名前が 空の ものは 0つ。
//   ★★★だから「読めませんでした」は 嘘 です。★読めて います。
//     ★★その 先生が、★まだ 付けて いない だけ です。
//
//   ★★測る のは 3つ です。
//     ★一 ★教室の 名が 空の とき、★お名前で 呼ぶ
//     ★二 ★どちらも 空の ときだけ、★読めなかった と 言う
//     ★三 ★同じ お名前を 2度 出さない
// ============================================================================

const assert = require("assert");
const { readCode } = require("./_source");

let 数 = 0;
function ok(cond, 名) {
  数 += 1;
  assert.ok(cond, "★落ちました ── " + 名);
  console.log("  ok  " + 名);
}

const 本体 = readCode("components", "VocalTracker.jsx");

// ★★招かれて いる 1枚の ところ だけ を 見ます。
const i = 本体.indexOf("pendingInvitation ? (");
assert.ok(i > 0, "★止まりました ── 招かれて いる 1枚が 見つかりません。");
const 札 = 本体.slice(i, i + 2200);

// ★一 ★教室の 名が 無い ときは お名前。
ok(/pendingInvitation\.teacher\.school\)[\s\S]{0,200}display_name[\s\S]{0,80}先生/.test(札),
  "教室の 名が 空の ときは、★お名前で 呼ぶ");

// ★二 ★読めなかった、は いちばん 最後。
const 教室 = 札.indexOf("pendingInvitation.teacher.school");
const 名 = 札.indexOf("display_name");
const 断り = 札.indexOf("NAME_FETCH_FAILED_LABEL");
ok(教室 >= 0 && 名 > 教室 && 断り > 名,
  "断りは いちばん 後ろ（教室 → お名前 → 断り）");

// ★三 ★下の 行は、★教室の 名が ある ときだけ。
ok(/display_name[\s\S]{0,60}&&[\s\S]{0,60}\.school \?/.test(札),
  "下に お名前を 出すのは、★教室の 名が ある ときだけ");

// ★★「不明」と 書かない、は そのまま。
ok(!/不明/.test(札), "「不明」と 書いて いない");

console.log("\n★" + 数 + "件 通りました ── 招かれて いる 1枚");
