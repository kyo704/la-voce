// ============================================================================
// ★しるしの 見張り（★裁定 その78 §3 ／ その81 §3）
//
//   ★★見る の は 5つ。
//     ★【一】★裁定の 形と 合って いる か（★紙から 読みます。★写しません）
//     ★【二】★曲線が 混ざって いない か
//     ★【三】★ます目の 外に 出て いない か
//     ★【四】★色を 持って いない か（★親から 受け取る）
//     ★【五】★塗りつぶして いない か
// ============================================================================

const { readCode, readRaw, loadLib, readPack } = require("./_source");

let ok = 0, ng = 0;
function t(cond, label) {
  if (cond) { ok++; console.log("  ○ " + label); }
  else { ng++; console.log("  ✗ " + label); }
}

(async () => {
  const m = await loadLib("lib", "opsIcons.js");
  const 裁定 = readPack(
    "ruling-81-visual-design.md");

  // -------------------------------------------------------------------------
  // 【一】★数と 名
  // -------------------------------------------------------------------------
  console.log("【一】裁定の しるしが そろって いる");
  t(Object.keys(m.ICO).length === 10, "運営の しるしは 10種");
  t(Object.keys(m.ICO_P).length === 5, "個人の 帯は 5種");
  ["home", "users", "cap", "grid", "star", "mail", "gear", "search", "fold", "unfold"]
    .forEach((k) => t(!!m.ICO[k], "運営 " + k + " が ある"));
  ["きょう", "記録", "ふりかえる", "ノート", "ひつじ"]
    .forEach((k) => t(!!m.ICO_P[k], "個人 " + k + " が ある"));

  // ★★★形そのものを、★裁定の 紙と 突き合わせます。
  //   ★★点の 数が 1つ ちがえば、★絵が 変わります。★目では 気づけません。
  //   ★★紙から 座標を 拾って、★手元の 座標と くらべます。
  function 座標(s) {
    return (String(s).match(/-?\d+(?:\.\d+)?/g) || []).join(",");
  }
  const 紙の節 = 裁定.slice(裁定.indexOf("var ICO = {"), 裁定.indexOf("### 3-4"));
  t(紙の節.length > 500, "紙から しるしの 節を 読めた");
  Object.keys(m.ICO).forEach((k) => {
    // ★★紙の 中の、★その 名の ところ だけ を 切り出します。
    const i = 紙の節.indexOf("\n " + k + ":");
    const 次 = Object.keys(m.ICO).map((x) => 紙の節.indexOf("\n " + x + ":"))
      .filter((p) => p > i).sort((a, b) => a - b)[0];
    const 塊 = 紙の節.slice(i, 次 > 0 ? 次 : 紙の節.indexOf("};"));
    t(i > 0 && 座標(塊).includes(座標(m.ICO[k]).slice(0, 40)),
      "運営 " + k + " ── 形が 裁定と 合って いる");
  });

  // -------------------------------------------------------------------------
  // 【二】★曲線を 使って いない（★§3-2）
  // -------------------------------------------------------------------------
  console.log("【二】曲線（C / A）を 使って いない");
  m.iconKeys().forEach((k) => {
    t(!m.hasCurve(m.iconBody(k)), k + " ── 直線・円・楕円 だけ");
  });
  // ★★道具の 較正 ── ★わざと 曲線を 1つ 作って、★見つかる こと。
  t(m.hasCurve('<path d="M0 0 C 4 4 8 8 12 12"/>'), "★わざとの 曲線を 見つけられる");
  // ★★`rx="2"` の x を 拾って いない こと（★出しすぎる 道具は 使えません）。
  t(!m.hasCurve('<rect x="3" y="4.8" width="18" height="15.6" rx="2"/>'),
    "★`rx` を 曲線と 見なして いない");

  // -------------------------------------------------------------------------
  // 【三】★ます目（24×24）の 外に 出て いない
  //
  //   ★★出ると、★端が 切れます。★小さく すると もっと 切れます。
  // -------------------------------------------------------------------------
  console.log("【三】24×24 の ます目に 収まって いる");

  // ★★★数を そのまま 拾っては いけません（★2026-09-18、★ここで 3つ 誤報しました）。
  //   ★★`v-5.6` の -5.6 は **座標では なく 差** です。
  //   ★★「-5.6 は ます目の 外」と 出ましたが、★絵は 外に 出て いません。
  //   ★★★出しすぎる 道具は、★出さない 道具と 同じくらい 使えません。
  //   ★★だから、★点を たどって 実際の 位置を 出します。
  function 点をたどる(body) {
    const 点 = [];
    // ★○ と 楕円 ── ★中心 ± 半径
    [...String(body).matchAll(/<(circle|ellipse)([^>]*)>/g)].forEach(([, , 属性]) => {
      const 取 = (n) => {
        const mm = 属性.match(new RegExp(n + '="(-?[\\d.]+)"'));
        return mm ? Number(mm[1]) : null;
      };
      const cx = 取("cx"), cy = 取("cy");
      const rx = 取("r") != null ? 取("r") : 取("rx");
      const ry = 取("r") != null ? 取("r") : 取("ry");
      if (cx != null && rx != null) { 点.push([cx - rx, cy - ry], [cx + rx, cy + ry]); }
    });
    // ★四角 ── ★左上と 右下
    [...String(body).matchAll(/<rect([^>]*)>/g)].forEach(([, 属性]) => {
      const 取 = (n) => {
        const mm = 属性.match(new RegExp(n + '="(-?[\\d.]+)"'));
        return mm ? Number(mm[1]) : null;
      };
      const x = 取("x"), y = 取("y"), w = 取("width"), h = 取("height");
      if (x != null && w != null) { 点.push([x, y], [x + w, y + h]); }
    });
    // ★線 ── ★M L H V と、★その 小文字（★差で 動きます）
    [...String(body).matchAll(/d="([^"]*)"/g)].forEach(([, d]) => {
      let x = 0, y = 0;
      const 札 = d.match(/[A-Za-z]|-?\d+(?:\.\d+)?/g) || [];
      let 命 = "M", i = 0;
      while (i < 札.length) {
        if (/[A-Za-z]/.test(札[i])) { 命 = 札[i]; i++; continue; }
        const 読 = () => Number(札[i++]);
        if (命 === "M" || 命 === "L") { x = 読(); y = 読(); }
        else if (命 === "m" || 命 === "l") { x += 読(); y += 読(); }
        else if (命 === "H") { x = 読(); }
        else if (命 === "h") { x += 読(); }
        else if (命 === "V") { y = 読(); }
        else if (命 === "v") { y += 読(); }
        else { i++; continue; }
        点.push([x, y]);
        // ★★M の あと 数が 続いたら、★以後は L です（★SVG の 決まり）。
        if (命 === "M") 命 = "L";
        if (命 === "m") 命 = "l";
      }
    });
    return 点;
  }

  m.iconKeys().forEach((k) => {
    const 点 = 点をたどる(m.iconBody(k));
    const 外 = 点.filter(([x, y]) => x < -0.01 || x > m.ICON_BOX + 0.01
      || y < -0.01 || y > m.ICON_BOX + 0.01);
    t(点.length > 0 && 外.length === 0,
      k + " ── 外に 出て いない（点 " + 点.length + "）"
        + (外.length ? "★外:" + 外.map((p) => p.join(":")).join(" ") : ""));
  });
  // ★★道具の 較正 ── ★わざと 外に 出した 1件が 見つかる こと。
  const 外れた = 点をたどる('<path d="M12 12 L30 12"/>');
  t(外れた.some(([x]) => x > m.ICON_BOX), "★わざとの 1件（ます目の 外）を 見つけられる");
  // ★★差で 動く 指図を、★座標と 取り違えて いない こと。
  const 差 = 点をたどる('<path d="M12 12 v-5.6"/>');
  t(差.every(([, y]) => y >= 0), "★`v-5.6` を 座標と 取り違えて いない");
  t(m.ICON_BOX === 24 && m.ICON_STROKE === 1.9, "ます目 24 ／ 線 1.9");
  // ★★たたんだ ときは 大きく します（★裁定 その78 §2-3）。
  t(m.ICON_SIZE_RAIL > m.ICON_SIZE, "たたむと しるしを 大きく する");

  // -------------------------------------------------------------------------
  // 【四】★部品は 色を 持たない
  // -------------------------------------------------------------------------
  console.log("【四】色は 親から 受け取る");
  const 部品 = readCode("components", "OpsIcon.jsx");
  t(部品.includes('stroke="currentColor"'), "線は currentColor");
  t(部品.includes('fill="none"'), "塗りません");
  t(!/#[0-9A-Fa-f]{3,6}"/.test(部品), "色を 直に 書いて いない");
  t(部品.includes('aria-hidden="true"'), "読み上げには 出しません（★名は 隣の 字）");
  // ★★知らない 名で 空の 四角を 出さない こと。
  t(部品.includes("if (!中身) return null"), "知らない 名は 何も 出さない");
  t(m.iconBody("しらない") === null, "知らない 名は null");

  // -------------------------------------------------------------------------
  // 【五】★塗りつぶさない（★§3-6）
  // -------------------------------------------------------------------------
  console.log("【五】選んだ ときに 塗りつぶさない");
  t(!/background/.test(部品), "しるしの 部品が 地を 持って いない");

  console.log(`\n○ ${ok}　✗ ${ng}`);
  process.exit(ng === 0 ? 0 : 1);
})();
