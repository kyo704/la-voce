#!/usr/bin/env node

// ============================================================================
// ★名簿の 月額の 下限は 9,800円。★12,800円に 戻さない こと
//
//   ★★2026年9月13日、★坂本さんが 12,800円 → **9,800円** に 改めました（★案A）。
//     ★`lib/orgRoster.js` に、★いつ どう 変わったかまで 書いて あります。
//
//   ★★2026-09-16、★新しい 見本（正式版）が 届きました。
//     ★★その 中の 料金が、★**12,800円に 戻って いました**。
//       ★新しい 版は、★9月13日の お決めより **前**の 土台から 作られて います。
//     ★★見本の 側は それで かまいません。★見本は 見本 です。
//       ★★けれど、★次に 突き合わせる 人が
//         ★「見本が 12,800 だから、★コードも 直そう」と するかも しれません。
//       ★★それは **お決めを 巻き戻す** ことに なります。
//
//   ★★この 見張りは、★その 手を 止めます。
//     ★★戻す ときは、★坂本さんの 新しい お決めと 日付を 添えて、
//       ★この 見張りを 書き換えて ください。★黙って 通さない ため の 1枚です。
//
//   ★★おなじ 形が もう 1つ あります ── 個人の 年額。
//     ★5,800円 → **4,800円**（★新しい 見本も 4,800円 です。★一致して います）。
// ============================================================================

const fs = require("fs");
const path = require("path");

const { readCode, loadLib } = require("./_source");

let ok = 0, ng = 0;
function t(cond, label) {
  if (cond) { console.log("  ✓ " + label); ok++; }
  else { console.log("  ✗ " + label); ng++; }
}

// ★★`readCode` は **リポジトリからの 道のり**を 受けます。★絶対の 道では ありません。
//   ★★はじめ 絶対の 道を 渡して、★道が 二重に 繋がりました。
const L = path.join(__dirname, "..", "..", "lib");

function code(name) {
  if (!fs.existsSync(path.join(L, name))) {
    console.log("★★ありません: lib/" + name);
    console.log("　★数えません。★止まります。");
    process.exit(1);
  }
  return readCode("lib", name);
}

console.log("① 名簿の 月額（★2026-09-21・裁定155／確定 第3版）");
const roster = code("orgRoster.js");
// ★★字ではなく、★**使われて いる 数**を 見ます。
//   ★★覚え書きには 古い 数が 出て きます（★いつ どう 変わったかの 記録）。
//     ★だから `readCode` で 覚え書きを 落としてから 数えます。
// ★★★2026-09-21、★下限が 1本 から 2本に なりました（★裁定155 §3）──
//   ★教室 月2,980円（★6〜30人・定額）／★学校 下限 月12,800円（★31人〜）
//   ★★9,800円は 無く なりました。★12,800円に 戻った のでは ありません。
//     ★★6〜30人が 教室に 分かれ、★31人からが 学校 です。
t(/\b2980\b/.test(roster), "2980（教室）が コードに ある");
t(/\b12800\b/.test(roster), "12800（学校の 下限）が コードに ある");
t(!/\b9800\b/.test(roster), "★9800 は コードに ない（★覚え書きを 除いて）");



console.log("\n② 個人の 年額（★しらべる 5,800 → 4,800）");
// ★★★2026-09-21、★この 節の 見方を 変えました。
//   ★★もとは「5800 が lib の どこにも 無い」でした。
//   ★★裁定155 §3 で **よそおい（年）5,800円** が 入りました。
//     ★★同じ 数が、★別の ものの 値段 として 戻って きました。
//   ★★★数を 追い出すのを やめ、★**どの 品が いくらか** を 見ます。
//     ★★12,800円に 2つの 意味が あった のと 同じ 形 です。
let found4800 = false;
for (const f of fs.readdirSync(L).filter((x) => x.endsWith(".js"))) {
  if (/\b4800\b/.test(readCode("lib", f))) found4800 = true;
}
t(found4800, "4800 が lib の どこかに ある");

console.log("\n③ 見本と 食い違う ことを、忘れない ため の 覚え");
// ★★見本は 12,800 に 戻って います。★こちらは 戻しません。
//   ★★この 1行が 落ちたら、★どちらかが 動いた しるし です。
const MIHON = path.join(__dirname, "..", "..", "docs", "design", "pack-final",
  "00-動く見本-PC・iPad（運営）.html");
if (fs.existsSync(MIHON)) {
  const m = fs.readFileSync(MIHON, "utf8");
  const mi12 = /下限 12,800円/.test(m);
  const mi9 = /下限 9,800円/.test(m);
  console.log("  ・見本は " + (mi12 ? "12,800円" : mi9 ? "9,800円" : "（読めません）"));
  if (mi9) {
    console.log("  ★★見本が 9,800円に なりました。★食い違いは 解けて います。");
    console.log("  ★★この 節を 消して かまいません。");
  }
  t(true, "見本を 読めました（★合否には しません）");
} else {
  console.log("  ★見本が ありません。★この 節は 飛ばします。");
}

// ★★★式に 通して 確かめる ところは、★数え終わる のを 待ちます（★2026-09-21）。
//   ★★はじめ 上の ほうに 置きました。★中の 数が 1つも 数えられず、
//     ★★「すべて 通りました（6）」と 出ました。★見張りが 何も 見て いません。
//   ★★★待たない 非同期は、★通った ことに なります。★いちばん 危ない 形 です。
// ★★★数を 覚えません。★式に 通して 確かめます（★確定 第3版 §2 の 早見表）。
//   ★★字が 在るだけ では、★使われて いる とは 言えません。
const 早見 = [[5, 0], [6, 2980], [30, 2980], [31, 12800], [32, 12800],
  [60, 24000], [100, 35000], [216, 75000], [300, 75000], [500, 125000]];
(async () => {
  const R = await loadLib("lib", "orgRoster.js");
  for (const [n, yen] of 早見) {
    t(R.monthlyFee(n) === yen, `${n}人 → ${yen}円（いま ${R.monthlyFee(n)}）`);
  }
  // ★教室の 年額は 月額×10 では ありません（★裁定155 §3）。
  t(R.yearlyFee(20) === 29800, `教室の 年額 29,800円（いま ${R.yearlyFee(20)}）`);
  // ★導入支援は 100人以上（★裁定155 Q4・第3版 §4）。
  t(R.setupFee(50) === 0, "50人には 導入支援を かけない");
  t(R.setupFee(100) === R.SETUP_FEE, "100人から 導入支援");
  // ★表示は 税込（★裁定155 §3・第3版 §6）。
  t(R.PRICE_TAX_LABEL === "税込", `表示は 税込（いま ${R.PRICE_TAX_LABEL}）`);
  // ★★★しらべる は 4,800円 の まま（★2026-09-07 の 決め）。
  //   ★★よそおい の 5,800円 と 取り違えない こと。★別の 品 です。
  const P = await loadLib("lib", "plans.js");
  t(P.planByKey("annual").priceYen === 4800, "しらべる（年）は 4,800");
  t(P.YEARLY_PRICE_155.shiraberu === 4800, "裁定155 の しらべる も 4,800");
  t(P.YEARLY_PRICE_155.yosooi === 5800, "★よそおい は 5,800（★別の 品）");
  console.log(ng === 0 ? `\n★すべて 通りました（${ok}）` : `\n★${ng} 件 落ちました`);
  process.exit(ng === 0 ? 0 : 1);
})();
