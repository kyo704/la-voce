// ============================================================================
// ★まとめて つける（★裁定 その91・2026-09-18）
//
//   ★★★R4 ── ★一括を 採ります（★見本が 正）。
//     ★★20人を 1人ずつ 押すのは 20回 です。
//     ★★実際は「ほとんど 出席、★休みは 1〜2人」です。
//   ★★★保存する まで 台帳に 書きません。★保存の 前に 数を 出します。
//   ★★★一度も 触らずに 保存できます（★先生の ご判断 です）。★止めません。
//
//   ★★見る の は 6つ。
//     ★【一】★下書き（★白い 方 だけ 出席に する）
//     ★【二】★変わった ぶん だけ 書く
//     ★【三】★数（★率を 出さない ／「18/20」の 形に しない）
//     ★【四】★戻り道 2つ ／ 一覧の 中を 移る ／ 学年
//     ★【五】★率が どこにも 出て いない（★裁定 その90 Q3）
//     ★【六】★出席順の 並べ替えが 無い（★裁定 その90 Q4）
// ============================================================================

const { readCode, readRaw, loadLib } = require("./_source");

let ok = 0, ng = 0;
function t(cond, label) {
  if (cond) { ok++; console.log("  ○ " + label); }
  else { ng++; console.log("  ✗ " + label); }
}

(async () => {
  const A = await loadLib("lib", "opsAttendance.js");
  const 一覧 = readCode("components", "OpsAttendanceBulk.jsx");
  const 一覧生 = readRaw("components", "OpsAttendanceBulk.jsx");
  const 一人 = readCode("components", "OpsAttendance.jsx");
  const 親 = readRaw("components", "VocalTracker.jsx");

  const L = [
    { id: "a", student_id: "s1" },
    { id: "b", student_id: "s2", attendance: "absent" },
    { id: "c", student_id: "s3" }
  ];

  // -------------------------------------------------------------------------
  // 【一】★下書き
  // -------------------------------------------------------------------------
  console.log("【一】下書き（★白い 方 だけ 出席に）");
  const d = A.draftOf(L);
  t(d.a === "came" && d.c === "came", "★白い 方は 出席");
  t(d.b === "absent", "★★もとから ついて いる ものを 上書きしない");
  t(A.DEFAULT_MARK === "came", "既定は 出席");
  t(A.isBulk(L) === true, "2つ 以上 なら まとめて");
  t(A.isBulk([L[0]]) === false, "1つ なら 1人ずつ");
  t(A.isBulk([]) === false, "0でも 落ちない");
  // ★★同じ ものを もう一度 押すと 白に 戻る こと。
  const d2 = A.setDraft(d, "a", "came");
  t(d2.a === undefined, "★同じ ものを 押すと 白に 戻る");
  t(A.setDraft(d, "a", "absent").a === "absent", "ちがう ものを 押すと 変わる");

  // -------------------------------------------------------------------------
  // 【二】★変わった ぶん だけ 書く
  // -------------------------------------------------------------------------
  console.log("【二】変わった ぶん だけ 書く");
  const 変 = A.changedRows(L, d);
  t(変.length === 2, "白かった 2つ だけ（" + 変.length + "）");
  t(!変.some((x) => x.lesson.id === "b"), "★★もとから ついて いる ものを 書かない");
  t(A.changedRows(L, A.draftOf(L)).length === 2, "同じ 答え");
  // ★★何も 変えて いなければ 0。
  const そのまま = {};
  L.forEach((l) => { if (l.attendance) そのまま[l.id] = l.attendance; });
  t(A.changedRows(L, そのまま).length === 0, "★触って いなければ 0");
  t(A.saveWord(L, そのまま) === "変えた ところは ありません", "★その ときの 字");
  t(A.saveWord(L, d) === "2人を つけました", "★つけた 数を 出す");

  // -------------------------------------------------------------------------
  // 【三】★数
  // -------------------------------------------------------------------------
  console.log("【三】数（★率を 出さない）");
  const 行 = A.bulkCountLine(L, d);
  t(行 === "3人中、出席2／休み1", "見本の 形（" + 行 + "）");
  t(!/\//.test(行.replace("／", "")), "★「18/20」の 形に して いない");
  t(!/%|％/.test(行), "★率を 出して いない");
  // ★★0の ものを 並べない こと。
  t(!行.includes("休講"), "★0の ものを 並べない");

  // -------------------------------------------------------------------------
  // 【四】★戻り道・移り・学年
  // -------------------------------------------------------------------------
  console.log("【四】戻り道 2つ ／ 移り ／ 学年");
  t(A.BACK_LABEL === "もどる" && A.BACK_MINE_LABEL === "自分の レッスンを 見る",
    "戻り道の 字が 2つ");
  t(一覧.includes("BACK_MINE_LABEL") && 一人.includes("BACK_MINE_LABEL"),
    "★どちらの 画面にも ある");
  // ★★★つけられない ときも 戻れる こと（★裁定 その91 R1）。
  t(一覧生.indexOf("BACK_MINE_LABEL") < 一覧生.indexOf("!つけられる"),
    "★つけられない 判じより 先に 戻り道が ある");
  // ★★一覧の 中を 移る。
  t(A.nextOf(L, "a").id === "b" && A.prevOf(L, "b").id === "a", "次と 前");
  t(A.nextOf(L, "c") === null && A.prevOf(L, "a") === null, "★端では 出さない");
  t(A.positionWord(L, "b") === "3人中 2人目", "いま 何人目");
  t(A.positionWord(L, "しらない") === "", "★知らない ものは 空");
  t(一人.includes("positionWord"), "1人の 画面が 使って いる");
  // ★★学年（★場所は 出しません）。
  t(一人.includes("gradeOf") && 一覧.includes("gradeOf"), "学年を 出して いる");
  t(!一人.includes("place") && !一覧.includes("place"), "★場所を 出して いない（★列が ありません）");

  // -------------------------------------------------------------------------
  // 【五】★率が どこにも 出て いない（★裁定 その90 Q3）
  // -------------------------------------------------------------------------
  console.log("【五】率が どこにも 出て いない");
  const 見る = ["lib/opsAttendance.js", "components/OpsAttendance.jsx",
    "components/OpsAttendanceBulk.jsx", "lib/todayBand.js"];
  見る.forEach((f) => {
    // ★★★禁じた 言葉を **並べて いる** ところを 数えません（★2026-09-18）。
    //   ★★`lib/todayBand.js` は `FORBIDDEN_WORDS` に「達成」を 持って います。
    //   ★★あれは「書かない」と 決めた 一覧 です。★画面に 出る 字では ありません。
    //   ★★★この 蔵で 何度も 踏んだ 罠 です（★`_source.js` の 註 ── 5回目の 形）。
    //     ★★コメントを 外しても、★**文字列として 書かれた 禁止語**は 残ります。
    const 中 = readCode(...f.split("/"))
      .replace(/export const FORBIDDEN_WORDS = Object\.freeze\(\[[\s\S]*?\]\);/, "");
    ["％", "パーセント", "達成", "出席率"].forEach((w) => {
      t(!中.includes(w), f + " に「" + w + "」が ない");
    });
  });
  // ★★道具の 較正。
  t("出席率 80%".includes("出席率"), "★わざとの 1件を 見つけられる");
  // ★★★外しすぎて いない こと ── ★一覧の 外の「達成」は 見つかる こと。
  t("const a = \"達成\";".replace(/export const FORBIDDEN_WORDS = Object\.freeze\(\[[\s\S]*?\]\);/, "")
    .includes("達成"), "★一覧の 外なら 見つけられる");

  // -------------------------------------------------------------------------
  // 【六】★出席順の 並べ替えが 無い（★裁定 その90 Q4）
  // -------------------------------------------------------------------------
  console.log("【六】出席順の 並べ替えが 無い");
  t(!/sort\([^)]*attendance/.test(一覧), "★出席で 並べ替えて いない");
  t(!/sort\(/.test(一覧), "★そもそも 並べ替えて いない（★渡された 順の まま）");
  t(!/sort\(/.test(一人), "★1人の 画面も 同じ");

  // -------------------------------------------------------------------------
  // 【七】★呼ぶ 側
  // -------------------------------------------------------------------------
  console.log("【七】呼ぶ 側");
  t(親.includes("<OpsAttendanceBulk"), "まとめての 画面を 出して いる");
  t(親.includes("isBulk(同じコマ) && !opsAttendanceOne"), "2つ 以上 なら まとめて");
  t(親.includes("onOpenOne={(l) => setOpsAttendanceOne(l.id)}"), "★お名前を 押すと 1人へ");
  t(親.includes("const onOpsSaveBulk = async"), "まとめて 書く 道が ある");
  t(/\.update\(patch\)\.eq\("id", r\.lesson\.id\)\.select\("id"\)/.test(親),
    "★`.select()` が 付いて いる（★静かな 0行を 作らない）");
  // ★★★開く たびに、★前の「1人」を 持ち越さない こと。
  t((親.match(/setOpsAttendanceOne\(null\)/g) || []).length >= 4,
    "★開く／閉じる ときに 消して いる");

  console.log(`\n○ ${ok}　✗ ${ng}`);
  process.exit(ng === 0 ? 0 : 1);
})();
