// ============================================================================
// ★見張り ── ★出欠を つける（★裁定 その79 ／ 見本 `P_shukketsu`）
//
//   ★★測る のは 5つ です。
//     ★一 ★3つの 字を、★自分で 持って いない（★`lib/todayBand.js` から）
//     ★二 ★つけられない とき、★★お名前を 出して いない
//     ★三 ★代わりに つける とき、★必ず お伝えして いる
//     ★四 ★「よろしいですか」を 出して いない（★押した その場で 変わる）
//     ★五 ★注を 減らして いない
// ============================================================================

const assert = require("assert");
const { readCode, readRaw, loadLib } = require("./_source");

let 数 = 0;
function ok(cond, 名) {
  数 += 1;
  assert.ok(cond, "★落ちました ── " + 名);
  console.log("  ok  " + 名);
}

(async () => {
  const A = await loadLib("lib", "opsAttendance.js");
  const T = await loadLib("lib", "todayBand.js");
  const 束 = readCode("lib", "opsAttendance.js");
  const 画面 = readCode("components", "OpsAttendance.jsx");
  const 生画面 = readRaw("components", "OpsAttendance.jsx");

  // ------------------------------------------------------------------------
  // ★一 ★字を 自分で 持って いない
  // ------------------------------------------------------------------------
  // ★★★同じ 物か を くらべて いました。★別々に 読み込む ので、★別の 物に なります。
  //   ★★見るのは「同じ 中身か」と「自分で 作って いないか」の 2つ です。
  ok(A.MARKS.map((m) => m.key + ":" + m.label).join(",")
    === T.ATTENDANCE.map((m) => m.key + ":" + m.label).join(","),
    "3つの 字が lib/todayBand.js と 同じ");
  ok(/from "@\/lib\/todayBand"/.test(束), "束が lib/todayBand.js から 取って いる");
  // ★★★はじめ「出席／休講 の 字が 1つも 無い こと」を 見て いました。★落ちました。
  //   ★★注に「休講＝その回を しなかった とき」と 書いて あります。
  //   ★★★あれは **説明** です。★札の 字の 写しでは ありません。
  //   ★★見るのは「3つを **自分で 作って いないか**」です。
  ok(!/label:\s*"(出席|休み|休講)"/.test(束), "束が 3つを 自分で 作って いない");
  ok(!/"出席"|"休講"|"休み"/.test(画面), "画面も 書き写して いない");
  ok(A.countLine([{ attendance: "came" }, { attendance: null }])
    === "出席 1　休み 0　休講 0　まだ 1", "数の 1行（見本の 形）");

  // ------------------------------------------------------------------------
  // ★二 ★つけられない とき、★お名前を 出さない
  // ------------------------------------------------------------------------
  ok(A.LOCKED_LINES.some((x) => x.includes("お名前も 出しません")),
    "「お名前も 出しません」と 書いて ある");
  // ★★★描く 順を 見ます。★つけられない 枝の 中に、★お名前が 無い こと。
  const 枝 = 画面.slice(画面.indexOf("!つけられる ?"), 画面.indexOf(") : ("));
  ok(!/nameOf\(l\.student_id\)/.test(枝),
    "★つけられない ときの 枝に、★お名前が 出て いない");
  ok(/nameOf\(l\.student_id\)/.test(画面), "つけられる ときは お名前を 出す");

  // ------------------------------------------------------------------------
  // ★三 ★代わりに つける とき
  // ------------------------------------------------------------------------
  ok(A.isActingFor({ teacher_id: "t" }, "u", ["shukketsu"]) === true,
    "ほかの 先生の レッスンなら『代わりに』");
  ok(A.isActingFor({ teacher_id: "u" }, "u", ["shukketsu"]) === false,
    "自分の レッスンなら ちがう");
  ok(A.isActingFor({ teacher_id: "t" }, "u", []) === false,
    "できことが 無ければ、そもそも つけられない");
  ok(/お名前が 残ります/.test(A.ACTING_NOTE), "名が 残る ことを 言って いる");
  ok(/ACTING_NOTE/.test(画面), "画面が それを 出して いる");

  // ------------------------------------------------------------------------
  // ★四 ★確認を 出さない
  // ------------------------------------------------------------------------
  ok(!/confirm\(|よろしいですか/.test(画面),
    "「よろしいですか」を 出して いない（★押した その場で 変わる）");
  ok(/取り消す/.test(生画面), "かわりに「取り消す」が ある");

  // ------------------------------------------------------------------------
  // ★五 ★注を 減らして いない
  // ------------------------------------------------------------------------
  ["担当して いる 人", "代わって", "体調・記録の 中身", "休講", "確認を 出しません"]
    .forEach((語) => {
      数 += 1;
      assert.ok(A.NOTES.some((x) => x.includes(語)),
        "★落ちました ── 注から 消えて います: " + 語);
    });
  console.log("  ok  注の 5つが そろって いる");
  ok(A.NOTES.some((x) => x.includes("生徒の 欠席に なりません")),
    "★休講は 生徒の 欠席に ならない、と 書いて ある");

  // ★★次の 方へ ── ★まだ つけて いない 方 だけ。
  const ls = [{ id: 1, attendance: "came" }, { id: 2, attendance: null }, { id: 3, attendance: null }];
  ok(A.nextUnmarked(ls, 2).id === 3, "次は、まだ つけて いない 方");
  ok(A.nextUnmarked([{ id: 1, attendance: "came" }], 1) === null,
    "みんな つけ終わって いれば、次は 無い");

  console.log("\n★" + 数 + "件 通りました ── 出欠を つける");
})().catch((e) => { console.error(e.message || e); process.exit(1); });
