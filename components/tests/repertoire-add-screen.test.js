#!/usr/bin/env node
// STRIP: A
// ============================================================================
// ★曲を 足す（★見本 SC['曲を足す']）の 見張り ── 2026-09-24
//
//   ★★この 1枚で 見つけた ものは、★見た目の ちがいでは ありません。
//     ★★① 打てるのに 書く 先が 無い 欄が ありました（★本番の 予定）。
//     ★★② 名前を 変えると 曲が 2つに 割れて いました。
//     ★★③ 見本の 断り 6つの うち、★3つは 仕組みと ちがいます。
//
//   ★★だから この 見張りは「字が あるか」では なく、
//     ★★**書いた 約束が 本当か** を 見ます。
// ============================================================================

const assert = require("assert");
const { readRaw, readCode } = require("./_source");

let 数 = 0;
function 見る(名, f) { f(); 数 += 1; console.log("  ○ " + 名); }

const 画 = readRaw("components", "NotesV2.jsx");
const 字 = readCode("components", "NotesV2.jsx");      // ★覚え書きを 外した もの
const vt = readCode("components", "VocalTracker.jsx");
const 棚 = readCode("lib", "repertoireLog.js");

見る("較正 ── ★読めて いる", () => {
  assert.ok(画.includes("曲を 足す"), "★見出しが 読めて いません");
  assert.ok(vt.includes("onAddRepertoire"), "★受け手が 読めて いません");
});

// ---------------------------------------------------------------------------
// ★① 打てるのに 消える 欄を 作らない
// ---------------------------------------------------------------------------
見る("★書く 先の 無い 欄を 置かない（★本番の 予定）", () => {
  // ★★欄も、★受け渡しも、★どちらも 無い こと。
  assert.ok(!/placeholder="れい：11月20日/.test(字), "★欄が 戻って います");
  assert.ok(!/editing\.performance/.test(字), "★欄の 値を 持って います");
  assert.ok(!/performance: (draft|item)\.performance/.test(字), "★受け渡しが 残って います");
  // ★★受け手の 側にも 無い こと。
  assert.ok(!/status, performance \}/.test(vt), "★受け手が まだ 受け取って います");
});

見る("★0日目の 約束を 書かない", () => {
  // ★★0日目を 決めるのは 記録用紙の 印 です。★曲の 台帳では ありません。
  assert.ok(/本番でそろえる の 0日目/.test(readCode("lib", "recordSheets.js")),
    "★較正 ── ★0日目の 決めが 見つかりません");
  assert.ok(!/0日目/.test(字), "★曲を 足す に 0日目の 約束を 書いて います");
});

// ---------------------------------------------------------------------------
// ★② 名前を 変えても、★曲が 2つに 割れない
// ---------------------------------------------------------------------------
見る("★名前を 変えたら、★先に つなぎ直す", () => {
  assert.ok(/previousName/.test(字), "★開いた ときの 名前を 渡して いません");
  assert.ok(/previousName/.test(vt), "★受け手が 受け取って いません");
  // ★★つなぎ直しが **先** で ある こと。★あとでは 割れた ままに なります。
  const i = vt.indexOf("handleRenameRepertoire(前, key)");
  const j = vt.indexOf("handleSaveRepertoireFields(key");
  assert.ok(i > 0, "★つなぎ直しを 呼んで いません");
  assert.ok(j > i, "★つなぎ直しが あと に なって います");
  // ★★つなぎ直せなかった ときは 書かない こと。
  assert.ok(/つないだ === false\) return \{ ok: false/.test(vt),
    "★つなぎ直せなくても 書いて います");
});

見る("★約束の 字が、★仕組みと 合って いる", () => {
  // ★★「名前では なく 中で つないでいます」── ★これは 嘘 です。★書かない こと。
  assert.ok(!/名前では なく 中で つない/.test(字), "★仕組みと ちがう 字を 書いて います");
  // ★★書いて よいのは、★していること だけ です。
  assert.ok(/記録の 中の 曲名も、いっしょに 書き換えます/.test(字),
    "★していることを 書いて いません");
  // ★★そして 本当に 書き換えて いる こと。
  assert.ok(/it\.repertoireName, from\) \? \{ \.\.\.it, repertoireName: to \}/.test(vt),
    "★記録の 中の 曲名を 書き換えて いません");
});

// ---------------------------------------------------------------------------
// ★③ 嘘に なる 断りを 書かない
// ---------------------------------------------------------------------------
見る("★たなの 約束を 書かない", () => {
  // ★★たなは **記録** から 出ます。★足しただけ では 並びません。
  assert.ok(/repertoireLog\(entries\)/.test(棚), "★較正 ── ★たなの 出どころが ちがいます");
  assert.ok(!/たな.{0,12}にも 並びます/.test(字), "★足しただけ で 並ぶ、と 書いて います");
});

見る("★どれか 1つ、と 書かない", () => {
  // ★★この 道は 曲名が 要ります。★見本の 中でも 食いちがって います。
  assert.ok(/if \(!key\) return \{ ok: false, why: "曲名が ありません" \}/.test(vt),
    "★曲名が 要る ことが、★字に なって いません");
  assert.ok(!/どれか 1つ.{0,10}あれば 入ります/.test(字), "★どれか 1つ、と 書いて います");
});

見る("★入らなかった わけを、★その場に 出す", () => {
  // ★★「まだ足せていません」だけ だと、★送れなかった ように 読めます。
  assert.ok(/res && res\.why/.test(字), "★わけを 受け取って いません");
  assert.ok(/why \+ "。開いたままにしています。"/.test(字), "★わけを 出して いません");
});

見る("★書いた 断りは、★本当の もの だけ", () => {
  ["ぜんぶ 空のままでは 入りません",
    "記録は ついてきます",
    "出来ばえ・点数の 欄は ありません"].forEach((w) =>
      assert.ok(字.includes(w), "★" + w + " が ありません"));
});

console.log("\n★" + 数 + "つ 通りました。");
