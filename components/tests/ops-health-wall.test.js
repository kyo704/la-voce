// ============================================================================
// ★見張り ── ★健康の 線（★上から 2番目）
//
//   ★出どころ docs/design/pack-final/00-動く見本-PC・iPad（運営）.html
//            `<div class="wall"><i></i>…`
//   ★裁定    2026-09-18・⑨（★坂本さん／Opus）
//            「最下部だと、稟議で 見る 学長・事務長が 見ません」
//
//   ★★測る のは 4つ です。
//     ★一 ★字が 見本と 同じ か（★書き写しません。★見本から 引きます）
//     ★二 ★**上から 2番目** に 出て いるか（★中身より 先、★上の帯より 後）
//     ★三 ★設定 だけで なく、★どの 帯でも 出るか（★帯で 出し分けて いないか）
//     ★四 ★もとの 場所（設定の いちばん 下）から 消えて いるか
//          ★★2か所に 出ると、★片方だけ 変わります。
// ============================================================================

const assert = require("assert");
const fs = require("fs");
const path = require("path");
const { readCode, readRaw, loadLib } = require("./_source");

const ROOT = path.join(__dirname, "..", "..");
const 見本の道 = path.join(ROOT, "docs/design/pack-final/00-動く見本-PC・iPad（運営）.html");

let 数 = 0;
function ok(cond, 名) {
  数 += 1;
  assert.ok(cond, "★落ちました ── " + 名);
  console.log("  ok  " + 名);
}

(async () => {
  // ------------------------------------------------------------------------
  // ★★較正 ── ★見本に その 線が 無ければ 止まります。
  // ------------------------------------------------------------------------
  if (!fs.existsSync(見本の道)) {
    console.error("★止まりました ── 見本が ありません: " + 見本の道);
    process.exit(1);
  }
  const 見本 = fs.readFileSync(見本の道, "utf8");
  const m = /<div class="wall"><i><\/i>([^<]+)<\/div>/.exec(見本);
  assert.ok(m, "★止まりました ── 見本に 健康の 線が ありません。★測りの ほうを 疑って ください。");
  const 見本の字 = m[1].trim();

  const L = await loadLib("lib", "opsShell.js");

  // ------------------------------------------------------------------------
  // ★一 ★字が 見本と 同じ か
  // ------------------------------------------------------------------------
  ok(L.HEALTH_WALL_LINE === 見本の字,
    "字が 見本と 同じ（" + 見本の字.slice(0, 18) + "…）");
  ok(Array.isArray(L.HEALTH_WALL_ITEMS) && L.HEALTH_WALL_ITEMS.length === 3,
    "たどりつけない ものは 3つ");
  ok(L.HEALTH_WALL_ITEMS.every((x) => /生徒の/.test(x)),
    "3つ とも 生徒の もの");

  // ------------------------------------------------------------------------
  // ★二 ★上から 2番目 か
  // ------------------------------------------------------------------------
  //   ★★注も 位置に 数えます（★`readRaw`）。★並びを 見る とき、注も 場所 です。
  const 殻 = readRaw("components", "OpsShell.jsx");
  const 上の帯 = 殻.indexOf("‹ もどる");
  const 線 = 殻.indexOf("HEALTH_WALL_LINE}");
  const 中身 = 殻.indexOf("renderTab ? renderTab(cur)");
  ok(上の帯 > 0 && 線 > 上の帯, "線は 上の帯 より 後");
  ok(中身 > 0 && 線 < 中身, "線は 中身 より 先");

  // ------------------------------------------------------------------------
  // ★三 ★帯で 出し分けて いないか
  // ------------------------------------------------------------------------
  //   ★★`cur === "settings"` の ような 条件の 中に 入って いたら、
  //     ★★設定 でしか 出ません。★約束は どの 帯にも 要ります。
  const 線の前 = 殻.slice(0, 線);
  const 直前 = 線の前.slice(-400);
  ok(!/cur\s*===/.test(直前), "帯（cur）で 出し分けて いない");
  ok(!/role\s*===/.test(直前), "役割で 出し分けて いない");

  // ------------------------------------------------------------------------
  // ★四 ★もとの 場所から 消えて いるか
  // ------------------------------------------------------------------------
  //   ★★注は 数えません（★`readCode`）。★注には 移した 経緯を 書いて あります。
  const 設定 = readCode("components", "OpsSettings.jsx");
  ok(!/NOT_HERE/.test(設定), "設定に NOT_HERE が 残って いない");
  ok(!/この画面から 見られないもの/.test(設定),
    "設定の いちばん 下の カードが 消えて いる");
  ok(!/生徒の 声の記録/.test(設定), "3つの 字が 設定に 残って いない");

  // ★★字を 持つ ところは 1つ だけ。
  const 殻のコード = readCode("components", "OpsShell.jsx");
  ok(!殻のコード.includes(見本の字),
    "画面が 字を 書き写して いない（lib から 取る）");

  console.log("\n★" + 数 + "件 通りました ── 健康の 線");
})().catch((e) => { console.error(e.message || e); process.exit(1); });
