  t(/\{onCompose && mayPost\(\{ perms, isAnnouncement: true \}\) \? \(\s*\n\s*<p style=\{\{ \.\.\.small, marginTop: 6 \}\}>\{EMPTY_HOW\}/.test(生),
    "★2行目は 書ける 方に だけ 出す");
