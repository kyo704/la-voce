// ============================================================================
// ★出席の 回数（★裁定 その90 §2 §4・2026-09-18）
//
//   ★★★出さない もの ── ★率（％）／「9 / 12」の 形／出席順／色の 警告。
//   ★★★「12回目 / 30回」は 例外 です。★みなさん 同じ 進み ぐあい で、
//     ★★その方の 成績では ありません（★見本の とおり）。
// ============================================================================

const { readCode, readRaw, loadLib } = require("./_source");

let ok = 0, ng = 0;
function t(cond, label) {
  if (cond) { ok++; console.log("  ○ " + label); }
  else { ng++; console.log("  ✗ " + label); }
}

(async () => {
  const A = await loadLib("lib", "attendanceCount.js");
  const L = [
    { attendance: "came" }, { attendance: "absent" },
    { attendance: "canceled" }, { attendance: null }, { attendance: "came" }
  ];

  // -------------------------------------------------------------------------
  // 【一】★数え方
  // -------------------------------------------------------------------------
  console.log("【一】数え方（★裁定 その90 §2）");
  t(A.heldCount(L) === 3, "行われた 回 ＝ 出席 ＋ 休み（3）");
  t(A.cameCount(L) === 2, "出席した 回（2）");
  // ★★★休講を 数えません。★しなかった 回 です。
  t(!A.COUNTED_AS_HELD.includes("canceled"), "★休講を「行われた」に 入れない");
  // ★★まだ つけて いない ものも 数えません。
  t(A.heldCount([{ attendance: null }]) === 0, "★白い ものを 数えない");
  t(A.heldCount(null) === 0 && A.cameCount(null) === 0, "★渡されなくても 落ちない");

  // -------------------------------------------------------------------------
  // 【二】★出さない もの
  // -------------------------------------------------------------------------
  console.log("【二】出さない もの（★裁定 その90 §4）");
  t(A.cameWord(L) === "出席 2", "★数 だけ（" + A.cameWord(L) + "）");
  t(!/\//.test(A.cameWord(L)), "★「9 / 12」の 形に しない");
  t(!/%|％/.test(A.cameWord(L)), "★率を 出さない");
  // ★★★進み ぐあい だけ、★スラッシュを 使います（★みなさん 同じ 数 だから）。
  t(A.progressWord(12, 30) === "12回目 / 30回", "進み ぐあい（見本の とおり）");
  t(A.progressWord(12, 0) === "12回目", "★年間の 回数が 無ければ 分母を 出さない");
  t(A.progressWord(12, null) === "12回目", "★同じ");
  t(A.progressWord(null, 30) === "", "★数が 無ければ 空");
  // ★★率の 字が どこにも 無い こと。
  const 元 = readCode("lib", "attendanceCount.js");
  // ★★★「率を 出しません」と **言って いる 1行** を 数えません（★2026-09-18）。
  //   ★★`FORBIDDEN_WORDS` の ときと 同じ 形 です。★この 蔵で 何度も 踏みました。
  //   ★★禁じた 語を 名指しする 字は、★コメントを 外しても 残ります。
  const 断り以外 = 元.split(A.NO_RATE_LINE).join("");
  ["％", "パーセント", "達成", "出席率"].forEach((w) => {
    t(!断り以外.includes(w), "lib に「" + w + "」が ない（★断りの 1行を 除く）");
  });
  // ★★道具の 較正 ── ★外しすぎて いない こと。
  t(("率 80％").split(A.NO_RATE_LINE).join("").includes("％"),
    "★断りの 外なら 見つけられる");
  t(A.NO_RATE_LINE.includes("回数だけ"), "★率を 出さない、と 書いて ある");

  // -------------------------------------------------------------------------
  // 【三】★足りない 見込みの 印
  // -------------------------------------------------------------------------
  console.log("【三】★印（★色を 使わない）");
  t(A.SHORT_MARK === "★", "印は ★");
  // ★★★残りを ぜんぶ 出ても 足りない とき だけ。
  t(A.looksShort({ came: 5, held: 12, total: 30, need: 24 }) === true,
    "★残り18を 足しても 23。★足りない 見込み");
  t(A.looksShort({ came: 11, held: 12, total: 30, need: 24 }) === false,
    "★まだ 取り返せる ときは 出さない");
  t(A.looksShort({ came: 5, held: 12, total: 30, need: 0 }) === false,
    "★線が 決まって いなければ 出さない");
  t(A.looksShort({ came: 5 }) === false, "★数が そろわなければ 出さない");
  t(A.SHORT_NOTE.includes("責める"), "★責める ものでは ない、と 書いて ある");
  // ★★★色で 示して いない こと。
  t(!/C\.curtain|C\.rust|色/.test(元.replace(/★色を 使いません[^\n]*/g, "")),
    "★色の 名を 持って いない");

  // -------------------------------------------------------------------------
  // 【四】★並べ替えない
  // -------------------------------------------------------------------------
  console.log("【四】並べ替えない（★裁定 その90 §4）");
  const 行 = [{ n: 3 }, { n: 1 }, { n: 2 }];
  t(JSON.stringify(A.inGivenOrder(行)) === JSON.stringify(行), "★渡された 順の まま");
  t(A.inGivenOrder(行) !== 行, "★元を 触らない（写しを 返す）");
  t(!/\.sort\(/.test(元), "★lib に 並べ替えが ない");

  console.log(`\n○ ${ok}　✗ ${ng}`);
  process.exit(ng === 0 ? 0 : 1);
})();
