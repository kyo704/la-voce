const assert = require("assert");
const fs = require("fs");
const path = require("path");
const { readCode, readRaw } = require("./_source");

const ROOT = path.join(__dirname, "..", "..");
let 数 = 0, 落 = [];
function 見る(名, f) {
  try { f(); 数 += 1; console.log("  ○ " + 名); }
  catch (e) { 落.push(名 + " …… " + e.message); console.log("  ✗ " + 名 + " …… " + e.message); }
}

// ★画面の 紙（★束・道具・試しは 外します）。
const 画面 = fs.readdirSync(path.join(ROOT, "components"))
  .filter((f) => f.endsWith(".jsx"))
  .filter((f) => !["UiV2.jsx"].includes(f));

console.log("★A群 共通5点 ── ★画面 " + 画面.length + "枚");

// ---------------------------------------------------------------------------
// ① 信号色
// ---------------------------------------------------------------------------
//   ★★この 家の 色は `lib/tokens.js` が 持ちます。★画面で 作りません。
//   ★★生の 赤・黄・緑を 書いて いないか を 見ます。
見る("① 信号色を 画面で 作って いない", () => {
  const 悪 = [];
  画面.forEach((f) => {
    const s = readCode("components", f);
    // ★★`#f00` `#00ff00` `red` `green` `yellow` のような 生の 色。
    const m = s.match(/#(?:f{2}0{4}|0{2}f{2}0{2}|0{4}f{2}|ff0000|00ff00|ffff00)\b/gi) || [];
    const w = s.match(/color:\s*"(red|green|yellow|lime|crimson)"/gi) || [];
    if (m.length || w.length) 悪.push(f + "（" + [...m, ...w].slice(0, 2).join(" ") + "）");
  });
  assert.strictEqual(悪.length, 0, "★生の 信号色: " + 悪.join(" "));
});

// ---------------------------------------------------------------------------
// ② 点数・順位
// ---------------------------------------------------------------------------
//   ★★★「点」は 採点の 束では 正しい 言葉 です（★裁定105）。
//     ★★だから 採点の 画面は 外します。★ほかで 出て いないかを 見ます。
見る("② 点数・順位を 出して いない（★採点の 画面を 除く）", () => {
  const 採点 = ["OpsSaiten.jsx", "OpsTenIreru.jsx", "OpsEvalItems.jsx", "JuryPanel.jsx", "JuryLayout.jsx"];
  // ★★★2026-09-24 ── ★言葉を 数えるだけ では 足りません でした。
  //   ★★この 家は「★順位には 使って いません」「★偏差値は 含めず」と、
  //     ★★**出さない ことを 書いて** います。★あれは 約束の 字 です。
  //   ★★★だから 40字の うちに 打ち消しが あれば 通します。
  //     ★無ければ、★それは 本当に 出して いる ところ です。
  const 打消 = /(使って いません|使っていません|含めず|含めません|出しません|出さない|ありません)/;
  const 悪 = [];
  画面.filter((f) => !採点.includes(f)).forEach((f) => {
    const s = readCode("components", f);
    ["順位", "ランキング", "偏差値", "平均との差"].forEach((w) => {
      let i = -1;
      while ((i = s.indexOf(w, i + 1)) >= 0) {
        if (!打消.test(s.slice(i, i + 40))) { 悪.push(f + "（" + w + "）"); break; }
      }
    });
  });
  assert.strictEqual(悪.length, 0, "★順位の 言葉: " + 悪.join(" "));
});

// ---------------------------------------------------------------------------
// ③ 「あと○日」の 催促
// ---------------------------------------------------------------------------
//   ★★2026-09-10 に 消した ものです。★戻って いないかを 見ます。
//   ★★日付で 書く のは よい ── ★「あと」が 付く ものだけ を 見ます。
見る("③ ごほうびへの「あと○」が 無い", () => {
  // ★★★2026-09-24 ── ★禁じられて いるのは「★**ごほうび**への あと○」です。
  //   ★★坂本さんの わけ …「★思いがけず もらえる ことが 大事。★数えさせると
  //     ★そこへ 向かう 作業に なる」（★2026-09-10）。
  //   ★★★だから 見るのは、★点・品物・ひつじ に つながる「あと」だけ です。
  //     ★「あと 2つ」（★書く 手順の 残り）や「あと 3着」（★入れ物の 空き）は、
  //       ★ごほうびでは ありません。★2026-09-24 に 1枚ずつ 見て 確かめました。
  const ごほうび = /(点|ポイント|品|もの|ひつじ|羊|服|ごほうび|もらえ)/;
  const 悪 = [];
  画面.forEach((f) => {
    const s = readCode("components", f);
    // ★★★はじめ `s.search` で 書いて いました ── ★いつも **先頭の 1件** しか
    //   ★見ません でした（★2026-09-24 の 目盛り合わせで 出ました）。
    //   ★★1枚の 紙に いくつ あっても、★ぜんぶ 見ます。
    const re = /(あと|残り)\s*\{?[0-9０-９a-zA-Z_.]/g;
    let m;
    while ((m = re.exec(s)) !== null) {
      const 窓 = s.slice(Math.max(0, m.index - 30), m.index + 40);
      if (ごほうび.test(窓)) 悪.push(f + "（" + 窓.replace(/\s+/g, " ").slice(0, 34) + "）");
    }
  });
  assert.strictEqual(悪.length, 0, "★ごほうびへの 催促: " + 悪.join(" ／ "));
});

