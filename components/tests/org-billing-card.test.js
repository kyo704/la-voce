// ============================================================================
// ★見張り ── ★お支払いの 箱（★裁定 その74 ／ 追補・2026-09-18）
//
//   ★★測る のは 5つ です。
//     ★一 ★値の 無い 行を 出さない（★「—」を 置かない）
//     ★二 ★見本の 5行 のうち、★出せない 2行が 記録されて いる
//     ★三 ★登録番号が 無い ときは、★必ず 断りを 出す
//     ★四 ★直す 札を 置いて いない（★押した 先が ありません・§8⑤）
//     ★五 ★画面が 字を 書き写して いない
// ============================================================================

const assert = require("assert");
const { readCode, readRaw, loadLib } = require("./_source");

let 数 = 0;
function ok(cond, 名) {
  数 += 1;
  assert.ok(cond, "★落ちました ── " + 名);
  console.log("  ok  " + 名);
}

(async () => {
  const B = await loadLib("lib", "orgBilling.js");

  // ------------------------------------------------------------------------
  // ★一 ★値の 無い 行を 出さない
  // ------------------------------------------------------------------------
  ok(B.billingRows(null, 0).length === 0, "台帳に 行が 無ければ、★1行も 出さない");
  ok(B.billingRows({}, 0).length === 0, "中身が 空なら、★1行も 出さない");

  const 全部 = B.billingRows({
    atesaki_name: "坂本 響", method: "card", next_billing_date: "2026-09-25"
  }, 67900);
  ok(全部.length === 3, "そろって いれば 3行（いま " + 全部.length + "）");
  ok(全部.every((r) => r.value && String(r.value).trim() !== ""),
    "どの 行にも 値が ある");
  ok(!全部.some((r) => /—|不明|未設定/.test(String(r.value))),
    "「—」も「不明」も 置いて いない");

  // ★★1つだけ ある とき、★その 1行 だけ。
  const 片方 = B.billingRows({ method: "invoice" }, 0);
  ok(片方.length === 1 && 片方[0].key === "method", "ある ぶん だけ 出す");
  ok(片方[0].value === "請求書", "支払い方法の 言い方（invoice → 請求書）");

  // ★★金額は 渡された もの を 使う。★ここで 数えない。
  const 額あり = B.billingRows({ next_billing_date: "2026-09-25" }, 67900);
  ok(/67,900円/.test(額あり[0].value), "金額は 渡された ものを 出す");
  const 額なし = B.billingRows({ next_billing_date: "2026-09-25" }, 0);
  ok(!/円/.test(額なし[0].value), "0円の ときは 金額を 出さない");

  // ------------------------------------------------------------------------
  // ★二 ★出せない 2行が 記録されて いる
  // ------------------------------------------------------------------------
  ok(B.MISSING_ROWS.length === 2, "出せない 行は 2つ（いま " + B.MISSING_ROWS.length + "）");
  B.MISSING_ROWS.forEach((m) => {
    数 += 1;
    assert.ok(m.why && m.column,
      "★落ちました ── 「" + m.label + "」に わけか 列の 名が ありません");
  });
  console.log("  ok  どちらにも、★わけと 列の 名が ある（引き金）");

  // ------------------------------------------------------------------------
  // ★三 ★登録番号が 無い ときの 断り
  // ------------------------------------------------------------------------
  ok(B.hasInvoiceNo(null) === false, "行が 無ければ 登録番号も 無い");
  ok(B.hasInvoiceNo({ invoice_no: "" }) === false, "空の 字は 番号では ない");
  ok(B.hasInvoiceNo({ invoice_no: "T1234567890123" }) === true, "番号が あれば true");
  ok(/適格請求書では ありません/.test(B.NOT_QUALIFIED_INVOICE), "断りの 字");
  // ★★★2026-09-19 ── ★登録の ご予定が ある ことも 書きます。
  //   ★★「いま 無い」は 消しません。★足すだけ です。
  ok(/登録を 予定/.test(B.NOT_QUALIFIED_INVOICE), "★予定も 書いて いる");
  // ★★★日づけを 書きません（★決まって いない ことを 約束に しません）。
  ok(!/月曜|\d+月\d+日/.test(B.NOT_QUALIFIED_INVOICE), "★日づけを 書いて いない");

  const 画面 = readRaw("components", "OpsSettings.jsx");
  ok(/!hasInvoiceNo\(billing\)/.test(画面), "番号が 無い ときに 断りを 出して いる");

  // ------------------------------------------------------------------------
  // ★四 ★直す 札を 置いて いない
  // ------------------------------------------------------------------------
  const コード = readCode("components", "OpsSettings.jsx");
  ["支払い方法を 変える", "宛先を 変える", "領収書を 出す"].forEach((札) => {
    数 += 1;
    assert.ok(!コード.includes(札),
      "★落ちました ── 押した 先の 無い 札が あります: " + 札);
  });
  console.log("  ok  直す 札を 置いて いない（★押した 先が ありません・§8⑤）");

  // ------------------------------------------------------------------------
  // ★五 ★画面が 字を 書き写して いない
  // ------------------------------------------------------------------------
  ok(!コード.includes("クレジットカード"), "支払い方法の 言い方を 書き写して いない");
  ok(!コード.includes("ご請求の 宛先"), "行の 名を 書き写して いない");
  ok(/billingRows\(/.test(コード), "並びは lib が 作る");

  console.log("\n★" + 数 + "件 通りました ── お支払いの 箱");
})().catch((e) => { console.error(e.message || e); process.exit(1); });
